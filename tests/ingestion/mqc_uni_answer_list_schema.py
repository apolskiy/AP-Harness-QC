from typing import Any

import pytest

from cmn.case_steps import step
from ingestion.schemas import GoldenRuleSet

from tests.evaluation.answer_list_support import declared_list_payload as _declared

pytestmark = pytest.mark.unit


class TestMQCAnswerListDeclaration:
    """G12: a declared list says its style, one bound, and how a question is judged."""

    def MQC_ING_UNI_111357_a_declared_answer_list_loads_with_its_fields(
        self, sample_rule_payload: dict[str, Any]
    ) -> None:
        """A numbered count and a bulleted ceiling each load as declared.

        Design: ``tier1_ingestion.md`` section 3.5, G12.

        Args:
            sample_rule_payload (dict): Minimal rule payload, carrying a rubric.

        Returns:
            None
        """
        step(1, "load a rule declaring four numbered items")
        numbered = GoldenRuleSet.from_dict(
            _declared(sample_rule_payload, style="numbered", count=4)
        ).answer_list
        assert (
            numbered.style, numbered.count, numbered.max_count,
            numbered.clarification_rubric.threshold,
        ) == ("numbered", 4, None, 3.0)

        step(2, "load a rule declaring at most three bullets")
        bulleted = GoldenRuleSet.from_dict(
            _declared(sample_rule_payload, style="bulleted", max_count=3)
        ).answer_list
        assert (bulleted.style, bulleted.count, bulleted.max_count) == ("bulleted", None, 3)

        step(3, "load a rule declaring none")
        assert GoldenRuleSet.from_dict(sample_rule_payload).answer_list is None

    def MQC_ING_UNI_111358_an_answer_list_of_an_unregistered_style_is_refused(
        self, sample_rule_payload: dict[str, Any]
    ) -> None:
        """A style other than numbered or bulleted is refused, naming the field.

        Design: ``tier1_ingestion.md`` section 3.5, G12.

        Args:
            sample_rule_payload (dict): Minimal rule payload.

        Returns:
            None
        """
        step(1, "load a rule declaring a lettered list")
        with pytest.raises(ValueError, match="QC_DATA_INVARIANT_VIOLATION.*style"):
            GoldenRuleSet.from_dict(_declared(sample_rule_payload, style="lettered", count=2))

        step(2, "load a rule carrying a key the declaration does not have")
        with pytest.raises(KeyError):
            GoldenRuleSet.from_dict(
                _declared(sample_rule_payload, style="numbered", count=2, ordered=True)
            )

    def MQC_ING_UNI_111359_both_bounds_neither_or_a_numbered_ceiling_is_refused(
        self, sample_rule_payload: dict[str, Any]
    ) -> None:
        """Exactly one bound of one or more, and a count where the list is numbered.

        Design: ``tier1_ingestion.md`` section 3.5, G12.

        Args:
            sample_rule_payload (dict): Minimal rule payload.

        Returns:
            None
        """
        refused = {
            "both bounds": {"style": "bulleted", "count": 3, "max_count": 3},
            "neither bound": {"style": "bulleted"},
            "a numbered ceiling": {"style": "numbered", "max_count": 4},
            "a count of zero": {"style": "numbered", "count": 0},
            "a ceiling of zero": {"style": "bulleted", "max_count": 0},
        }
        step(1, "load each shape and collect any that loads")
        loaded = []
        for label, declaration in refused.items():
            try:
                GoldenRuleSet.from_dict(_declared(sample_rule_payload, **declaration))
            except ValueError as error:
                assert "QC_DATA_INVARIANT_VIOLATION" in str(error), str(error)
            else:
                loaded.append(label)
        assert not loaded, f"declarations loaded that G12 refuses: {loaded}"

    def MQC_ING_UNI_111360_an_answer_list_without_a_clarification_rubric_is_refused(
        self, sample_rule_payload: dict[str, Any]
    ) -> None:
        """A declaration admits a clarification, so it carries a rubric to judge one.

        Design: ``tier1_ingestion.md`` section 3.5, G12.

        Args:
            sample_rule_payload (dict): Minimal rule payload.

        Returns:
            None
        """
        step(1, "load a rule whose list declares no clarification rubric")
        with pytest.raises((KeyError, ValueError), match="clarification_rubric"):
            GoldenRuleSet.from_dict(
                {**sample_rule_payload, "answer_list": {"style": "numbered", "count": 2}}
            )

        step(2, "load one whose clarification rubric has no criteria")
        with pytest.raises(ValueError):
            GoldenRuleSet.from_dict(_declared(
                sample_rule_payload, style="numbered", count=2,
                clarification_rubric={"criteria": [], "threshold": 3.0},
            ))

    def MQC_ING_UNI_111361_a_scope_beyond_the_declared_count_is_refused(
        self, sample_rule_payload: dict[str, Any]
    ) -> None:
        """An assertion reading item 3 of a two-item list reads what cannot exist.

        Design: ``tier1_ingestion.md`` section 3.5, G12.

        Args:
            sample_rule_payload (dict): Minimal rule payload.

        Returns:
            None
        """
        def scoped(item: int) -> dict[str, Any]:
            return {
                "assertion_id": "A_SCOPED",
                "kind": "contains",
                "parameters": {"value": "10", "scope": {"list_item": item}},
                "taxonomy_code": "QC_LLM_CONTEXT_OMISSION",
                "severity": "violation",
            }

        step(1, "load a two-item list whose assertion reads item 2, the last that exists")
        assert GoldenRuleSet.from_dict({
            **_declared(sample_rule_payload, style="numbered", count=2),
            "assertions": [scoped(2)],
        }).answer_list.count == 2

        step(2, "load the same list whose assertion reads item 3")
        with pytest.raises(ValueError, match="QC_DATA_INVARIANT_VIOLATION.*A_SCOPED"):
            GoldenRuleSet.from_dict({
                **_declared(sample_rule_payload, style="numbered", count=2),
                "assertions": [scoped(3)],
            })
