"""Unit cases for validating the answer list a golden rule declares.

Created: 2026-11-04
Last updated: 2026-11-04

Its cases check ``GoldenRuleSet`` in :mod:`ingestion.schemas`. A declared list
loads with its style, its bound and its clarification rubric; an unregistered
style, both bounds, neither bound, a ceiling on a numbered list and a bound
below one are refused, as is a declaration without a clarification rubric and
a rule scoping an assertion to an item beyond the declared count. The
evaluation pipeline later reads the declaration to decide which route an
answer takes.

Specified by ``docs/design/tier1_ingestion.md`` section 3.5, invariant G12,
and ``docs/design/tier3_evaluation.md`` section 5.5.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.
"""

