from typing import Any

import pytest

from cmn.case_steps import step
from ingestion.schemas import GoldenRuleSet

pytestmark = pytest.mark.unit


class TestMQCPlantedScoreDeclaration:
    """G9 and G10: a fingerprint the judge could return honestly proves nothing."""

    def MQC_ING_UNI_111352_a_planted_score_at_an_anchored_level_is_refused(
        self, sample_rule_payload: dict[str, Any]
    ) -> None:
        """A 5 is anchored by the sample rubric, so planting it is refused.

        Design: ``tier1_ingestion.md`` section 3.6, G9.

        Args:
            sample_rule_payload (dict): Minimal rule payload, anchoring 1, 3 and 5.

        Returns:
            None
        """
        step(1, "load a response-only rule planting a score its rubric anchors")
        with pytest.raises(ValueError, match="QC_DATA_INVARIANT_VIOLATION") as raised:
            GoldenRuleSet.from_dict({
                **sample_rule_payload,
                "judge_response_only": True,
                "rubric": {**sample_rule_payload["rubric"], "planted_score": 5},
            })

        step(2, "read whether the refusal names the field")
        assert "planted_score" in str(raised.value), str(raised.value)

