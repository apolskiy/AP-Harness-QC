"""Unit cases for the rubric a declared adversarial task may carry.

Created: 2026-09-26
Last updated: 2026-10-21

Its cases check invariant R6 in :mod:`ingestion.integrity` and invariant G8 in
:mod:`ingestion.schemas`: a declared adversarial task paired with a rubric rule
is refused at ingest with the remedy named, unless that rule declares
``judge_response_only``, and a rule declaring ``judge_response_only`` without a
rubric is refused.

A declared adversarial task reaches no judge unless its rule judges the answer
alone, so without these refusals a rubric on one would make a case that always
fails for a reason visible nowhere in its result.

Specified by ``docs/design/tier1_ingestion.md`` sections 3.5, 6.6 and 13.1.
Moved from ``mqc_uni_schemas.py`` on 2026-10-21, when that module reached the
900-line runway (``code-style.md`` section 5.1).

A failure here is **not a model finding**, so the module carries no priority marker, per
``framework-rules.md`` section 3.3.
"""

