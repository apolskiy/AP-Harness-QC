from typing import Any

import pytest

from cmn.case_steps import step
from ingestion.schemas import GoldenRuleSet
from tests.evaluation.pipeline_support import GRADING_CHECK, PASSAGE_CHECK

pytestmark = pytest.mark.unit


class TestMQCRelayForbiddenDeclaration:
    """G13: a rule forbidding the relay carries the check that fails one."""

    def MQC_ING_UNI_111362_a_forbidden_relay_without_a_passage_check_is_refused(
        self, sample_rule_payload: dict[str, Any]
    ) -> None:
        """A rule declaring relay_forbidden and no passage check is refused; with one it loads.

        Design: ``tier1_ingestion.md`` section 3.5, G13.

        Args:
            sample_rule_payload (dict): Minimal rule payload, carrying a rubric.

        Returns:
            None
        """
        forbidden = {
            **sample_rule_payload, "judge_response_only": True, "relay_forbidden": True,
        }

        step(1, "load a rule forbidding the relay and carrying no assertion")
        with pytest.raises(ValueError, match="QC_DATA_INVARIANT_VIOLATION") as raised:
            GoldenRuleSet.from_dict(forbidden)

        step(2, "read whether the refusal names the declaration and the check it needs")
        message = str(raised.value)
        assert "relay_forbidden" in message and "source_phrase_absent" in message, message

        step(3, "load the same rule carrying the grading check alone")
        with pytest.raises(ValueError, match="QC_DATA_INVARIANT_VIOLATION"):
            GoldenRuleSet.from_dict({**forbidden, "assertions": [GRADING_CHECK]})

        step(4, "load the same rule carrying a passage check beside the grading check")
        loaded = GoldenRuleSet.from_dict(
            {**forbidden, "assertions": [GRADING_CHECK, PASSAGE_CHECK]}
        )
        assert loaded.relay_forbidden, "the rule loaded without its declaration"
