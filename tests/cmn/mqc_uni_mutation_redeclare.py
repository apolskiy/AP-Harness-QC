"""Unit precondition for re-declaring an audited module whose code did not change.

Created: 2026-10-21
Last updated: 2026-10-21

The case here checks ``redeclare`` in ``tools/mutation_redeclare.py`` against a
scratch repository holding one audited module with one declared survivor: a
docstring and comment edit is re-declared, with the new digest written and the
survivor moved to the line its point now sits on; a code edit is refused and
leaves the manifest as it was; and a module reading exactly as its own unparse
is refused, being the damage the full-text digest exists for.

A prose edit to an audited module would otherwise cost a full mutation audit,
so this decides whether that edit costs a command or an hour. A failure here is
**not a model finding**, so the module carries no priority marker.

Specified by ``docs/design/harness_test_taxonomy.md`` section 15.14.
"""

