import ast
from pathlib import Path

import pytest

from cmn.case_steps import step
from cmn.mutation_guard import module_digest
from tools.mutation_audit import MutationRefusal, declared_survivors
from tools.mutation_redeclare import redeclare

from tests.cmn.file_dates_support import git_in
from tests.cmn.mutation_tool_support import (
    MODULE, POINTED, committed_survivor_tree,
)

pytestmark = pytest.mark.unit

# THE DECLARED SURVIVOR'S LINE ONCE THREE COMMENT LINES SIT ABOVE IT.
_MOVED = "line 9: 2 to 3"
_PROSE = "# a note the audit cannot see\n# and another\n"


class TestMQCMutationRedeclare:
    """A prose edit costs a command; a code edit still costs an audit."""

    def MQC_CMN_UNI_112422_a_prose_edit_is_redeclared_and_a_code_edit_refused(
        self, tmp_path: Path
    ) -> None:
        """Prose is re-declared with its survivor moved; code and a stripped module are refused.

        Design: ``harness_test_taxonomy.md`` section 15.14.

        Returns:
            None
        """
        module = committed_survivor_tree(tmp_path)
        manifest = tmp_path / "config" / "mutation_survivors.yaml"
        edited = POINTED.replace('"""A module', _PROSE + '"""A module', 1).replace(
            '    """Return the value doubled',
            '    # why it doubles\n    """Return the value doubled',
            1,
        )

        step(1, "add comments to the module and re-declare it")
        module.write_text(edited, encoding="utf-8", newline="\n")
        redeclare(tmp_path, MODULE)
        entry = declared_survivors(manifest)[MODULE]
        assert entry["digest"] == module_digest(edited) and [
            accepted["mutation"] for accepted in entry["accepted"]
        ] == [_MOVED], f"the prose edit was not re-declared with its survivor moved: {entry}"

        step(2, "change the module's code and re-declare it against the committed declaration")
        git_in(tmp_path, "checkout", "--quiet", "--", "config")
        before = manifest.read_text(encoding="utf-8")
        module.write_text(edited.replace("value * 2", "value * 3"), encoding="utf-8", newline="\n")
        refused = ""
        try:
            redeclare(tmp_path, MODULE)
        except MutationRefusal as error:
            refused = str(error)
        assert "code changed" in refused and manifest.read_text(encoding="utf-8") == before, (
            f"a code edit was re-declared, or the manifest moved: {refused!r}"
        )

        step(3, "write the module as its own unparse and re-declare it")
        module.write_text(ast.unparse(ast.parse(edited)), encoding="utf-8", newline="\n")
        with pytest.raises(MutationRefusal, match="unparse"):
            redeclare(tmp_path, MODULE)
