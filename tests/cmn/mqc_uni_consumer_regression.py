from pathlib import Path

import pytest
import yaml

from cmn.case_steps import step
from cmn.grouping import story
from tests.cmn.consumer_regression_support import FAILED as _FAILED
from tests.cmn.consumer_regression_support import PASSED as _PASSED
from tests.cmn.consumer_regression_support import PASSW as _PASSW
from tests.cmn.consumer_regression_support import SKIPPED as _SKIPPED
from tests.cmn.consumer_regression_support import junit_report as _report
from tools.consumer_regression import case_outcomes, changed_outcomes, main

pytestmark = pytest.mark.unit

_WORKFLOW = (Path(__file__).resolve().parents[2] / ".github" / "workflows"
             / "regress-consumers-on-merge.yml")


class TestMQCConsumerRegression:
    """A harness change fails the consumer regression when it changes an outcome."""

    @story("An outcome the change did not alter is the consumer's")
    def MQC_CMN_UNI_112529_an_outcome_matching_the_one_before_the_change_is_not_ours(
        self, tmp_path: Path
    ) -> None:
        """A model failure, a passw and a cascade skip on both sides leave the job green.

        Design: ``harness_ci_pipeline.md`` section 3B.3.1.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        cases = (_PASSED.format(name="a"), _PASSW.format(name="b"),
                 _FAILED.format(name="c", code="QC_LLM_SOURCE_ALTERATION"),
                 _SKIPPED.format(name="d"))
        before = _report(tmp_path / "before.xml", *cases)
        after = _report(tmp_path / "after.xml", *cases)

        step(1, "read the four outcomes with their codes")
        assert case_outcomes(before) == {
            "c::a": "passed", "c::b": "passw QC_LLM_MATCH_MISCOMPUTED",
            "c::c": "failed QC_LLM_SOURCE_ALTERATION",
            "c::d": "skipped QC_HARNESS_DEPENDENCY_UNMET"}, case_outcomes(before)

        step(2, "compare matching reports and find no change")
        assert not changed_outcomes(before, after), changed_outcomes(before, after)

        step(3, "exit 0 on matching reports")
        assert main([str(before), str(after)]) == 0

    @story("An outcome the change altered is the harness's")
    def MQC_CMN_UNI_112530_a_pass_turned_into_a_model_failure_is_reported(
        self, tmp_path: Path
    ) -> None:
        """A failure carrying a model code is ours when the case passed before the change.

        Design: ``harness_ci_pipeline.md`` section 3B.3.1.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        before = _report(tmp_path / "before.xml", _PASSED.format(name="a"))
        after = _report(tmp_path / "after.xml",
                        _FAILED.format(name="a", code="QC_LLM_SOURCE_ALTERATION"))

        step(1, "report the case by its outcome before and after the change")
        assert changed_outcomes(before, after) == [
            "a: passed before the change, failed QC_LLM_SOURCE_ALTERATION after it"
        ], changed_outcomes(before, after)

        step(2, "exit 1 on a changed outcome")
        assert main([str(before), str(after)]) == 1

    @story("An outcome the change altered is the harness's")
    def MQC_CMN_UNI_112531_a_changed_warning_or_failure_code_is_reported(
        self, tmp_path: Path
    ) -> None:
        """A passw turned pass, and a failure whose code changed, are both changes.

        Design: ``harness_ci_pipeline.md`` section 3B.3.1.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        before = _report(tmp_path / "before.xml", _PASSW.format(name="a"),
                         _FAILED.format(name="b", code="QC_LLM_SOURCE_ALTERATION"))
        after = _report(tmp_path / "after.xml", _PASSED.format(name="a"),
                        _FAILED.format(name="b", code="QC_HARNESS_FIXTURE_STALE"))
        changed = changed_outcomes(before, after)

        step(1, "report the passw that became a pass")
        assert ("a: passw QC_LLM_MATCH_MISCOMPUTED before the change, passed after it"
                in changed), changed

        step(2, "report the failure whose code changed")
        assert ("b: failed QC_LLM_SOURCE_ALTERATION before the change, "
                "failed QC_HARNESS_FIXTURE_STALE after it" in changed), changed

    @story("An outcome the change altered is the harness's")
    def MQC_CMN_UNI_112532_a_case_run_on_one_side_only_is_reported(
        self, tmp_path: Path
    ) -> None:
        """A case skipped on one side, or absent from one, changed with the harness.

        Design: ``harness_ci_pipeline.md`` section 3B.3.1.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        before = _report(tmp_path / "before.xml", _PASSED.format(name="a"),
                         _PASSED.format(name="b"))
        after = _report(tmp_path / "after.xml", _SKIPPED.format(name="a"),
                        _PASSED.format(name="c"))
        changed = changed_outcomes(before, after)

        step(1, "report the case skipped after the change")
        assert ("a: passed before the change, skipped QC_HARNESS_DEPENDENCY_UNMET "
                "after it" in changed), changed

        step(2, "report the case each side lacks")
        assert ("b: passed before the change, absent after it" in changed
                and "c: absent before the change, passed after it" in changed), changed

    @story("A comparison with nothing to compare refuses")
    def MQC_CMN_UNI_112533_a_missing_or_empty_report_refuses(self, tmp_path: Path) -> None:
        """A report absent, unreadable or holding no case verified nothing, and exits 4.

        Design: ``harness_ci_pipeline.md`` section 3B.3.1.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        present = _report(tmp_path / "present.xml", _PASSED.format(name="a"))
        empty = _report(tmp_path / "empty.xml")
        broken = tmp_path / "broken.xml"
        broken.write_text("<testsuites><testsuite>", encoding="utf-8")

        step(1, "refuse a baseline that was never written")
        assert main([str(tmp_path / "absent.xml"), str(present)]) == 4

        step(2, "refuse a candidate holding no case")
        assert main([str(present), str(empty)]) == 4

        step(3, "refuse a report that will not parse")
        with pytest.raises(ValueError, match="QC_HARNESS_PARSER_ERROR"):
            case_outcomes(broken)

    @story("The workflow compares against the harness before the change")
    def MQC_CMN_UNI_112534_the_workflow_replays_the_parent_and_compares_both(self) -> None:
        """The gate step reads two reports, and the first is replayed on the parent commit.

        Design: ``harness_ci_pipeline.md`` section 3B.3.1.

        Returns:
            None
        """
        steps = yaml.safe_load(_WORKFLOW.read_text(encoding="utf-8"))["jobs"]["verify"]["steps"]
        runs = [str(entry.get("run", "")) for entry in steps]
        gate = [run.split() for run in runs if "consumer_regression.py" in run]

        step(1, "find one gate step naming a baseline and a candidate report")
        assert len(gate) == 1 and len(gate[0]) == 4, gate

        step(2, "find the baseline report written by a replay against the parent harness")
        assert any(f"--junitxml={gate[0][2].removeprefix('consumer/')}" in run
                   and "baseline" in run for run in runs), runs

        step(3, "find the parent harness checked out for that replay")
        assert any("HEAD^" in run for run in runs), runs
