        """The gate step reads two reports, and the first is replayed on the parent commit.

        Design: ``harness_ci_pipeline.md`` section 3B.3.1.

        Returns:
            None
        """
        steps = yaml.safe_load(_WORKFLOW.read_text(encoding="utf-8"))["jobs"]["verify"]["steps"]
