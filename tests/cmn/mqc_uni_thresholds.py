"""Unit preconditions for the threshold domain and its boundaries.

Covers `MQC_CMN_UNI_112052` through `112059`, inventoried in
``docs/design/cmn_verdict_and_cli.md`` section 10.38.

**Split from ``mqc_uni_verdict.py`` on 2026-10-13**, which holds the nine
verdict rules and what each one decides. The subject here is narrower and
different: what a threshold is allowed to be, and which side of a threshold
its own value falls on. Section 8.2 is the table these cases assert.

**A boundary is stated at the threshold, never near it.** Four of the seven
live thresholds were exercised only on one side until these were written, so a
comparison that had drifted from `>` to `>=` would have left the suite green.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.
"""

