class TestMQCThresholdBoundaries:
    """Each live threshold, stated at exactly its own value.

    Which side the value falls on is tabulated in
    ``docs/design/cmn_verdict_and_cli.md`` section 8.2, and it is not the same
    side for every threshold.
    """

    def MQC_CMN_UNI_112052_p0_share_at_exactly_the_ceiling_is_permitted(self) -> None:
        """V7 fires above its ceiling and not at it.

        Four P0 definitions in forty is 10.0 percent, the ceiling exactly. The
        denominator is chosen so the share lands on the value rather than near
        it, which is the whole of what this case establishes: `112027` already
        covers a quarter of the suite at P0.

        Returns:
            None
        """
        observations = distribution_suite(at_zero=4, at_one=0, total=40)

        report = evaluate_distribution(observations, Thresholds())
        assert report.p0_share == pytest.approx(0.10), (
            "the population was not built to land on the ceiling, so whatever "
            "this case reports it is not a boundary"
        )

        result = verdict(observations, VerdictConfig(), TODAY)
        assert "V7" not in result.breached_rules, (
            "a P0 share exactly at the ceiling breached V7, so the comparison "
            "has drifted from above-the-ceiling to at-or-above it"
        )
        assert result.green

        # AND ONE MORE BREACHES IT, so the case is not passing because the rule
        # is unreachable at this population size.
        above = distribution_suite(at_zero=5, at_one=0, total=40)
        assert evaluate_distribution(above, Thresholds()).p0_share == pytest.approx(0.125)
        assert "V7" in verdict(above, VerdictConfig(), TODAY).breached_rules

    def MQC_CMN_UNI_112053_p1_share_decides_on_both_sides_of_its_ceiling(self) -> None:
        """V8 had no case of any kind until 2026-10-13.

        So this one carries both sides rather than only the boundary: eight P1
        definitions in forty is 20.0 percent and passes, nine is 22.5 percent
        and breaches. The P0 count stays at zero so no other ceiling can be
        the one that fired.

        Returns:
            None
        """
        at_ceiling = distribution_suite(at_zero=0, at_one=8, total=40)
        assert evaluate_distribution(at_ceiling, Thresholds()).p1_share == pytest.approx(0.20)

        result = verdict(at_ceiling, VerdictConfig(), TODAY)
        assert "V8" not in result.breached_rules
        assert result.green

        above = distribution_suite(at_zero=0, at_one=9, total=40)
        assert evaluate_distribution(above, Thresholds()).p1_share == pytest.approx(0.225)

        breached = verdict(above, VerdictConfig(), TODAY)
        assert breached.breached_rules == ["V8"], (
            f"a P1 share above the ceiling reported {breached.breached_rules}, "
            f"so either V8 never fires or another rule is firing for it"
        )

    def MQC_CMN_UNI_112054_combined_share_at_exactly_the_ceiling_is_permitted(self) -> None:
        """All three distribution ceilings sit on their values at once.

        Four P0 and eight P1 in forty is 10.0, 20.0 and 30.0 percent, which is
        every ceiling exactly. **The combined ceiling is reachable only this
        way**: ten percent plus twenty percent is thirty, so a combined share
        above the ceiling always carries one of the other two above its own,
        and `112028` is where that is asserted.

        Returns:
            None
        """
        observations = distribution_suite(at_zero=4, at_one=8, total=40)

        report = evaluate_distribution(observations, Thresholds())
        assert report.p0_share == pytest.approx(0.10)
        assert report.p1_share == pytest.approx(0.20)
        assert report.combined_share == pytest.approx(0.30)

        result = verdict(observations, VerdictConfig(), TODAY)
        assert not result.breached_rules, (
            f"a suite sitting on all three ceilings reported "
            f"{result.breached_rules}, so a ceiling excludes its own value"
        )
        assert result.green

    def MQC_CMN_UNI_112055_distribution_returns_a_verdict_at_exactly_the_minimum(
        self,
    ) -> None:
        """Thirty case definitions is the population, not one above it.

        `112026` states the abstention at twenty-nine. This states that the
        check resumes at thirty, which is the half a comparison drifting by one
        would break silently: an abstaining check reports no breach, so a run
        over an inflated corpus would go green and say nothing.

        Returns:
            None
        """
        observations = distribution_suite(at_zero=0, at_one=0, total=30)

        report = evaluate_distribution(observations, Thresholds())
        assert report.case_definitions == 30
        assert report.verdict_returned is True, (
            "the check abstained at exactly the minimum, so the ceilings are "
            "unenforced on the smallest population they were meant to govern"
        )
        assert report.p0_share == pytest.approx(0.0)

        # AND THE SHARES ARE DECIDED, not merely computed: a corpus at the
        # minimum breaches when it should.
        inflated = distribution_suite(at_zero=4, at_one=0, total=30)
        assert evaluate_distribution(inflated, Thresholds()).p0_share > 0.10
        assert "V7" in verdict(inflated, VerdictConfig(), TODAY).breached_rules


class TestMQCThresholdDomain:
    """An impossible standard is refused rather than applied.

    Designed in ``docs/design/cmn_verdict_and_cli.md`` section 8.1, which
    records what each of these values did before the refusal existed.
    """

    @pytest.mark.parametrize("field_name", sorted(RATE_FIELDS))
    @pytest.mark.parametrize("value", [-1.0, 0.0, 1.5, 100.0])
    def MQC_CMN_UNI_112056_a_rate_outside_the_unit_interval_is_refused(
        self, field_name: str, value: float
    ) -> None:
        """Every rate, at each of the four values that reached a verdict.

        **Zero and negative one are the dangerous pair.** A `pass_floor` at
        either turned every run green at exit 0 with no breach recorded, which
        is worse than the error a string produced because the run reported a
        result. `100.0` is the slip for someone who meant ninety percent.

        **Zero is refused for the ceilings too.** It leaves no band, and the
        rule it reaches for is V1.

        Args:
            field_name (str): The rate under test.
            value (float): The value outside the domain.

        Returns:
            None
        """
        with pytest.raises(ValueError) as refusal:
            Thresholds(**{field_name: value})

        assert field_name in str(refusal.value), (
            "the refusal did not name the field, so it points at the "
            "comparison rather than at the edit that caused it"
        )
        assert repr(value) in str(refusal.value)

    def MQC_CMN_UNI_112057_a_non_numeric_threshold_is_refused(self) -> None:
        """A stored artifact can carry a string, and one broke the run.

        `'ninety'` was accepted by construction and raised `TypeError` part-way
        through evaluating the pass rate, so the harness broke while measuring
        rather than before it started.

        **`True` is refused although it is an `int`.** A `pass_floor` of
        `True` is a floor of 1.0, which is a real standard and certainly not
        what was meant.

        Returns:
            None
        """
        for value in ("ninety", "0.9", None, True, [0.9]):
            with pytest.raises(ValueError):
                Thresholds(pass_floor=value)

        for value in ("thirty", None, True, 2.5):
            with pytest.raises(ValueError):
                Thresholds(distribution_minimum=value)

    @pytest.mark.parametrize("field_name", sorted(COUNT_FIELDS))
    @pytest.mark.parametrize("value", [0, -1, -5])
    def MQC_CMN_UNI_112058_a_population_count_below_one_is_refused(
        self, field_name: str, value: int
    ) -> None:
        """A count of zero or less names no population.

        A `distribution_minimum` of zero would mean the check never abstains,
        which is the opposite of what the field is for, and a quarantine window
        of zero days would expire every entry on the day it was written.

        Args:
            field_name (str): The count under test.
            value (int): The value below the domain.

        Returns:
            None
        """
        with pytest.raises(ValueError) as refusal:
            Thresholds(**{field_name: value})

        assert field_name in str(refusal.value)

        # AND EVERY FIELD IS REGISTERED, so a threshold added later cannot be
        # unchecked by default. That default is how this module came to be
        # needed.
        declared = {entry.name for entry in dataclasses.fields(Thresholds())}
        assert declared == RATE_FIELDS | COUNT_FIELDS, (
            f"these thresholds declare no domain: "
            f"{sorted(declared - (RATE_FIELDS | COUNT_FIELDS))}"
        )

    def MQC_CMN_UNI_112362_the_permitted_extremes_of_each_domain_are_accepted(
        self,
    ) -> None:
        """The valid end of every domain, which the invalid cases do not reach.

        **Section 8.1 states both extremes and nothing asserted either.**
        Narrowing the rate check to `0 < x < 1`, so a `pass_floor` of exactly
        `1.0` is refused, survived all 768 cases; so did narrowing the count
        check so a `distribution_minimum` of `1` is refused. The design said it
        and the suite did not reach it, which is the whole shape this case
        exists to close.

        **A floor of 1.0 is a real standard**, and a ceiling of 1.0 is the
        off switch for a distribution rule somebody wants computed and recorded
        but not enforced. This asserts that the value is accepted and then
        applied; what the bands require of a run is settled in section 4.3.

        Returns:
            None
        """
        # EVERY RATE ACCEPTS ITS UPPER EXTREME.
        for field_name in sorted(RATE_FIELDS):
            built = Thresholds(**{field_name: 1.0})
            assert getattr(built, field_name) == 1.0, (
                f"{field_name} refused 1.0, so the domain excludes the value "
                f"section 8.1 says it permits"
            )

        # AND ITS SMALLEST MEANINGFUL ONE, just above the excluded zero.
        for field_name in sorted(RATE_FIELDS):
            assert getattr(Thresholds(**{field_name: 0.01}), field_name) == 0.01

        # EVERY COUNT ACCEPTS ONE, the lower extreme its domain states.
        for field_name in sorted(COUNT_FIELDS):
            assert getattr(Thresholds(**{field_name: 1}), field_name) == 1, (
                f"{field_name} refused 1, so the domain excludes the smallest "
                f"population it is defined over"
            )

        # AND A FLOOR OF 1.0 DECIDES, rather than being accepted and inert.
        # P3 throughout, so no blocking-band rule is involved.
        perfect = VerdictConfig(thresholds=Thresholds(pass_floor=1.0))
        clean = distribution_suite(at_zero=0, at_one=0, total=10)
        assert verdict(clean, perfect, TODAY).green

        blemished = list(clean)
        blemished.append(
            graded("MQC_TASK_one::MQC_RULE_r", outcome="fail", priority=3)
        )
        assert not verdict(blemished, perfect, TODAY).green, (
            "a floor of 1.0 passed a population carrying a failure, so the "
            "standard was accepted and then not applied"
        )

    def MQC_CMN_UNI_112059_a_stored_artifact_carrying_an_impossible_threshold_refuses(
        self,
    ) -> None:
        """The loader is the path where nobody present typed the value.

        `thresholds_from` rebuilds the standard a run was judged against from
        the artifact rather than from current configuration, so an artifact
        edited by hand or written by an older harness arrives here. A guard
        holding only at direct construction would be the section 7.6.2 defect
        again: read in one place and set in none.

        Returns:
            None
        """
        for declared in ({"pass_floor": 0.0}, {"pass_floor": "ninety"},
                         {"p0_share_ceiling": 0.0}, {"distribution_minimum": 0}):
            artifact = gated_artifact(effective_thresholds=declared)
            with pytest.raises(ValueError):
                thresholds_from(artifact)

        # AND AN ARTIFACT RECORDING NOTHING STILL LOADS, which is the ordinary
        # case: the defaults are the standard when none was recorded.
        assert thresholds_from(gated_artifact()).pass_floor == 0.90

        # AND THE DEFAULTS SATISFY THE DOMAIN THEY DECLARE, which is the one
        # assertion that would catch a domain written wrongly rather than a
        # value written wrongly.
        check_domain(Thresholds())
