class TestMQCThresholdBoundaries:
    """Each live threshold, stated at exactly its own value.

    Which side the value falls on is tabulated in
    ``docs/design/cmn_verdict_and_cli.md`` section 8.2, and it is not the same
    side for every threshold.
    """

    def MQC_CMN_UNI_112052_p0_share_at_exactly_the_ceiling_is_permitted(self) -> None:
        """V7 fires above its ceiling and not at it.

        Four P0 definitions in forty is 10.0 percent, the ceiling exactly. The
        denominator is chosen so the share lands on the value rather than near
        it, which is the whole of what this case establishes: `112027` already
        covers a quarter of the suite at P0.

        Returns:
            None
        """
        observations = distribution_suite(at_zero=4, at_one=0, total=40)

        report = evaluate_distribution(observations, Thresholds())
        assert report.p0_share == pytest.approx(0.10), (
            "the population was not built to land on the ceiling, so whatever "
            "this case reports it is not a boundary"
        )

        result = verdict(observations, VerdictConfig(), TODAY)
        assert "V7" not in result.breached_rules, (
            "a P0 share exactly at the ceiling breached V7, so the comparison "
            "has drifted from above-the-ceiling to at-or-above it"
        )
        assert result.green

        # AND ONE MORE BREACHES IT, so the case is not passing because the rule
        # is unreachable at this population size.
        above = distribution_suite(at_zero=5, at_one=0, total=40)
        assert evaluate_distribution(above, Thresholds()).p0_share == pytest.approx(0.125)
        assert "V7" in verdict(above, VerdictConfig(), TODAY).breached_rules

    def MQC_CMN_UNI_112053_p1_share_decides_on_both_sides_of_its_ceiling(self) -> None:
        """V8 had no case of any kind until 2026-10-13.

        So this one carries both sides rather than only the boundary: eight P1
        definitions in forty is 20.0 percent and passes, nine is 22.5 percent
        and breaches. The P0 count stays at zero so no other ceiling can be
        the one that fired.

        Returns:
            None
        """
        at_ceiling = distribution_suite(at_zero=0, at_one=8, total=40)
        assert evaluate_distribution(at_ceiling, Thresholds()).p1_share == pytest.approx(0.20)

        result = verdict(at_ceiling, VerdictConfig(), TODAY)
        assert "V8" not in result.breached_rules
        assert result.green

        above = distribution_suite(at_zero=0, at_one=9, total=40)
        assert evaluate_distribution(above, Thresholds()).p1_share == pytest.approx(0.225)

        breached = verdict(above, VerdictConfig(), TODAY)
        assert breached.breached_rules == ["V8"], (
            f"a P1 share above the ceiling reported {breached.breached_rules}, "
            f"so either V8 never fires or another rule is firing for it"
        )

    def MQC_CMN_UNI_112054_combined_share_at_exactly_the_ceiling_is_permitted(self) -> None:
        """All three distribution ceilings sit on their values at once.

        Four P0 and eight P1 in forty is 10.0, 20.0 and 30.0 percent, which is
        every ceiling exactly. **The combined ceiling is reachable only this
        way**: ten percent plus twenty percent is thirty, so a combined share
        above the ceiling always carries one of the other two above its own,
        and `112028` is where that is asserted.

        Returns:
            None
        """
        observations = distribution_suite(at_zero=4, at_one=8, total=40)

        report = evaluate_distribution(observations, Thresholds())
        assert report.p0_share == pytest.approx(0.10)
        assert report.p1_share == pytest.approx(0.20)
        assert report.combined_share == pytest.approx(0.30)

        result = verdict(observations, VerdictConfig(), TODAY)
        assert not result.breached_rules, (
            f"a suite sitting on all three ceilings reported "
            f"{result.breached_rules}, so a ceiling excludes its own value"
        )
        assert result.green

    def MQC_CMN_UNI_112055_distribution_returns_a_verdict_at_exactly_the_minimum(
        self,
    ) -> None:
        """Thirty case definitions is the population, not one above it.

        `112026` states the abstention at twenty-nine. This states that the
        check resumes at thirty, which is the half a comparison drifting by one
        would break silently: an abstaining check reports no breach, so a run
        over an inflated corpus would go green and say nothing.

        Returns:
            None
        """
        observations = distribution_suite(at_zero=0, at_one=0, total=30)

        report = evaluate_distribution(observations, Thresholds())
        assert report.case_definitions == 30
        assert report.verdict_returned is True, (
            "the check abstained at exactly the minimum, so the ceilings are "
            "unenforced on the smallest population they were meant to govern"
        )
        assert report.p0_share == pytest.approx(0.0)

        # AND THE SHARES ARE DECIDED, not merely computed: a corpus at the
        # minimum breaches when it should.
        inflated = distribution_suite(at_zero=4, at_one=0, total=30)
        assert evaluate_distribution(inflated, Thresholds()).p0_share > 0.10
        assert "V7" in verdict(inflated, VerdictConfig(), TODAY).breached_rules


