class TestMQCPreconditionSkips:
    """Zero skips, enforced rather than stated."""

    def MQC_CMN_UNI_112344_a_precondition_that_skipped_fails_the_run(self) -> None:
        """An ungraded skip exits 3, and a graded one leaves the status alone.

        **A harness unit job reported green at 99.44%** with 704 total, 700
        executed and 4 skipped. Gate 2 has required 100% pass and zero skips
        since it was written, and pytest exits 0 when a test skips, so nothing
        enforced the second half.

        **No reason excuses one.** A precondition measures our harness and every
        one is unconditionally blocking, so a skipped one measured nothing.

        Design: ``harness_test_taxonomy.md`` section 7.5.1.

        Returns:
            None
        """
        # THE LAYER PARTITION, read from the identifier because a skip from
        # collection or setup carries no marker a hook can read.
        assert is_precondition("tests/cmn/m.py::T::MQC_CMN_UNI_112000_x")
        assert is_precondition("tests/x/m.py::T::MQC_EXE_SYS_122000_x")
        assert not is_precondition("tests/cases/m.py::T::MQC_EVL_EVAL_134200_x")
        assert not is_precondition("tests/cases/m.py::T::MQC_EVL_SEC_154100_x")
        assert not is_precondition("tests/cases/m.py::T::MQC_EVL_TOOL_144700_x")

        skipped = Session(Reporter("tests/cmn/m.py::T::MQC_CMN_UNI_112000_x"))
        assert refuse_precondition_skips(skipped) == 1
        assert skipped.exitstatus == 3, (
            "a skipped precondition left the run green, so Gate 2's zero is "
            "stated and not enforced"
        )

        # A GRADED SKIP IS NOT THIS GATE'S BUSINESS. It is counted by its cause
        # in the pass rate, which is a different question from whether the
        # harness itself was measured (section 7.4.1).
        graded = Session(Reporter("tests/cases/m.py::T::MQC_EVL_EVAL_134200_x"))
        assert refuse_precondition_skips(graded) == 0
        assert graded.exitstatus == 0

        # AND IT ADDS A FAILURE, NEVER REMOVES ONE. A run already red stays red
        # at the code it earned.
        already = Session(Reporter(), exitstatus=1)
        assert refuse_precondition_skips(already) == 0
        assert already.exitstatus == 1

        # NO REPORTER MEANS NOTHING TO READ, which must not raise: the hook runs
        # in every invocation, including ones that collected nothing.
        assert refuse_precondition_skips(Session(None)) == 0


class TestMQCEnvironmentScope:
    """A case the environment cannot run is not this run's to measure."""

    def MQC_CMN_UNI_112345_a_case_whose_environment_scope_is_absent_is_deselected(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """Deselected before it runs, so it leaves the total rather than it.

        **A skip is an outcome and this is not one.** "This case could not have
        run here" is a statement about the selection, and recording it as a skip
        put a non-outcome in the result where a reader had to interpret it: the
        line read "4 skipped for a reason of ours" and the job was green.

        Design: ``harness_test_taxonomy.md`` section 7.5.1.

        Returns:
            None
        """
        # THE REGISTRY IS PINNED, so a new scope is deliberate: each one is a
        # new way for a precondition to leave a run silently.
        assert registered_environment_scopes() == frozenset(
            {"local", "paired", "reporter"}
        )

        # THE REPORTING EXTRA IS ASKED FOR AS A RESOLUTION, both packages. A
        # machine with the module and no plugin cannot read what a reporter
        # wrote, so the scope is unavailable there as well: the mutation audit
        # reported the polarity of this test as asserted by nothing
        # (`harness_test_taxonomy.md` section 16.7).
        assert scope_available("reporter")
        monkeypatch.setattr("cmn.environments.find_spec", lambda name: None)
        assert not scope_available("reporter")
        monkeypatch.undo()

        # A SIBLING THAT EXISTS SATISFIES `paired`, and one that does not, does
        # not. The directory name comes from the case, so this repository names
        # no consumer.
        (tmp_path / "beside" / "Present-Repo").mkdir(parents=True)
        root = tmp_path / "beside" / "This-Repo"
        root.mkdir()
        assert scope_available("paired", "Present-Repo", root)
        assert not scope_available("paired", "Absent-Repo", root)
        assert not scope_available("paired", "", root), (
            "a paired scope naming no sibling was treated as satisfied"
        )

        # AN UNREGISTERED SCOPE IS REFUSED RATHER THAN GUESSED. Treating it as
        # available runs a case where it declared it could not, and treating it
        # as absent drops a case on a typo; both are silent.
        with pytest.raises(ValueError):
            scope_available("invented", "", root)
        with pytest.raises(ValueError):
            mark_environment("invented")

        # A CASE DECLARING NOTHING IS ALWAYS AVAILABLE, which keeps the
        # mechanism opt-in.
        plain = Item("tests/cmn/m.py::T::MQC_CMN_UNI_112000_x")
        assert unavailable_here(plain, root) == ""

        absent = Item(
            "tests/cmn/m.py::T::MQC_CMN_UNI_112001_x",
            Marker("paired", sibling="Absent-Repo"),
        )
        present = Item(
            "tests/cmn/m.py::T::MQC_CMN_UNI_112002_x",
            Marker("paired", sibling="Present-Repo"),
        )
        assert unavailable_here(absent, root) == "paired"
        assert unavailable_here(present, root) == ""

        config = Config()
        items = [plain, absent, present]
        dropped = deselect_unavailable_environments(config, items, root)

        assert dropped == 1
        assert config.hook.deselected == [absent], (
            "the wrong case was deselected, so a run either measured something "
            "it could not or dropped something it could"
        )
        assert items == [plain, present], (
            "the kept items are not the ones that remain selected"
        )

        # AND A SELECTION WITH NOTHING ABSENT IS UNTOUCHED, so the hook is not
        # called with an empty list and no line is printed about nothing.
        quiet = Config()
        kept = [plain, present]
        assert deselect_unavailable_environments(quiet, kept, root) == 0
        assert not quiet.hook.deselected
        assert kept == [plain, present]


class TestMQCMarkerRegistry:
    """The marker name is in three files, and these compare them.

    Designed in ``docs/design/harness_test_taxonomy.md`` section 7.5.1, which
    records why comparing is the only option an ini file leaves.
    """

    @mark_environment("paired", sibling="AP-Model-QC")
    def MQC_CMN_UNI_112355_a_marker_registry_disagreeing_with_the_code_is_reported(
        self,
    ) -> None:
        """The registration, the code that applies it, and the other copy.

        **Three assertions, and the third is the one nothing else can make.**
        `--strict-markers` already fails collection when an applied marker is
        unregistered, which covers a rename in either direction for a marker
        this suite applies. It is silent about `evaluator`, `tool`, `sec` and
        `priority`, which are registered here and applied by the consumer
        because this repository owns no graded case.

        **The sibling half declares the `paired` scope** and is deselected
        where the case repository is not checked out beside this one, so a
        clone on its own asserts what it can see rather than failing.

        Returns:
            None
        """
        here = registered_markers(_ROOT / "pytest.ini")

        # THE SCOPE MARKER THE CODE READS IS THE ONE THE INI REGISTERS, which
        # is the claim `environment_marker` made and could not keep alone.
        assert environment_marker() in here, (
            f"the code applies {environment_marker()!r} and pytest.ini "
            f"registers {sorted(here)}, so the scope mechanism is unregistered"
        )

        # EVERY ENTRY CARRIES A DESCRIPTION. A bare word registers the name and
        # tells a reader of `--markers` nothing, which is how a marker nobody
        # understands survives.
        bare = sorted(name for name, text in here.items() if not text)
        assert not bare, f"{len(bare)} marker(s) registered with no description: {bare}"

        # AND THE TWO REPOSITORIES REGISTER THE SAME NAMES. The consumer
        # declares the whole registry deliberately, so a registry copied once
        # and edited once is the drift neither pytest nor either suite sees.
        sibling = registered_markers(_ROOT.parent / "AP-Model-QC" / "pytest.ini")
        assert set(here) == set(sibling), (
            f"the two marker registries disagree: only here "
            f"{sorted(set(here) - set(sibling))}, only there "
            f"{sorted(set(sibling) - set(here))}"
        )

    def MQC_CMN_UNI_112356_an_unreadable_marker_registry_is_refused(self) -> None:
        """A comparison against nothing would assert nothing.

        An absent file and one registering no markers both make the case above
        vacuous while it still passes, which is the failure mode the project
        has corrected often enough to check for rather than reason about.

        Returns:
            None
        """
        with pytest.raises(ValueError, match="QC_HARNESS_PARSER_ERROR"):
            registered_markers(_ROOT / "no_such_pytest.ini")

    def MQC_CMN_UNI_112357_a_registry_with_no_markers_is_refused(
        self, tmp_path: Path
    ) -> None:
        """An ini carrying a `pytest` section and no marker block.

        Args:
            tmp_path (Path): Where the empty configuration is written.

        Returns:
            None
        """
        empty = tmp_path / "pytest.ini"
        empty.write_text("[pytest]\naddopts = -v\n", encoding="utf-8")

        with pytest.raises(ValueError, match="registers no markers"):
            registered_markers(empty)

        # AND A REAL ONE IS READ, so the refusal above is about the content
        # rather than about the reader.
        assert "unit" in registered_markers(_ROOT / "pytest.ini")

    def MQC_CMN_UNI_112358_the_marker_applied_is_the_marker_read(self) -> None:
        """The deselection hook looks for the name a case actually carries.

        **The module held two copies and they agreed, so nothing showed.**
        `mark_environment` wrote the name out and the hook read ``_MARKER``;
        renaming the constant left the marker applied and registered, and the
        hook looked for a name no case carried, so **every scoped case ran
        where its scope was absent** with no warning.

        Design: ``harness_test_taxonomy.md`` section 7.5.1.

        Returns:
            None
        """
        applied = mark_environment("local")

        assert applied.name == environment_marker(), (
            f"cases carry {applied.name!r} and the deselection hook looks for "
            f"{environment_marker()!r}, so no scope is ever read"
        )

        # AND THE SCOPE SURVIVES THE ROUND TRIP, so the assertion above is
        # about one name rather than about an empty marker.
        assert applied.args == ("local",)
        assert applied.kwargs == {"sibling": ""}

    def MQC_CMN_UNI_112375_a_runner_is_recognised_and_each_deselection_counted(
        self, monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture
    ) -> None:
        """A runner variable makes this a runner, and the log counts each drop.

        Two cases scoped to a developer's machine, collected on a runner, are
        both deselected and the line says two.

        Design: ``harness_test_taxonomy.md`` section 7.5.1.

        Args:
            monkeypatch (pytest.MonkeyPatch): Sets and clears runner variables.
            caplog (pytest.LogCaptureFixture): Captures the deselection line.

        Returns:
            None
        """
        for marker in ci_markers():
            monkeypatch.delenv(marker, raising=False)
        assert not under_ci(), "no runner variable is set and this reads as a runner"

        monkeypatch.setenv(ci_markers()[0], "true")
        assert under_ci(), f"{ci_markers()[0]} is set and this does not read as a runner"

        items = [
            Item("tests/cmn/m.py::T::MQC_CMN_UNI_112003_x", Marker("local")),
            Item("tests/cmn/m.py::T::MQC_CMN_UNI_112004_x", Marker("local")),
        ]
        with caplog.at_level(logging.INFO, logger="cmn.environments"):
            assert deselect_unavailable_environments(Config(), items, _ROOT) == 2
        assert "2 case(s) deselected: this environment is not local" in caplog.text, (
            caplog.text
        )

    def MQC_CMN_UNI_112376_a_marker_block_is_read_the_way_pytest_reads_it(
        self, tmp_path: Path
    ) -> None:
        """A key with no value parses, and a blank line registers nothing.

        Args:
            tmp_path (Path): Where the configuration is written.

        Returns:
            None
        """
        ini = tmp_path / "pytest.ini"
        ini.write_text(
            "[pytest]\nconsider_namespace_packages\nmarkers =\n"
            "    unit: unit preconditions\n\n    sec: security\n",
            encoding="utf-8",
        )

        assert registered_markers(ini) == {"unit": "unit preconditions", "sec": "security"}
