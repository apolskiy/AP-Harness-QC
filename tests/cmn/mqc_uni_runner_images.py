"""Unit preconditions for the runner image the CI definitions name.

Created: 2026-10-28
Last updated: 2026-10-28

This file contains one case over ``cmn.runner_images.unpinned_runner_images``:
every Ubuntu label the workflows name carries a version rather than moving,
names the one version the repository pins, and is declared to ``actionlint``,
which validates ``runs-on`` against the labels of its own release. It runs
against this repository and then against planted roots, one per class the check
reports plus a matrix shape whose ``runs-on`` is an expression.

It runs with every unit precondition run, so a workflow naming a label that
moves, a second operating system version, or a version the linter does not know
fails the build locally rather than turning a lint job red and skipping every
job behind it.

**A new module rather than another subject in ``mqc_uni_graded_selection.py``**,
matching the production split: ``runner_images.py`` came out of
``workflow_standards.py`` at its nine-hundred-line runway, and the subject here
is where a job runs rather than what stands in front of it.

**The pin held by review alone until this was written.** ``DESIGN.md`` section
5.0 pinned the image in September and nothing read the decision, so the move to
26.04 on 2026-10-28 reached CI as 19 lint findings here and 15 in the case
repository, every one of them the same class.

**A failure here is not a model finding.** The module carries no priority
marker, per ``framework-rules.md`` section 3.3.

Specified by ``docs/design/harness_ci_pipeline.md`` sections 3.1.2.2 and 8.7.
"""

