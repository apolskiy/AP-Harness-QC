from pathlib import Path

import pytest

from cmn.runner_images import unpinned_runner_images
from tests.cmn.workflow_plant_support import (
    DECLARED_PIN,
    matrix_workflow,
    pinned_workflow,
    plant_root,
)

pytestmark = pytest.mark.unit

# THE ROOT, which is as far up as a case reads (``code-style.md`` section 8.0).
_ROOT: Path = Path(__file__).resolve().parents[2]

# A SECOND LABEL APPENDED TO THE DECLARATION, which plants the one left behind
# by a pin that moved.
_STALE_PIN: str = DECLARED_PIN + "    - ubuntu-24.04\n"


class TestMQCRunnerImagePin:
    """One Ubuntu image, named with a version, and the linter knows it."""

    def MQC_CMN_UNI_112190_a_runner_label_disagreeing_with_the_pin_is_reported(
        self,
        tmp_path: Path,
    ) -> None:
        """Every Ubuntu label agrees with the pin and with the declaration.

        Four classes are reported and this plants one root for each: a label
        carrying no version, a second version in the repository, a version the
        lint configuration does not declare, and a declaration no workflow
        names. A fifth root names its runner through a matrix, which is the
        shape every job in this repository uses, and a sixth names the pin
        correctly and must be silent.

        **The declaration and the pin are compared with each other**, not each
        with a constant, so moving the pin is a sweep and one line and omitting
        either half fails here rather than in CI.

        **The undeclared root is this repository as it stood on 2026-10-28.**
        The pin had moved and no ``.github/actionlint.yaml`` existed, which is
        what the lint job reported 19 times.

        Design: ``harness_ci_pipeline.md`` sections 3.1.2.2 and 8.7.

        Args:
            tmp_path (Path): Where the planted roots are written.

        Returns:
            None
        """
        assert not unpinned_runner_images(_ROOT), (
            "runner label(s) disagree with the pinned image, so a gate could "
            "run two operating system majors or a lint job could refuse the "
            "file: " + "; ".join(unpinned_runner_images(_ROOT))
        )

        two_versions = pinned_workflow("ubuntu-26.04").replace(
            "      - run: echo built\n",
            "      - run: echo built\n"
            "  older:\n"
            "    runs-on: ubuntu-24.04\n"
            "    steps:\n"
            "      - run: echo older\n",
        )
        plants: dict[str, tuple[str, str]] = {
            "moving": (pinned_workflow("ubuntu-latest"), DECLARED_PIN),
            "two_versions": (two_versions, _STALE_PIN),
            "undeclared": (pinned_workflow("ubuntu-26.04"), ""),
            "stale": (pinned_workflow("ubuntu-26.04"), _STALE_PIN),
            "matrix": (
                matrix_workflow("[ubuntu-latest, windows-latest]"),
                DECLARED_PIN,
            ),
            "pinned": (pinned_workflow("ubuntu-26.04"), DECLARED_PIN),
        }
        reported = {
            shape: unpinned_runner_images(
                plant_root(
                    tmp_path / shape, workflow, declaration=declaration
                )
            )
            for shape, (workflow, declaration) in plants.items()
        }

        assert any("names no version" in gap for gap in reported["moving"]), (
            "a workflow running on a label that migrates was not reported, so "
            "the pin DESIGN.md section 5.0.2 accepted a cost for is held by "
            "nothing"
        )
        assert any(
            "versions at once" in gap for gap in reported["two_versions"]
        ), (
            "two Ubuntu versions in one repository were accepted, so a sweep "
            "that moved the pin and missed a line would leave one gate "
            "comparing platforms rather than code"
        )
        assert any(
            "no .github/actionlint.yaml declares" in gap
            for gap in reported["undeclared"]
        ), (
            "a pinned image no lint configuration declares was accepted, "
            "which is the state that turned this repository's lint job red on "
            "2026-10-28 with every job behind it skipped"
        )
        assert any(
            "which no workflow names" in gap for gap in reported["stale"]
        ), (
            "a declaration left behind by a pin that moved was accepted, so "
            "the linter would go on accepting a label nothing runs on"
        )
        assert any("names no version" in gap for gap in reported["matrix"]), (
            "a label named through a matrix was not read, and every job in "
            "this repository names its runner that way, so the check would be "
            "blind to the definitions it exists for"
        )
        assert not reported["pinned"], (
            "a workflow naming the pinned image, declared, was reported: "
            f"{reported['pinned']}"
        )
