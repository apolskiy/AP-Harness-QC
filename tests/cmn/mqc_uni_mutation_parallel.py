"""Unit preconditions for a mutation audit measured in parallel, each point in its own copy.

Created: 2026-10-21
Last updated: 2026-10-21

Its cases check ``tools/mutation_parallel.py`` and the guard in
``cmn.mutation_guard``: an audit with two workers reports the same survivor a
serial audit would, runs every point in a copy and never in the repository,
leaves the repository's module untouched throughout, gives every copy the
sibling repository a paired case needs, and removes its copies when it ends;
a lock marked isolated lets an ordinary run start where an in-place lock
refuses it; and a mutant runs first against the test modules whose imports
reach its module, the full targets running only where those miss it.

An audit took an hour in one tree, and blocked every other run while it did,
so these decide whether the faster audit measures the same thing and frees the
repository. A failure here is **not a model finding**, so the module carries no
priority marker.

Specified by ``docs/design/harness_test_taxonomy.md`` sections 15.15 and 15.16.
"""

