class TestMQCMutationParallel:
    """Parallel copies measure what one tree would, and leave the tree alone."""

    def MQC_CMN_UNI_112423_a_parallel_audit_matches_serial_and_never_writes_the_module(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """Two workers find the one survivor, in copies that see the sibling, then clean up.

        Design: ``harness_test_taxonomy.md`` section 15.15.

        Args:
            tmp_path (Path): Holds the harness root and its sibling.
            monkeypatch (pytest.MonkeyPatch): Replaces the process launcher.

        Returns:
            None
        """
        root = tmp_path / "AP-Harness-QC"
        module = pointed_tree(root)
        (tmp_path / SIBLING).mkdir()
        (tmp_path / SIBLING / SIBLING_MARKER).write_text("present", encoding="utf-8")
        seen: dict[str, list[Any]] = {"cwd": [], "untouched": [], "sibling": []}
        monkeypatch.setattr(mutation_audit.subprocess, "run", isolated_launcher(module, seen))

        step(1, "audit the module with two workers")
        found = parallel_survivors(root, module, ["tests/x.py"], workers=2)
        assert [point.describe() for point in found] == ["line 6: 2 to 3"], (
            f"the parallel audit reported {[point.describe() for point in found]}"
        )

        step(2, "read where each run happened")
        places = set(seen["cwd"])
        assert len(places) >= 2 and root not in places, f"runs happened in {sorted(places)}"

        step(3, "read whether the module stayed the baseline, held isolated, at every run")
        assert seen["untouched"] and all(seen["untouched"]), (
            "a run found the repository's module rewritten or backed up"
        )

        step(4, "read whether every copy saw the sibling repository")
        assert all(seen["sibling"]), "a copy ran without the sibling a paired case needs"

        step(5, "read what the audit left behind")
        assert restored_baseline(module) and not any(place.exists() for place in places) and (
            tmp_path / SIBLING / SIBLING_MARKER
        ).is_file(), "the audit left a copy, a lock or a changed module, or reached the sibling"

    def MQC_CMN_UNI_112424_an_isolated_audit_lock_does_not_refuse_an_ordinary_run(
        self, tmp_path: Path
    ) -> None:
        """A live isolated lock lets a run start; a live in-place lock refuses it.

        Design: ``harness_test_taxonomy.md`` section 15.15.

        Args:
            tmp_path (Path): The harness root.

        Returns:
            None
        """
        module = pointed_tree(tmp_path)
        lock = module.with_name(module.name + LOCK_SUFFIX)
        held = {"pid": os.getpid(), "started": "2026-10-21T18:00:00+00:00"}

        step(1, "hold the module with a live isolated lock and ask whether a run may start")
        lock.write_text(json.dumps({**held, "isolated": True}), encoding="utf-8")
        assert mutation_state(tmp_path, environ={}) is None, "an isolated lock refused the run"

        step(2, "hold it with a live in-place lock and ask again")
        lock.write_text(json.dumps(held), encoding="utf-8")
        assert "is under mutation" in (mutation_state(tmp_path, environ={}) or ""), (
            "an in-place lock let the run start"
        )


class TestMQCMutationSeeingFirst:
    """A mutant meets the cases that can see its module before the whole suite."""

    def MQC_CMN_UNI_112425_a_mutant_meets_the_cases_that_import_its_module_first(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The seeing modules run first; only a mutant they miss costs the full targets.

        Design: ``harness_test_taxonomy.md`` section 15.16.

        Args:
            tmp_path (Path): Holds the harness root.
            monkeypatch (pytest.MonkeyPatch): Replaces the process launcher.

        Returns:
            None
        """
        root = tmp_path / "AP-Harness-QC"
        paths = seeing_tree(root)

        step(1, "list the test modules that can see the module")
        assert seeing_modules(root, paths["module"]) == [
            "tests/mqc_uni_direct.py", "tests/mqc_uni_indirect.py",
        ], f"the seeing modules were {seeing_modules(root, paths['module'])}"

        calls: list[list[str]] = []
        monkeypatch.setattr(mutation_audit.subprocess, "run", subset_launcher(calls, "value * 3"))
        step(2, "audit the module with two workers")
        found = parallel_survivors(root, paths["module"], ["tests"], workers=2)
        assert found == [], f"the full targets' kill was overruled: {found}"

        step(3, "count the full-target runs among the points")
        points = [call for call in calls if "-x" in call]
        full = [call for call in points if not any(part.endswith(".py") for part in call)]
        assert len(full) == 1 and len(points) == len(mutation_points(POINTED)) + 1, (
            f"{len(full)} full runs over {len(points)} point runs"
        )
