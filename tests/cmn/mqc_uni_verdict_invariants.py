import pytest

from cmn.observations import Observation
from cmn.verdict import VerdictConfig, verdict
from tests.cmn.verdict_support import TODAY, passing_suite

pytestmark = pytest.mark.unit


class TestMQCRedIsNeverGreen:
    """Two readings of one run must not disagree."""

    def MQC_CMN_UNI_112360_a_red_verdict_is_never_green(self) -> None:
        """A non-zero exit code and `green` are one statement, not two.

        `green` is what a badge and a reader take from a run, so the two
        disagreeing is the worst shape a result can have: one reader sees a
        pass and another sees a failure, about the same run.

        Asserted over every red path the suite can reach rather than over the
        one the mutation found, which is the difference between closing a
        survivor and closing its class.

        Returns:
            None
        """
        reds = (
            ("no observations at all", []),
            ("a failed precondition",
             [Observation("MQC_TASK_pre::MQC_RULE_pre", "UNI", "fail")]),
            ("a skipped precondition",
             [Observation("MQC_TASK_pre::MQC_RULE_pre", "UNI", "skip")]),
            ("no graded observation",
             [Observation("MQC_TASK_pre::MQC_RULE_pre", "UNI", "pass")]),
        )
        for label, observations in reds:
            result = verdict(list(observations), VerdictConfig(), TODAY)
            assert result.exit_code != 0, f"{label} exited zero"
            assert result.green is False, (
                f"{label} reported green with exit {result.exit_code}, so a "
                f"reader taking the flag and a reader taking the code "
                f"disagree about the same run"
            )

        # AND THE CONVERSE, so this is about the two agreeing rather than
        # about `green` being False everywhere.
        clean = verdict(passing_suite(10), VerdictConfig(), TODAY)
        assert clean.exit_code == 0
        assert clean.green is True
