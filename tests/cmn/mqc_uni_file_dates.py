"""Unit preconditions for the creation and update dates every module docstring carries.

Created: 2026-10-21
Last updated: 2026-10-21

The case here checks ``cmn.file_dates``: that a docstring missing either date
line, carrying one that is not a date, created after it was last updated or
dated in the future is reported, that a file changed since its last commit with
its date left behind is reported as stale, that stamping it clears the report,
and that this repository's own files carry both lines correctly.

It runs with every unit precondition run, so a file added without its dates, or
edited without running ``tools/refresh_file_dates.py``, fails the build naming
the file. A failure here is **not a model finding**, so the module carries no
priority marker.

Specified by ``.claude/rules/code-style.md`` section 3.1.2 and
``docs/design/cmn_verdict_and_cli.md`` section 10.39.
"""

# ------------------------------------------------------------- cases in here
# Generated by `tools/refresh_case_summaries.py`.
#
# TestMQCFileDates
#   112526  a_file_date_line_missing_or_stale_is_reported
# ------------------------------------------------------------ end of cases

from datetime import date, timedelta
from pathlib import Path

import pytest

from cmn.case_steps import step
from cmn.file_dates import file_date_problems, stamped_source

from tests.cmn.file_dates_support import HEADER, git_in, planted_module

pytestmark = pytest.mark.unit


class TestMQCFileDates:
    """Every module says when it was created and last updated, and the dates hold."""

    def MQC_CMN_UNI_112526_a_file_date_line_missing_or_stale_is_reported(
        self, tmp_path: Path
    ) -> None:
        """Missing, malformed, misordered, future and stale dates are each reported.

        Design: ``cmn_verdict_and_cli.md`` section 10.39.

        Returns:
            None
        """
        today = date.today()
        planted = {
            "undated.py": f'{HEADER}"""A planted module.\n\nWhat it holds.\n"""\n',
            "malformed.py": planted_module("yesterday", "2026-10-21"),
            "misordered.py": planted_module("2026-10-21", "2026-10-20"),
            "future.py": planted_module("2026-10-01", "2999-01-01"),
        }
        for name, text in planted.items():
            (tmp_path / name).write_text(text, encoding="utf-8")

        step(1, "plant one file per defect and read the problems")
        reported = "\n".join(file_date_problems(tmp_path, today))
        assert all(
            message in reported
            for message in (
                "undated.py: the module docstring carries no 'Created:' line",
                "malformed.py: 'Created: yesterday' is not a date",
                "misordered.py: created 2026-10-21 is later than last updated",
                "future.py: 2999-01-01 is later than today",
            )
        ), f"a planted date defect went unreported, or under another message:\n{reported}"

        step(2, "edit a committed file and leave its date behind")
        history = tmp_path / "history"
        history.mkdir()
        dated = history / "dated.py"
        dated.write_text(planted_module("2026-01-01", "2026-01-01"), encoding="utf-8")
        git_in(history, "init", "--quiet")
        git_in(history, "add", "dated.py")
        git_in(history, "commit", "--quiet", "-m", "planted")
        dated.write_text(
            planted_module("2026-01-01", "2026-01-01") + "OTHER = 2\n", encoding="utf-8"
        )
        stale = file_date_problems(history, today)
        assert len(stale) == 1 and "run tools/refresh_file_dates.py" in stale[0], (
            f"an edited file with its date left behind was not reported stale: {stale}"
        )

        step(3, "stamp today's date and read the problems again")
        dated.write_text(
            stamped_source(dated.read_text(encoding="utf-8"), "2026-01-01", today.isoformat()),
            encoding="utf-8",
        )
        assert not file_date_problems(history, today), "a stamped file is still reported"

        # THE STAMP AND THE COMMIT DATE COME FROM THE AUTHOR'S CLOCK and
        # `today` from the runner's. Comparing across them called a file
        # committed and stamped on one local day stale for the seven hours
        # after local midnight, which refused every mutation audit in CI on
        # 2026-10-21: the audit is the one caller whose tree differs from its
        # last commit because it wrote it. Section 10.39.1.
        step(4, "read the same tree against another day's clock")
        tomorrow = today + timedelta(days=1)
        assert file_date_problems(history, tomorrow) == file_date_problems(
            history, today
        ), (
            "the staleness verdict moved with the clock, so a runner ahead of "
            "the author's timezone asks for a stamp nobody can write: a date "
            "later than today is rejected by this same check"
        )

        step(5, "read this repository's own files")
        own = file_date_problems(Path(__file__).resolve().parents[2], today)
        assert not own, f"{len(own)} file date problem(s):\n  " + "\n  ".join(own[:12])
