from types import SimpleNamespace

import pytest

from cmn.band_summary import (
    Alarms,
    band_table,
    result_lines,
    skip_reasons_from,
    skipped_cases_from,
)

pytestmark = pytest.mark.unit


class TestMQCBandArithmetic:
    """What a summary prints is computed from what it was given."""

    def MQC_CMN_UNI_112372_a_band_table_total_disagreeing_with_its_bands_is_reported(
        self,
    ) -> None:
        """The totals row sums the bands, and its rates divide those sums.

        Two bands of 6 and 7 cases: 13 in total, 9 executed, 6 passed, 3
        failed, 4 skipped, 6 of 9 and 6 of 13 passing.

        Design: ``cmn_verdict_and_cli.md`` section 7.11.3.

        Returns:
            None
        """
        table = band_table([
            ("0", 4, 1, [("a", "r")]),
            ("2,3,4", 2, 2, [("b", "r"), ("c", "r"), ("d", "r")]),
        ])

        total = "| **Total** | **13** | **9** | **6** | **3** | **4** | **66.7%** | **46.2%** |"
        assert total in table, (
            "the totals row does not sum the bands it closes: " + "\n".join(table)
        )
        assert "| Band P0 | 6 | 5 | 4 | 1 | 1 | 80.0% | 66.7% |" in table, table

    def MQC_CMN_UNI_112373_a_skip_reason_is_read_whatever_shape_pytest_gives_it(
        self,
    ) -> None:
        """A reason is the message of a three-part report, or the string given.

        Design: ``cmn_verdict_and_cli.md`` section 7.11.2.

        Returns:
            None
        """
        reports = [
            SimpleNamespace(nodeid="tests/a.py::TestA::case_one",
                            longrepr=("tests/a.py", 12, "QC_HARNESS_FIXTURE_MISSING: none")),
            SimpleNamespace(nodeid="tests/b.py::TestB::case_two",
                            longrepr="QC_HARNESS_DEPENDENCY_UNMET: base failed"),
            SimpleNamespace(nodeid="tests/c.py::case_three", longrepr=None),
        ]

        assert skip_reasons_from(reports) == [
            "QC_HARNESS_FIXTURE_MISSING: none",
            "QC_HARNESS_DEPENDENCY_UNMET: base failed",
            "",
        ]
        assert [case for case, _ in skipped_cases_from(reports)] == [
            "case_one", "case_two", "case_three",
        ], "a skipped case is not named by its own callable"

    def MQC_CMN_UNI_112374_a_precondition_skip_line_appears_only_when_one_skipped(
        self,
    ) -> None:
        """No precondition line by default, and never more than were skipped.

        A selection that is not a band reads in lower case after its article.

        Design: ``cmn_verdict_and_cli.md`` section 7.11.2.

        Returns:
            None
        """
        plain = result_lines(passed=1, failed=0, skips=[("c", "r")], engine="gemini")
        assert plain[0] == "Test results for the whole selection on gemini", plain[0]
        assert not any(line.startswith("preconditions skipped") for line in plain), (
            "a run that skipped no precondition says it exits 3"
        )

        clamped = result_lines(passed=1, failed=0, skips=[("c", "r"), ("d", "r")],
                               alarms=Alarms(preconditions_skipped=5))
        assert "preconditions skipped: 2, so the run exits 3" in clamped, (
            "the precondition count exceeds the skips it is drawn from"
        )
