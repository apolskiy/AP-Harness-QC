"""Unit precondition that a case a judge can decide does not claim P0 or P1.

Created: 2026-10-28
Last updated: 2026-10-28

The two cases here check ``exceeds_measurement_ceiling`` in ``cmn.demotion``:
that it reports a candidate claiming P0 or P1 whose outcome a rubric threshold
can decide, and that it accepts one priced at P2 although the same rubric
decides it. Both build their candidates here, because the predicate is pure and
the corpus it is pointed at belongs to the case repository.

They run in the ``unit`` precondition gate. The predicate decides whether a
priority assignment is admissible at all, so a failure here means the ceiling
is unenforced and every later distribution figure rests on levels nobody
checked.

**Security is not exempt from this one**, which is the distinction the cases are
written to pin. ``demotion_order`` leaves a security case alone because
security coverage does not compete for a budget; measurement reliability is a
different question and reaches every layer.

Specified by ``docs/design/harness_test_taxonomy.md`` section 4.1.2.1.

A failure here is **not a model finding**, so the module carries no priority marker, per
``framework-rules.md`` section 3.3.
"""

