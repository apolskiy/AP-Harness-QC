import pytest

from cmn.demotion import DemotionCandidate, exceeds_measurement_ceiling

pytestmark = pytest.mark.unit


class TestMQCMeasurementCeiling:
    """Whether a run can block on a number a judge produced."""

    def MQC_CMN_UNI_112430_a_judge_decidable_case_claiming_p0_is_reported(
        self,
    ) -> None:
        """A rubric-decidable candidate at P0 or P1 breaches the ceiling.

        **The security case is the one that matters.** Sixteen of the twenty
        one rules this predicate was written for are ``MQC_SEC_``, and the
        exemption they do carry is from the distribution ceilings rather than
        from the scale, so a reading that spared them here would spare the
        whole population.

        Design: ``harness_test_taxonomy.md`` section 4.1.2.1.

        Returns:
            None
        """
        for level in (0, 1):
            candidate = DemotionCandidate(
                case_id=f"1545{level:02d}",
                layer="SEC",
                assigned_priority=level,
                matched_conditions=["P0_SAFETY_CRITICAL_MODEL"],
            )
            assert exceeds_measurement_ceiling(candidate, rubric_decides=True), (
                f"a case a judge score can decide is admitted at P{level}, so a "
                f"run blocks on a rubric threshold rather than on a measurement "
                f"that disagrees with nobody"
            )

        # THE PREDICATE IS ABOUT THE FAILURE PATH AND NOT THE LEVEL. The same
        # candidate with no rubric is correctly priced, which is what keeps the
        # nineteen deterministic security rules at P0.
        deterministic = DemotionCandidate(
            case_id="154100",
            layer="SEC",
            assigned_priority=0,
            matched_conditions=["P0_SAFETY_CRITICAL_MODEL"],
        )
        assert not exceeds_measurement_ceiling(deterministic, rubric_decides=False), (
            "a canary assertion at P0 is reported as a breach, which would "
            "demote every deterministic security case the suite has"
        )

    def MQC_CMN_UNI_112431_a_judge_decidable_case_priced_at_p2_is_accepted(
        self,
    ) -> None:
        """A demoted candidate is admissible and still reads as demoted.

        **Both claims are asserted together deliberately.** A predicate that
        accepted P2 while the record lost its severity condition would price
        the gate correctly and throw away the only statement that the behaviour
        is safety-critical, which is the half a vendor ticket rests on.

        Design: ``harness_test_taxonomy.md`` sections 4.1.2.1 and 4.1.4.1.

        Returns:
            None
        """
        demoted = DemotionCandidate(
            case_id="154501",
            layer="SEC",
            assigned_priority=2,
            matched_conditions=["P0_SAFETY_CRITICAL_MODEL", "P2_RUBRIC_THRESHOLD"],
        )
        assert not exceeds_measurement_ceiling(demoted, rubric_decides=True), (
            "a case priced at its measurement ceiling is reported as a breach, "
            "so the remedy the predicate exists to name is itself refused"
        )
        assert demoted.demoted, (
            "a case demoted for measurement reliability does not read as "
            "demoted, so the count reported beside the distribution shares "
            "understates how the suite met its ceilings"
        )
        assert demoted.ceiling == 0, (
            "the severity condition no longer sets the ceiling, so the record "
            "has lost the claim that the behaviour is safety-critical"
        )

        for level in (3, 4):
            further = DemotionCandidate(
                case_id=f"15450{level}",
                layer="EVAL",
                assigned_priority=level,
                matched_conditions=["P1_TIER_GUARANTEE", "P2_RUBRIC_THRESHOLD"],
            )
            assert not exceeds_measurement_ceiling(further, rubric_decides=True), (
                f"P{level} is refused although it sits below the ceiling, so the "
                f"predicate reads as an assignment rather than as a limit"
            )
