from pathlib import Path

import pytest

from cmn.case_steps import step
from cmn.grouping import story
from cmn.missing_artifact import ARTIFACT_MISSING
from cmn.prerequisites import read_outcomes, write_outcomes
from tests.cmn.missing_artifact_support import (
    CARRY_DEPENDENT as _DEPENDENT,
    CARRY_INDEPENDENT as _INDEPENDENT,
    MALFORMED_CARRY_FILES,
    ArtifactItem,
    accepted_by,
    band_outcomes,
    carry_config,
    carry_population as _population,
    carry_provenance,
    write_malformed_carry,
)

pytestmark = pytest.mark.unit


class TestMQCCarriedArtifact:
    """A lost or unusable carry file skips only what rests on it."""

    @story("A missing carried outcome skips only its dependents")
    def MQC_CMN_UNI_112451_an_uncarried_foundation_skips_only_its_dependents(
        self, tmp_path: Path
    ) -> None:
        """A valid file lacking 90003 skips its dependent alone, naming the file and 90003.

        Design: ``cmn_verdict_and_cli.md`` section 10.28.8.

        Args:
            tmp_path (Path): Where the carry file is written.

        Returns:
            None
        """
        step(1, "run a band whose valid carry file holds 90001 and not 90003")
        record = tmp_path / "carry.json"
        write_outcomes(record, carry_provenance(), {"90001": True})
        items = _population()
        outcomes = band_outcomes(carry_config(str(record)), items)
        assert (
            outcomes[_DEPENDENT].startswith(f"{ARTIFACT_MISSING}: carried_outcome {record}")
            and "90003" in outcomes[_DEPENDENT]
            and outcomes[_INDEPENDENT] == "runs"
            and items[0].artifact_properties() == {
                "mqc_artifact_kind": "carried_outcome", "mqc_artifact_path": str(record),
            }
        ), outcomes

    @story("A missing carried outcome skips only its dependents")
    def MQC_CMN_UNI_112452_an_absent_carry_file_skips_the_cases_resting_on_it(
        self, tmp_path: Path
    ) -> None:
        """An absent carry file skips the dependent, saying so, and the other case runs.

        Design: ``cmn_verdict_and_cli.md`` section 10.28.8.

        Args:
            tmp_path (Path): Where the carry file is not.

        Returns:
            None
        """
        step(1, "run a band naming a carry file that does not exist")
        record = tmp_path / "carry.json"
        outcomes = band_outcomes(carry_config(str(record)), _population())
        assert (
            outcomes[_DEPENDENT].startswith(f"{ARTIFACT_MISSING}: carried_outcome {record}")
            and "is absent" in outcomes[_DEPENDENT]
            and outcomes[_INDEPENDENT] == "runs"
        ), outcomes

    @story("A missing carried outcome skips only its dependents")
    def MQC_CMN_UNI_112453_a_malformed_carry_file_skips_the_cases_resting_on_it(
        self, tmp_path: Path
    ) -> None:
        """Each malformed carry file skips the dependent alone instead of refusing the band.

        Design: ``cmn_verdict_and_cli.md`` section 10.28.8.

        Args:
            tmp_path (Path): Where each malformed file is written.

        Returns:
            None
        """
        step(1, "run a band over each malformed carry file, and collect the wrong outcomes")
        wrong: dict[str, object] = {}
        for name, body in MALFORMED_CARRY_FILES.items():
            record = write_malformed_carry(tmp_path / f"{name.replace(' ', '_')}.json", body)
            try:
                outcomes = band_outcomes(carry_config(str(record)), _population())
            except ValueError as error:
                wrong[name] = f"refused the band: {error}"
                continue
            if not (
                outcomes[_DEPENDENT].startswith(f"{ARTIFACT_MISSING}: carried_outcome {record}")
                and outcomes[_INDEPENDENT] == "runs"
            ):
                wrong[name] = outcomes
        assert not wrong, wrong

    @story("A missing carried outcome skips only its dependents")
    def MQC_CMN_UNI_112454_a_carry_file_from_another_run_skips_the_cases_resting_on_it(
        self, tmp_path: Path
    ) -> None:
        """A file written for another engine skips the dependent, naming the field that moved.

        Design: ``cmn_verdict_and_cli.md`` section 10.28.8.

        Args:
            tmp_path (Path): Where the carry file is written.

        Returns:
            None
        """
        step(1, "run a band whose carry file was written for openai")
        record = tmp_path / "carry.json"
        write_outcomes(record, carry_provenance(engine="openai"), {"90003": True})
        outcomes = band_outcomes(carry_config(str(record)), _population())
        assert (
            outcomes[_DEPENDENT].startswith(f"{ARTIFACT_MISSING}: carried_outcome {record}")
            and "engine" in outcomes[_DEPENDENT]
            and outcomes[_INDEPENDENT] == "runs"
        ), outcomes

    @story("A missing carried outcome skips only its dependents")
    def MQC_CMN_UNI_112455_a_valid_carry_file_still_decides_its_dependents(
        self, tmp_path: Path
    ) -> None:
        """A held foundation runs its dependent; one that did not hold skips it as unmet.

        Design: ``cmn_verdict_and_cli.md`` section 10.28.8.

        Args:
            tmp_path (Path): Where the carry file is written.

        Returns:
            None
        """
        step(1, "run a band whose carry file holds 90003 held and 90004 not held")
        record = tmp_path / "carry.json"
        write_outcomes(record, carry_provenance(), {"90003": True, "90004": False})
        failing = ArtifactItem("MQC_EVL_EVAL_134001_rests_on_a_failure", priority=2,
                               depends=("90004",))
        outcomes = band_outcomes(carry_config(str(record)), [*_population(), failing])
        assert (
            outcomes[_DEPENDENT] == "runs"
            and outcomes[_INDEPENDENT] == "runs"
            and outcomes[failing.name].startswith("QC_HARNESS_DEPENDENCY_UNMET")
            and failing.artifact_properties() == {}
        ), outcomes

    @story("A missing carried outcome skips only its dependents")
    def MQC_CMN_UNI_112456_the_carry_reader_refuses_each_malformed_record(
        self, tmp_path: Path
    ) -> None:
        """The reader refuses every malformed body, reads a valid one and an absent file.

        Design: ``cmn_verdict_and_cli.md`` section 10.28.8.

        Args:
            tmp_path (Path): Where each record is written.

        Returns:
            None
        """
        step(1, "read each malformed record, and collect the ones the reader accepted")
        records = {
            name: write_malformed_carry(tmp_path / f"{name.replace(' ', '_')}.json", body)
            for name, body in MALFORMED_CARRY_FILES.items()
        }
        accepted = accepted_by(lambda path: read_outcomes(path, carry_provenance()), records)
        assert not accepted, f"the reader accepted malformed records: {accepted}"

        step(2, "read a valid record and an absent one")
        valid = tmp_path / "valid.json"
        write_outcomes(valid, carry_provenance(), {"90003": False})
        assert (
            read_outcomes(valid, carry_provenance(band="2")).outcomes == {"90003": False}
            and not read_outcomes(tmp_path / "absent.json", carry_provenance()).outcomes
        )
