import re

import pytest

from cmn.layers import (
    LayerProperties,
    layer_properties,
    register_layer,
    registered_layers,
    unregister_layer,
)
from cmn.registries import (
    code_criticality,
    priority_condition_level,
    registered_codes,
    registered_priority_conditions,
)
from tests.cmn.table_support import (
    TAXONOMY,
    bare,
    layer_table_problems,
    outcome_table_problems,
    ranked_codes,
    table_after,
)

pytestmark = pytest.mark.unit


class TestMQCRegistryTables:
    """A registry the harness runs on says what its table says."""

    def MQC_CMN_UNI_112368_a_layer_or_outcome_disagreeing_with_its_table_is_reported(
        self,
    ) -> None:
        """Every layer and outcome property equals its row, both directions.

        Design: ``harness_test_taxonomy.md`` sections 3 and 7.4.0.

        Returns:
            None
        """
        problems = layer_table_problems() + outcome_table_problems()
        assert not problems, "; ".join(problems)

    def MQC_CMN_UNI_112369_a_priority_condition_disagreeing_with_its_table_is_reported(
        self,
    ) -> None:
        """Every condition's level equals its row, both directions.

        Design: ``harness_test_taxonomy.md`` section 4.1.0.

        Returns:
            None
        """
        rows = table_after(TAXONOMY, "4.1.0 The condition registry")
        assert rows, "the condition table was not found, so nothing is compared"
        tabled = {bare(row["Identifier"]): int(bare(row["Level"]).lstrip("P")) for row in rows}
        problems = [
            f"{name}: code P{priority_condition_level(name)}, table P{level}"
            for name, level in sorted(tabled.items())
            if priority_condition_level(name) != level
        ]
        problems.extend(
            f"{name} is registered and not in the table"
            for name in sorted(registered_priority_conditions() - set(tabled))
        )
        assert not problems, "; ".join(problems)

    def MQC_CMN_UNI_112370_a_criticality_rank_disagreeing_with_its_table_is_reported(
        self,
    ) -> None:
        """Every ranked code's rank equals its row, both directions.

        Design: ``harness_test_taxonomy.md`` section 6.5.

        Returns:
            None
        """
        rows = table_after(TAXONOMY, "The order")
        assert rows, "the ranking table was not found, so nothing is compared"
        tabled: dict[str, int] = {}
        for row in rows:
            for code in re.findall(r"QC_[A-Z_]+", row["Codes"]):
                tabled[code] = int(bare(row["Rank"]))
        problems = [
            f"{code}: code rank {code_criticality(code)}, table rank {rank}"
            for code, rank in sorted(tabled.items())
            if code_criticality(code) != rank
        ]
        ranked = {
            code for code in ranked_codes()
            if code not in tabled
        }
        problems.extend(f"{code} is ranked and not in the table" for code in sorted(ranked))
        assert not problems, "; ".join(problems)

    def MQC_CMN_UNI_112380_a_registered_code_absent_from_the_taxonomy_is_reported(
        self,
    ) -> None:
        """Every code the harness registers has a row in a section 6 table.

        ``112202`` asks the other direction, that every code a design names is
        registered; a code registered in the harness and never written into
        the taxonomy was unseen by both.

        Design: ``harness_test_taxonomy.md`` section 6 and ``framework-rules.md``
        section 4.1.

        Returns:
            None
        """
        tabled: set[str] = set()
        headings = ("6.1 `QC_LLM_*`", "6.2 `QC_HARNESS_*`", "6.3 `QC_DATA_*`", "6.4 `QC_SEC_*`")
        for heading in headings:
            rows = table_after(TAXONOMY, heading)
            assert rows, f"the table under {heading} was not found"
            for row in rows:
                tabled |= set(re.findall(r"QC_[A-Z_]+", next(iter(row.values()))))

        missing = sorted(registered_codes() - tabled)
        assert not missing, (
            f"{len(missing)} registered code(s) have no taxonomy row, so the single "
            f"registry does not list them: {missing}"
        )

    def MQC_CMN_UNI_112371_a_layer_block_touching_another_at_its_bound_is_refused(
        self,
    ) -> None:
        """A block starting on another block's last identifier overlaps it.

        Design: ``harness_test_taxonomy.md`` section 3.2.1.

        Returns:
            None
        """
        end = layer_properties("UNI").id_block[1]
        start = layer_properties("SYS").id_block[0]
        # BOTH ENDS: a block starting on another's last identifier, and one
        # ending on another's first.
        for block in ((end, end + 10), (start - 10, start)):
            touching = LayerProperties("ZZZ", "zzz", False, True, True, block)
            try:
                with pytest.raises(ValueError, match="overlaps"):
                    register_layer(touching)
            finally:
                if "ZZZ" in registered_layers():
                    unregister_layer("ZZZ")
