from pathlib import Path
from typing import Final

import pytest

from cmn.case_steps import step
from cmn.grouping import story
from cmn.missing_artifact import ARTIFACT_MISSING
from tests.cmn.missing_artifact_support import junit_outcomes
from tests.cmn.wired_session import run_wired_session

pytestmark = pytest.mark.unit

# A CONSUMER'S WIRING, reduced to the flag under test.
_CONFTEST: Final[str] = '''
from typing import Any

from cmn.missing_artifact import skip_declared_missing
from cmn.pytest_support import add_mqc_options, configure_invocation


def pytest_addoption(parser: Any) -> None:
    add_mqc_options(parser)


def pytest_configure(config: Any) -> None:
    configure_invocation(config)


def pytest_runtest_setup(item: Any) -> None:
    skip_declared_missing(item)
'''

# A GRADED CASE AND A PRECONDITION, told apart by the layer token in the name.
_CASES: Final[str] = '''
def test_MQC_EVL_EVAL_134000_graded() -> None:
    assert True


def test_MQC_CMN_UNI_111000_precondition() -> None:
    assert True
'''

_DECLARED: Final[str] = "spend_report=spent/junit_mqc_live_live_p0.xml"
_DECLARED_RECORD: Final[str] = "precondition_record=reports/preconditions.json"


class TestMQCDeclaredArtifact:
    """An artifact declared missing skips every graded case, and only those."""

    @story("An artifact declared missing skips the graded cases")
    def MQC_CMN_UNI_112469_a_declared_missing_artifact_skips_every_graded_case(
        self, tmp_path: Path
    ) -> None:
        """A declared spend report skips the graded case at setup, naming it in JUnit.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.2.

        Args:
            tmp_path (Path): Where the wired session and its report are written.

        Returns:
            None
        """
        step(1, "run a wired session declaring a spend report missing, writing JUnit")
        report = tmp_path / "junit.xml"
        finished = run_wired_session(
            tmp_path, _CONFTEST, _CASES,
            extra=("--missing-artifact", _DECLARED, "--junitxml", str(report)),
        )
        outcome, properties = junit_outcomes(report).get(
            "test_MQC_EVL_EVAL_134000_graded", ("not reported", {})
        )
        assert (
            outcome.startswith(
                f"skipped: {ARTIFACT_MISSING}: spend_report spent/junit_mqc_live_live_p0.xml, "
                f"declared missing to this run by --missing-artifact"
            )
            and properties.get("mqc_artifact_kind") == "spend_report"
            and properties.get("mqc_artifact_path") == "spent/junit_mqc_live_live_p0.xml"
        ), (outcome, properties, (finished.stdout + finished.stderr)[-800:])

    @story("An artifact declared missing skips the graded cases")
    def MQC_CMN_UNI_112470_a_malformed_missing_artifact_value_is_refused(
        self, tmp_path: Path
    ) -> None:
        """A value with no separator, an unknown kind or no path refuses the run, naming it.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.2.

        Args:
            tmp_path (Path): Where each wired session is written.

        Returns:
            None
        """
        step(1, "run a wired session with each malformed value and read how it ended")
        malformed = {
            "no separator": "spend_report",
            "an unknown kind": "receipt=spent/junit_mqc_live_live_p0.xml",
            "no path": "spend_report=",
        }
        accepted = []
        for fault, value in malformed.items():
            directory = tmp_path / fault.replace(" ", "_")
            directory.mkdir()
            finished = run_wired_session(
                directory, _CONFTEST, _CASES, extra=("--missing-artifact", value)
            )
            output = finished.stdout + finished.stderr
            refused = (
                finished.returncode == pytest.ExitCode.USAGE_ERROR
                and f"--missing-artifact {value!r}" in output
                and "passed" not in output
            )
            if not refused:
                accepted.append(f"{fault}: exit {finished.returncode}\n{output[-600:]}")
        assert not accepted, "\n".join(accepted)

    @story("An artifact declared missing skips the graded cases")
    def MQC_CMN_UNI_112471_a_precondition_or_an_undeclared_run_is_left_alone(
        self, tmp_path: Path
    ) -> None:
        """A precondition runs under a declaration, and a run declaring nothing skips nothing.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.2.

        Args:
            tmp_path (Path): Where the two wired sessions are written.

        Returns:
            None
        """
        step(1, "run one session declaring a spend report missing and one declaring nothing")
        declared, undeclared = tmp_path / "declared", tmp_path / "undeclared"
        declared.mkdir()
        undeclared.mkdir()
        run_wired_session(
            declared, _CONFTEST, _CASES,
            extra=("--missing-artifact", _DECLARED, "--junitxml", str(declared / "junit.xml")),
        )
        run_wired_session(
            undeclared, _CONFTEST, _CASES,
            extra=("--junitxml", str(undeclared / "junit.xml")),
        )
        with_declaration = {
            name: outcome for name, (outcome, _) in junit_outcomes(declared / "junit.xml").items()
        }
        without = {
            name: outcome for name, (outcome, _) in junit_outcomes(undeclared / "junit.xml").items()
        }
        assert (
            with_declaration.get("test_MQC_CMN_UNI_111000_precondition") == "passed"
            and set(without.values()) == {"passed"}
            and len(without) == 2
        ), (with_declaration, without)

