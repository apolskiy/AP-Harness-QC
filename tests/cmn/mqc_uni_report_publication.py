    def MQC_CMN_UNI_420010_a_pages_deploy_on_main_is_never_cancelled_midway(
        self,
    ) -> None:
        """A workflow that deploys the site never cancels a run in progress on main.

        **A run cancelled midway on main costs two things.** A Pages deployment
        cancelled while syncing left the next deploy waiting at
        ``syncing_files`` until it timed out, three of four publishes in the
        case repository on 2026-11-09, and a cancelled gate run concludes
        ``cancelled``, so the commit it measured is never green to the case
        repository's pairing resolver. Superseded runs on other refs still
        cancel: they deploy nothing and nothing pins them.

        A workflow's ``cancel-in-progress`` is accepted as ``false``, or as the
        expression ``github.ref != 'refs/heads/main'``, which is false on main.

        Design: ``harness_ci_pipeline.md`` section 3.4.

        Returns:
            None
        """
        allowed = (False, f"${{{{ {_NOT_MAIN} }}}}")
        cancelling = []
        for path in sorted((_ROOT / ".github" / "workflows").glob("*.yml")):
            definition = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
            deploying = [
                job or {} for job in (definition.get("jobs") or {}).values()
                if any("actions/deploy-pages" in str((each or {}).get("uses", ""))
                       for each in (job or {}).get("steps") or [])
            ]
            levels = [definition.get("concurrency")] + [
                job.get("concurrency") for job in deploying
            ]
            if deploying and any(
                isinstance(level, dict)
                and level.get("cancel-in-progress", False) not in allowed
                for level in levels
            ):
                cancelling.append(path.name)

        step(1, "find no workflow that deploys the site and cancels a run in progress on main")
        assert not cancelling, (
            f"these workflows deploy the site and can cancel a run in progress on "
            f"main, so a deploy stopped midway stalls the next and a cancelled "
            f"run leaves its commit never green: {cancelling}"
        )

    def MQC_CMN_UNI_420011_a_deploy_in_the_job_that_uploaded_is_reported(
        self, tmp_path: Path
    ) -> None:
        """The deploy runs in a job needing the uploader, and each other shape is reported.

        Design: ``harness_ci_pipeline.md`` section 7.4.6.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        step(1, "plant a generating job and a deploying job that needs it")
        split = plant_workflow(
            tmp_path / "split",
            "  publish:",
            "    runs-on: ubuntu-26.04",
            *GENERATE,
            "  deploy:",
            "    needs: [publish]",
            "    runs-on: ubuntu-26.04",
            *PAGES_PERMISSIONS,
            *DEPLOY,
        )
        assert not report_publication_gaps(split), report_publication_gaps(split)

        step(2, "plant a job that uploads and deploys the site itself")
        same = plant_workflow(
            tmp_path / "same",
            "  publish:",
            "    runs-on: ubuntu-26.04",
            *PAGES_PERMISSIONS,
            *GENERATE,
            "      - uses: actions/deploy-pages@v5",
        )
        assert any("job that uploaded" in gap for gap in report_publication_gaps(same)), (
            report_publication_gaps(same)
        )

        step(3, "plant a generating job that uploads no Pages artifact")
        unloaded = plant_workflow(
            tmp_path / "unloaded",
            "  publish:",
            "    runs-on: ubuntu-26.04",
            *GENERATE[:5],
            "  deploy:",
            "    needs: publish",
            "    runs-on: ubuntu-26.04",
            *PAGES_PERMISSIONS,
            *DEPLOY,
        )
        assert any("upload-pages-artifact" in gap
                   for gap in report_publication_gaps(unloaded)), (
            report_publication_gaps(unloaded)
        )

        step(4, "plant a deploying job that needs no generating job")
        unordered = plant_workflow(
            tmp_path / "unordered",
            "  publish:",
            "    runs-on: ubuntu-26.04",
            *GENERATE,
            "  deploy:",
            "    runs-on: ubuntu-26.04",
            *PAGES_PERMISSIONS,
            *DEPLOY,
        )
        assert any("deploy-pages" in gap and "needs" in gap
                   for gap in report_publication_gaps(unordered)), (
            report_publication_gaps(unordered)
        )

        step(5, "plant a deploying job without the Pages permissions")
        unpermitted = plant_workflow(
            tmp_path / "unpermitted",
            "  publish:",
            "    runs-on: ubuntu-26.04",
            *GENERATE,
            "  deploy:",
            "    needs: publish",
            "    runs-on: ubuntu-26.04",
            *DEPLOY,
        )
        assert any("pages, id-token" in gap
                   for gap in report_publication_gaps(unpermitted)), (
            report_publication_gaps(unpermitted)
        )
