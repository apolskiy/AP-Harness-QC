"""Unit preconditions for how the report is published to GitHub Pages.

Created: 2026-11-19
Last updated: 2026-11-19

This file contains ``TestMQCGroupingPublication``, three cases over the
workflows that publish the report. One asserts that this repository's
workflows generate the report, carry its trend and publish it, and that a
planted workflow missing any of that is reported. One asserts that a workflow
deploying the site never cancels a run in progress on main. One asserts that
the deploy runs in a job of its own after the job that uploaded the site, and
that a deploy in the uploading job, a missing upload, a deploy needing nothing
and a deploying job without the Pages permissions are each reported.

**These run in the ``unit`` precondition gate.** A failure is an instrument
defect, **not a model finding**, so the module carries no priority marker.

Split from ``mqc_uni_grouping.py`` on 2026-11-19, when the deploy split took
that module past the nine-hundred-line runway.

Specified by ``docs/design/harness_ci_pipeline.md`` sections 3.4, 7.4 and 7.4.6.
"""

