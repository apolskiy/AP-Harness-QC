class TestMQCPassw:
    """A pass with a warning is counted apart, and it is a pass."""

    @story("A pass with a warning has its own count")
    def MQC_CMN_UNI_112438_a_case_passing_with_a_warning_is_counted_as_passw(
        self, tmp_path: Path
    ) -> None:
        """One case recording passw is counted under passw, and the run exits 0.

        Design: ``harness_test_taxonomy.md`` section 5.1.2.

        Args:
            tmp_path (Path): Where the wired session and its cases are written.

        Returns:
            None
        """
        step(1, "run a session with a clean pass, a pass with a warning and a bare pass")
        finished = run_wired_session(tmp_path, _CONFTEST, _CASES)
        output = finished.stdout + finished.stderr
        assert "passed: 2" in output and "passw: 1" in output, (
            f"the pass with a warning was not counted apart:\n{output}"
        )

        step(2, "read the exit status")
        assert finished.returncode == 0, (
            f"a run whose only warning is a passw exited {finished.returncode}:\n{output}"
        )

        step(3, "read both conftests for the wiring")
        unwired = unwired_conftests()
        assert not unwired, unwired

