    @story("A precondition passes or fails")
    def MQC_CMN_UNI_112442_a_precondition_passing_with_a_warning_fails_the_run(
        self, tmp_path: Path
    ) -> None:
        """A precondition marked passw exits 3 with its code; a graded passw leaves 0.

        Design: ``harness_test_taxonomy.md`` section 5.1.2.1.

        Args:
            tmp_path (Path): Where the two wired sessions and their cases are written.

        Returns:
            None
        """
        step(1, "run a session where a precondition and a graded case each pass with a warning")
        mixed = tmp_path / "mixed"
        mixed.mkdir()
        finished = run_wired_session(
            mixed, _REFUSING_CONFTEST, _PRECONDITION_WARNED, extra=_LOG_CLI
        )
        output = finished.stdout + finished.stderr
        refused = [line for line in output.splitlines()
                   if "QC_HARNESS_PRECONDITION_WARNED" in line]
        assert finished.returncode == 3 and len(refused) == 1 and (
            "MQC_CMN_UNI_112999" in refused[0] and "MQC_EVL_EVAL_134999" not in refused[0]
        ), f"exit {finished.returncode}, refused {refused}:\n{output}"

        step(2, "run a session where only the graded case passes with a warning")
        graded_only = tmp_path / "graded"
        graded_only.mkdir()
        finished = run_wired_session(graded_only, _REFUSING_CONFTEST, _WARNED, extra=_LOG_CLI)
        assert finished.returncode == 0, (
            f"a graded passw exited {finished.returncode}:\n{finished.stdout}{finished.stderr}"
        )

        step(3, "read both conftests for the refusal")
        unwired = unwired_conftests()
        assert not unwired, unwired

    @story("A pass with a warning has its own count")
    def MQC_CMN_UNI_112439_a_passw_count_has_its_own_row_and_counts_as_a_pass(self) -> None:
        """The row sits between passed and failed, and both rates count it.

        Design: ``cmn_verdict_and_cli.md`` section 7.11.5.

        Returns:
            None
        """
        step(1, "render a band with ten passes, one passw and one failure")
        reported = result_lines(passed=10, passw=1, failed=1, skips=[], heading=Heading("2"))
        labels = [line.split(": ", 1)[0] for line in reported[1:6]]
        assert labels == ["total", "executed", "passed", "passw", "failed"], reported

        step(2, "read the counts and the rates")
        facts = dict(line.split(": ", 1) for line in reported[1:] if ": " in line)
        assert (facts["executed"], facts["execution pass"], facts["total pass"]) == (
            "12", "91.7% (11 of 12)", "91.7% (11 of 12)"
        ), reported

        step(3, "render a band with no passw")
        plain = dict(
            line.split(": ", 1)
            for line in result_lines(passed=1, failed=0, skips=[]) if ": " in line
        )
        assert plain.get("passw") == "0", f"a zero passw count was not printed: {plain}"

    @story("A pass with a warning has its own count")
    def MQC_CMN_UNI_112440_a_passw_observation_counts_toward_every_pass_floor(self) -> None:
        """Nine passw of ten clear the 90% floor exactly, and a P0 passw is no breach.

        Design: ``harness_test_taxonomy.md`` sections 5.1.2 and 7.4.0.

        Returns:
            None
        """
        observations = passing_suite(0) + [
            graded(f"MQC_TASK_{index}::MQC_RULE_r", "passw") for index in range(8)
        ] + [
            graded("MQC_TASK_zero::MQC_RULE_r", "passw", priority=0),
            graded("MQC_TASK_miss::MQC_RULE_r", "fail"),
        ]
        step(1, "compute the verdict over nine passw observations and one failure")
        result = verdict(observations, VerdictConfig(), TODAY)
        assert result.pass_rate == pytest.approx(0.9), (
            f"passw did not count as a pass in the rate: {result.pass_rate}"
        )

        step(2, "read the verdict at the floor")
        assert result.green and "V1" not in result.breached_rules, (
            f"a run at the floor whose P0 observation passed with a warning was red: "
            f"{result.breached_rules}"
        )
