from pathlib import Path

import pytest

from cmn.document_standards import changelog_problems
from cmn.document_citations import (
    citations_in,
    document_sections,
    duplicate_sections,
    unresolved_citations,
)

pytestmark = pytest.mark.unit

_ROOT = Path(__file__).resolve().parents[2]


class TestMQCDocumentCitations:
    """Every citation resolves, and no section number is used twice."""

    def MQC_CMN_UNI_112352_an_unresolved_or_duplicated_citation_is_reported(
        self, tmp_path: Path
    ) -> None:
        """This repository's citations resolve, and the reader is non-vacuous.

        **Both halves are asserted against a constructed tree first**, because
        a check that finds nothing proves nothing until it has been shown
        finding something. The first draft of the heading pattern demanded
        whitespace straight after the number and so missed every top-level
        section, reporting 91 false dangling citations out of 97: a reader
        would have discarded the six real ones with them.

        Returns:
            None
        """
        # THE READER SEES A NUMBER WRITTEN EITHER WAY. `## 8. Title` and
        # `#### 7.13.2 Title` are both used in these documents.
        probe = tmp_path / "docs"
        probe.mkdir()
        (probe / "target_doc.md").write_text(
            "## 8. A top level section\n\n#### 8.1.2 A nested one\n\n"
            "### 2A. A settled one\n",
            encoding="utf-8",
        )
        assert document_sections(probe / "target_doc.md") == ["8", "8.1.2", "2A"], (
            document_sections(probe / "target_doc.md")
        )

        # A DANGLING CITATION IS REPORTED, and a resolving one is not.
        (probe / "citing_doc.md").write_text(
            "See `target_doc.md` section 8 and target_doc.md section 9.4.\n",
            encoding="utf-8",
        )
        reported = unresolved_citations(tmp_path)
        assert any("section 9.4" in entry for entry in reported), reported
        assert not any("section 8," in entry for entry in reported), reported

        # A LINE CARRYING STRIKETHROUGH IS SKIPPED, because a retired row
        # cites what it named while it was live.
        (probe / "citing_doc.md").write_text(
            "~~`target_doc.md` section 9.4~~ was retired.\n", encoding="utf-8"
        )
        assert not unresolved_citations(tmp_path), unresolved_citations(tmp_path)

        # A REPEATED NUMBER IS REPORTED, naming the document and the number.
        (probe / "target_doc.md").write_text(
            "## 8. One\n\n## 8. Another\n", encoding="utf-8"
        )
        duplicated = duplicate_sections(tmp_path)
        assert any("numbers 8 more than once" in entry for entry in duplicated), (
            duplicated
        )

        # AND THE CITATION READER FINDS EVERY NUMBER IN A MULTIPLE CITATION,
        # which `cmn_verdict_and_cli.md sections 7.11.2 and 7.11.3` is.
        (probe / "citing_doc.md").write_text(
            "See `target_doc.md` sections 8 and 8.1.2.\n", encoding="utf-8"
        )
        assert citations_in(probe / "citing_doc.md") == [
            ("target_doc.md", "8"), ("target_doc.md", "8.1.2"),
        ], citations_in(probe / "citing_doc.md")

        # THE PROMPT LOG IS NEVER READ. It is untracked and must not reach a
        # published artifact, so a report quoting it would disclose it.
        logs = tmp_path / ".claude" / "logs"
        logs.mkdir(parents=True)
        (logs / "PROMPT_LOG.md").write_text(
            "`target_doc.md` section 99.99 is cited here.\n", encoding="utf-8"
        )
        assert not any("99.99" in entry for entry in unresolved_citations(tmp_path)), (
            "the prompt log was read, so its content can reach CI output"
        )

        # NOW THE REPOSITORY ITSELF.
        assert not unresolved_citations(_ROOT), (
            f"{len(unresolved_citations(_ROOT))} citation(s) resolve to nothing: "
            f"{unresolved_citations(_ROOT)}"
        )
        assert not duplicate_sections(_ROOT), (
            f"{len(duplicate_sections(_ROOT))} document(s) number a section "
            f"twice, so two citations of one number mean different things: "
            f"{duplicate_sections(_ROOT)}"
        )

    def MQC_CMN_UNI_112381_a_section_number_with_an_inner_letter_is_read_whole(
        self, tmp_path: Path
    ) -> None:
        """A number like ``5A.3`` is one section, cited and numbered whole.

        Read as ``5A`` followed by text, such a heading was no section at all,
        so two of them were never reported as a duplicate and a citation of
        one resolved to ``5A``.

        Design: ``code-style.md`` section 7.3.

        Args:
            tmp_path (Path): Where the constructed documents are written.

        Returns:
            None
        """
        probe = tmp_path / "docs"
        probe.mkdir()
        (probe / "target_doc.md").write_text(
            "## 5A. Judging\n\n### 5A.3 Absent\n\n#### 5A.3 Precedence\n", encoding="utf-8"
        )
        assert document_sections(probe / "target_doc.md") == ["5A", "5A.3", "5A.3"], (
            document_sections(probe / "target_doc.md")
        )
        assert any("numbers 5A.3 more than once" in entry
                   for entry in duplicate_sections(tmp_path)), duplicate_sections(tmp_path)

        (probe / "citing_doc.md").write_text(
            "See `target_doc.md` section 5A.4 and `target_doc.md` section 5A.3.\n",
            encoding="utf-8",
        )
        assert citations_in(probe / "citing_doc.md") == [
            ("target_doc.md", "5A.4"), ("target_doc.md", "5A.3"),
        ], citations_in(probe / "citing_doc.md")
        assert any("section 5A.4" in entry for entry in unresolved_citations(tmp_path)), (
            "a citation of a section that does not exist resolved to its parent"
        )

    def MQC_CMN_UNI_112353_a_readme_without_a_changelog_is_reported(
        self, tmp_path: Path
    ) -> None:
        """A repository holding a README holds a changelog.

        **The README is historyless by design.** It describes the current state
        and nothing else, so a figure that moves there records neither when nor
        why, and the why is what a later reader needs. The case repository had a
        README and no changelog while its recorded-response count, its finding
        totals and its precondition count all moved.

        Design: ``code-style.md`` section 7.4.

        Returns:
            None
        """
        # A README ALONE IS REPORTED.
        (tmp_path / "README.md").write_text("A repository.\n", encoding="utf-8")
        reported = changelog_problems(tmp_path)
        assert reported and "no CHANGELOG.md" in reported[0], reported

        # BOTH TOGETHER ARE NOT.
        (tmp_path / "CHANGELOG.md").write_text("# Changelog\n", encoding="utf-8")
        assert not changelog_problems(tmp_path), changelog_problems(tmp_path)

        # AND NEITHER IS NOT A FINDING, because a directory that is not a
        # repository root is not missing anything.
        bare = tmp_path / "nested"
        bare.mkdir()
        assert not changelog_problems(bare), changelog_problems(bare)

        # NOW THIS REPOSITORY.
        assert not changelog_problems(_ROOT), changelog_problems(_ROOT)
