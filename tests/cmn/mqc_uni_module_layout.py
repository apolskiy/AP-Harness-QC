class TestMQCCaseModuleContents:
    """What a collected test module is allowed to define, and what reaches it."""

    def MQC_CMN_UNI_112328_a_case_module_holding_support_code_is_reported(
        self,
    ) -> None:
        """A collected test module holds cases, not the library supporting them.

        **The convention existed and was unwritten**, which is what it cost:
        ``repository_root`` stood four times, byte-identical, once public in
        ``graded_support`` and once privately in each of three case modules. A
        helper nobody owned was cheaper to rewrite than to find.

        **``pytest.ini`` already draws the boundary** with
        ``python_files = mqc_*.py``, so a module outside that glob is support by
        construction. This asserts the other half: that a module inside it holds
        no support.

        **Fixtures are not support.** A ``@pytest.fixture`` is wiring for one
        module's cases, bound to them by name, and moving it would make the
        cases harder to read for a tidier line count.

        **The backlog is declared, not exempted.** Modules predating the rule
        are named in ``config/support_extraction.yaml`` with a reason and an
        expiry, and an expired entry fails this. The list shrinks and never
        grows, because anything undeclared fails here on the day it is written.

        Design: ``harness_test_taxonomy.md`` section 13.

        Returns:
            None
        """
        problems = extraction_problems(
            _ROOT / "tests", _ROOT, _ROOT / "config" / "support_extraction.yaml",
            project_today(),
        )
        assert not problems, (
            f"{len(problems)} case module(s) hold support code that belongs in "
            f"a sibling module, or carry a lapsed declaration: "
            + "; ".join(problems)
        )

    def MQC_CMN_UNI_112527_a_collected_module_no_gate_selects_is_reported(
        self, tmp_path: Path
    ) -> None:
        """A collected module names a gate marker, or every case in it does.

        **Collected is not the same as run.** Every gate runs ``-m <marker>``,
        so a module assigning no ``pytestmark`` and holding no marked case is
        collected, deselected and reported as nothing: the run is green and
        its cases never executed.

        **A module holding no case is not reported.** It contributes nothing
        for a gate to miss, which is why the count of cases is what decides.

        Design: ``harness_test_taxonomy.md`` section 13.6.

        Args:
            tmp_path (Path): Where the constructed modules are written.

        Returns:
            None
        """
        step(1, "read every collected module in this repository")
        assert not ungated_modules(_ROOT), (
            "a collected module carries no gate marker, so its cases are "
            "deselected by every gate: " + "; ".join(ungated_modules(_ROOT))
        )

        case = "    def MQC_CMN_UNI_119999_asserts_something(self) -> None:\n        assert True\n"
        built = tmp_path / "tests"
        built.mkdir()
        step(2, "read a constructed module that assigns no marker at all")
        (built / "mqc_uni_ungated.py").write_text(
            f"class TestMQCUngated:\n{case}", encoding="utf-8"
        )
        reported = ungated_modules(tmp_path)
        assert len(reported) == 1 and "mqc_uni_ungated.py" in reported[0], reported

        step(3, "read a module whose only marker selects nothing a gate runs")
        (built / "mqc_uni_ungated.py").write_text(
            f"import pytest\n\npytestmark = pytest.mark.base\n\n\n"
            f"class TestMQCUngated:\n{case}",
            encoding="utf-8",
        )
        assert len(ungated_modules(tmp_path)) == 1, (
            "a module marked only with base was read as gated, and no gate "
            "runs -m base"
        )

        step(4, "read the same module once it assigns a gate marker")
        (built / "mqc_uni_ungated.py").write_text(
            f"import pytest\n\npytestmark = pytest.mark.unit\n\n\n"
            f"class TestMQCUngated:\n{case}",
            encoding="utf-8",
        )
        assert not ungated_modules(tmp_path), "a module marked unit was reported"

        step(5, "read a module marking each case rather than the module")
        (built / "mqc_uni_ungated.py").write_text(
            "import pytest\n\n\nclass TestMQCUngated:\n"
            "    @pytest.mark.sec\n"
            "    def MQC_CMN_UNI_119999_asserts_something(self) -> None:\n"
            "        assert True\n",
            encoding="utf-8",
        )
        assert not ungated_modules(tmp_path), (
            "a module whose every case carries a gate marker of its own was "
            "reported, and each of those cases is selected"
        )

        step(6, "read a module whose class carries the marker its cases inherit")
        (built / "mqc_uni_ungated.py").write_text(
            f"import pytest\n\n\n@pytest.mark.unit\nclass TestMQCUngated:\n{case}",
            encoding="utf-8",
        )
        assert not ungated_modules(tmp_path), (
            "a class-level marker was not read as reaching the cases it "
            "decorates, and pytest propagates it to every method"
        )

        step(7, "read a collected module that holds no case at all")
        (built / "mqc_uni_ungated.py").write_text(
            "WHAT_IT_HOLDS = \"a constant and nothing else\"\n", encoding="utf-8"
        )
        assert not ungated_modules(tmp_path), (
            "a module holding no case was reported, and it contributes nothing "
            "for a gate to miss"
        )


