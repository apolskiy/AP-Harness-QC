from pathlib import Path

import pytest

from cmn.grouping import story
from cmn.junit_outcomes import main, outcomes, report_lines

from tests.cmn.junit_outcomes_support import CLEAN_REPORT, MIXED_REPORT, written

pytestmark = pytest.mark.unit


class TestMQCJUnitOutcomes:
    """What the failure lister reads out of a report, and what it refuses."""

    @story("The failure lister")
    def MQC_CMN_UNI_112432_separates_failures_from_errors_and_refuses_an_absent_report(
        self, tmp_path: Path
    ) -> None:
        """A failure, an error and a clean report each read as they should.

        Asserts four properties of ``cmn.junit_outcomes``:

        * A failing case is listed as failed and an erroring case as broken,
          never together, because the two implicate different code segments.
        * A case carrying both elements counts once, as broken: the instrument
          defect is the one that decides the remedy.
        * A clean report still produces its count line, so a reader can tell
          the tool ran from the tool finding nothing.
        * An absent report and an unparseable one refuse, with exit 4 from
          ``main`` rather than an empty list that reads as a green leg.

        Args:
            tmp_path (Path): pytest's per-test directory, which is what this
                reads instead of a repository path (`code-style.md` section 8.0).

        Returns:
            None
        """
        report = written(tmp_path, "mixed.xml", MIXED_REPORT)
        failed, broken = outcomes(report)

        assert failed == ["pkg.mod.TestOne MQC_CMN_UNI_999002_fails"], (
            "QC_HARNESS_ASSERTION_FAILED: only the failing case belongs in the "
            f"failed list, got {failed}"
        )
        # BOTH THE ERRORING CASE AND THE ONE CARRYING BOTH, which is the
        # counted-once property: four cases, one passed, one failed, two broken.
        assert broken == [
            "pkg.mod.TestOne MQC_CMN_UNI_999003_breaks",
            "pkg.mod.TestOne MQC_CMN_UNI_999004_does_both",
        ], (
            "QC_HARNESS_ASSERTION_FAILED: an erroring case, and one carrying a "
            f"failure as well, are both broken exactly once, got {broken}"
        )

        lines = report_lines(report, failed, broken)
        assert lines[0].endswith("1 failed, 2 broken"), (
            "QC_HARNESS_ASSERTION_FAILED: the count line leads, carrying both "
            f"figures, got {lines[0]!r}"
        )
        assert sum(1 for line in lines if " failed  " in line) == 1
        assert sum(1 for line in lines if " broken  " in line) == 2

        clean = written(tmp_path, "clean.xml", CLEAN_REPORT)
        clean_lines = report_lines(clean, *outcomes(clean))
        assert clean_lines == [f"{clean}: 0 failed, 0 broken"], (
            "QC_HARNESS_ASSERTION_FAILED: a clean report still states its "
            f"counts, so silence is never the answer, got {clean_lines}"
        )

        # THE REFUSALS. An absent report and a corrupt one are the two ways a
        # leg produces nothing readable, and treating either as an empty
        # failure list is what made the retired command read a broken run as
        # clean.
        with pytest.raises(ValueError, match="QC_HARNESS_PARSER_ERROR"):
            outcomes(tmp_path / "never_written.xml")

        unparseable = written(tmp_path, "truncated.xml", "<testsuites><testsuite>")
        with pytest.raises(ValueError, match="QC_HARNESS_PARSER_ERROR"):
            outcomes(unparseable)

        assert main([str(tmp_path / "never_written.xml")]) == 4, (
            "QC_HARNESS_ASSERTION_FAILED: an unreadable report exits 4, not 0, "
            "because exit 0 on an absent report reads as a green leg"
        )
        assert main([str(report)]) == 0, (
            "QC_HARNESS_ASSERTION_FAILED: a readable report exits 0 whatever it "
            "names, the exit status reporting readability rather than the verdict"
        )
