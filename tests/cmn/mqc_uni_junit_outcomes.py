"""Preconditions for the failure lister, the tool naming which cases went red.

Created: 2026-10-29
Last updated: 2026-10-29

This file contains ``TestMQCJUnitOutcomes``, which builds JUnit reports under
``tmp_path`` and asserts what ``cmn.junit_outcomes`` reads out of them: that a
failing case and an erroring case are listed apart, that a case carrying both
counts once as broken, that the count line is written even for a clean report,
and that an absent or unparseable report refuses rather than reporting no
failures.

It runs in Gate 2 as an ungraded precondition. A failure here means the
operator command both runbooks document is misreading a report, so a reader
told a leg was clean cannot rely on that.

Specified by ``docs/design/cmn_verdict_and_cli.md`` section 7.12.

**The refusal is the case worth having.** A lister that treats an absent
report as an empty failure list reads exactly like a green leg, which is the
defect the retired command shipped with.
"""

