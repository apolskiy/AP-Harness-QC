    def MQC_CMN_UNI_112708_an_entry_kept_through_a_model_change_is_in_force(self) -> None:
        """An entry quarantined with ends_on_model_change false holds through a new model.

        Its window still applies: the same entry past its window is not in force.

        Design: ``cmn_verdict_and_cli.md`` section 4.6.15.

        Returns:
            None
        """
        kept = in_force_cases([_entry(TODAY, ends_on_model_change=False)], TODAY, _NEWER,
                              QUARANTINE_WINDOW_DAYS)
