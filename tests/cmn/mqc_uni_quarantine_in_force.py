"""Unit tests for which quarantine entries are in force, and what an entry must carry.

Created: 2026-11-15
Last updated: 2026-11-15

This file contains ``TestMQCQuarantineInForce``, the three selection rules a
consumer applies at collection through ``in_force_cases`` in
``cmn/quarantine.py``: an entry within its window, or extended, is in force;
an expired entry, by window or by model change, is not; a case with no entry is
not. ``TestMQCQuarantineEntryRecord`` checks what an entry carries: a ticket,
refused where absent; ``originally_quarantined_on``, filled from
``quarantined_on`` where a file omits it and kept by ``reconcile``; and the
retired V5, which no expired entry fires.

A consumer deselects the cases ``in_force_cases`` returns before its run
starts, so an entry in force keeps its case out of every count and an expired
one returns it to selection.

Specified by ``docs/design/cmn_verdict_and_cli.md`` section 4.6.15.

A failure here is **not a model finding**, so the module carries no priority marker, per
``framework-rules.md`` section 3.3.
"""

