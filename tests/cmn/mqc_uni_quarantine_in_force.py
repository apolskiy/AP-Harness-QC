class TestMQCQuarantineEntryRecord:
    """An entry carries its ticket and the day its hold began, and fails no run."""

    def MQC_CMN_UNI_112710_an_entry_without_a_ticket_is_refused(self, tmp_path: Path) -> None:
        """A file holding an entry with no ticket is refused, naming the entry.

        Design: ``cmn_verdict_and_cli.md`` section 4.6.15.

        Args:
            tmp_path (Path): A directory standing in for ``config/``.

        Returns:
            None
        """
        write_quarantine(tmp_path, [{
            "case_id": "MQC_TASK_a::MQC_RULE_r", "reason": "flaky under load",
            "quarantined_on": date(2026, 9, 20), "observed_model": _OBSERVED,
        }])

        step(1, "find an entry without a ticket refused, naming the case")
        with pytest.raises(ValueError, match=r"MQC_TASK_a::MQC_RULE_r.*no ticket"):
            load_quarantine_for(tmp_path, "gemini")

    def MQC_CMN_UNI_112711_an_entry_without_an_original_date_takes_its_quarantine_date(
        self, tmp_path: Path,
    ) -> None:
        """An entry written before the field existed loads with its one date as both.

        One that carries the field keeps it, and loads whether it ends on a model
        change as written, ``true`` where the file omits it.

        Design: ``cmn_verdict_and_cli.md`` section 4.6.15.

        Args:
            tmp_path (Path): A directory standing in for ``config/``.

        Returns:
            None
        """
        stamped = date(2026, 9, 20)
        write_quarantine(tmp_path, [
            {"case_id": "MQC_TASK_a::MQC_RULE_r", "reason": "flaky under load",
             "quarantined_on": stamped, "observed_model": _OBSERVED, "ticket": "MQC-41"},
            {"case_id": "MQC_TASK_b::MQC_RULE_r", "reason": "refuses the format",
             "quarantined_on": stamped, "originally_quarantined_on": _FIRST_HELD,
             "observed_model": _OBSERVED, "ticket": "MQC-42",
             "ends_on_model_change": False},
        ])
        entries = load_quarantine_for(tmp_path, "gemini")
        older, newer = entries[0], entries[1]

        step(1, "find an entry without the field holding its quarantine date as both")
        assert older.originally_quarantined_on == stamped, older

        step(2, "find an entry carrying the field keeping the date its hold began")
        assert newer.originally_quarantined_on == _FIRST_HELD, newer

        step(3, "find ends_on_model_change true where omitted and false where written")
        assert (older.ends_on_model_change, newer.ends_on_model_change) == (True, False), \
            (older, newer)

    def MQC_CMN_UNI_112712_reconciling_a_failure_keeps_the_original_date(self) -> None:
        """Re-stamping a failing case moves its quarantine date and not its first date.

        Design: ``cmn_verdict_and_cli.md`` section 4.6.15.

        Returns:
            None
        """
        entry = _entry(TODAY - timedelta(days=10), originally_quarantined_on=_FIRST_HELD)
        remaining, _ = reconcile([entry], {QUARANTINED_CASE: [False]}, TODAY, _OBSERVED)
        stamped = remaining[0]

        step(1, "find the re-stamped entry dated today")
        assert stamped.quarantined_on == TODAY, stamped

        step(2, "find the date its hold began unmoved")
        assert stamped.originally_quarantined_on == _FIRST_HELD, stamped

    def MQC_CMN_UNI_112713_an_expired_entry_never_fails_the_run(self) -> None:
        """An entry long past its window leaves a passing run green, and V5 does not fire.

        Design: ``cmn_verdict_and_cli.md`` section 4.6.15.

        Returns:
            None
        """
        lapsed = _entry(TODAY - timedelta(days=QUARANTINE_WINDOW_DAYS + 30))
        result = verdict(passing_suite(), VerdictConfig(quarantine=[lapsed]), TODAY)

        step(1, "find a passing run with an expired entry green")
        assert result.green is True, result.breached_rules

        step(2, "find V5 among no breached rules")
        assert "V5" not in result.breached_rules, result.breached_rules
