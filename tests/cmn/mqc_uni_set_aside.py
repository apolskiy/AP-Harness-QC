"""Unit preconditions for a foundation set aside by quarantine, whose dependents still run.

Created: 2026-11-16
Last updated: 2026-11-16

This file contains ``TestMQCSetAsideFoundation``, three cases on the cascade in
``cmn.dependencies``. A dependency on a set-aside foundation is not refused at
collection, a dependent of one runs and is named against it, and a set-aside
foundation that ran in the execution is judged by its recorded outcome.

A consumer sets a foundation aside after deselecting it as quarantined, so the
cases here stand in for that consumer with simulated items.

**These run in the ``unit`` precondition gate.** A failure is an instrument
defect, **not a model finding**, and the module carries no priority marker.

Specified by ``docs/design/cmn_verdict_and_cli.md`` section 10.28.7.
"""

