import pytest

from cmn.case_steps import step
from cmn.dependencies import (
    arrange_dependencies,
    enforce_dependencies,
    record_base_outcome,
    reset_dependency_state,
    set_aside_foundations,
    set_aside_foundations_of,
    unknown_dependencies,
)

from tests.cmn.selection_support import SimulatedItem

pytestmark = pytest.mark.unit

_UNMET = "QC_HARNESS_DEPENDENCY_UNMET"
_FOUNDATION = "90021"
_DEPENDENT = SimulatedItem("MQC_CMN_UNI_90022_rests_on_it", depends=(_FOUNDATION,))
_UNRELATED = SimulatedItem("MQC_CMN_UNI_90023_rests_on_nothing")


class TestMQCSetAsideFoundation:
    """A quarantined foundation is set aside: its dependents run and count."""

    def MQC_CMN_UNI_112443_a_dependency_on_a_set_aside_foundation_is_not_refused(
        self,
    ) -> None:
        """A dependent whose foundation was deselected is refused, unless it is set aside.

        Design: ``cmn_verdict_and_cli.md`` section 10.28.7.

        Returns:
            None
        """
        reset_dependency_state()
        population = [_DEPENDENT, _UNRELATED]
        refused = unknown_dependencies(population)
        set_aside_foundations([_FOUNDATION])
        after = unknown_dependencies(population)
        arranged = list(population)
        arrange_dependencies(arranged)
        reset_dependency_state()
        forgotten = unknown_dependencies(population)

        step(1, "find the deselected foundation reported while nothing sets it aside")
        assert len(refused) == 1 and _FOUNDATION in refused[0], refused

        step(2, "find the dependency known once the foundation is set aside")
        assert not after, after

        step(3, "find the collection arranged rather than refused")
        assert sorted(item.name for item in arranged) == sorted(
            item.name for item in population
        ), arranged

        step(4, "find the declaration forgotten with the rest of the cascade")
        assert len(forgotten) == 1, forgotten

    def MQC_CMN_UNI_112444_a_dependent_of_a_set_aside_foundation_runs_and_is_named(
        self,
    ) -> None:
        """A dependent of a set-aside foundation is not skipped, and is named against it.

        Design: ``cmn_verdict_and_cli.md`` section 10.28.7.

        Returns:
            None
        """
        reset_dependency_state()
        set_aside_foundations([_FOUNDATION])
        skipped = ""
        try:
            enforce_dependencies(_DEPENDENT)
        except pytest.skip.Exception as raised:
            skipped = str(raised)

        step(1, "find the dependent set up without a skip")
        assert not skipped, skipped

        step(2, "find the dependent named against its set-aside foundation")
        assert set_aside_foundations_of(_DEPENDENT) == [_FOUNDATION], (
            set_aside_foundations_of(_DEPENDENT)
        )

        step(3, "find a case resting on nothing set aside named against nothing")
        assert not set_aside_foundations_of(_UNRELATED)

        reset_dependency_state()
        step(4, "find the dependent skipped once nothing sets its foundation aside")
        with pytest.raises(pytest.skip.Exception, match=_UNMET):
            enforce_dependencies(_DEPENDENT)

    def MQC_CMN_UNI_112445_a_measured_set_aside_foundation_is_judged_by_its_outcome(
        self,
    ) -> None:
        """A set-aside foundation that ran and failed still skips its dependents.

        Design: ``cmn_verdict_and_cli.md`` section 10.28.7.

        Returns:
            None
        """
        reset_dependency_state()
        set_aside_foundations([_FOUNDATION])
        record_base_outcome(
            SimulatedItem(f"MQC_CMN_UNI_{_FOUNDATION}_the_foundation", base=True), False
        )

        step(1, "find the dependent of a measured failure skipped")
        with pytest.raises(pytest.skip.Exception, match=_UNMET):
            enforce_dependencies(_DEPENDENT)

        step(2, "find it no longer named against a set-aside foundation")
        assert not set_aside_foundations_of(_DEPENDENT), set_aside_foundations_of(_DEPENDENT)

        reset_dependency_state()
        set_aside_foundations([_FOUNDATION])
        record_base_outcome(
            SimulatedItem(f"MQC_CMN_UNI_{_FOUNDATION}_the_foundation", base=True), True
        )
        held = ""
        try:
            enforce_dependencies(_DEPENDENT)
        except pytest.skip.Exception as raised:
            held = str(raised)
        reset_dependency_state()

        step(3, "find the dependent of a measured pass run normally")
        assert not held, held
