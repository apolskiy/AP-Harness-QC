"""Unit preconditions for a case skipped at setup because an artifact it reads is missing.

Created: 2026-11-16
Last updated: 2026-11-16

The cases here check ``cmn.missing_artifact``. A case whose artifact is missing
skips at setup with ``QC_HARNESS_ARTIFACT_MISSING`` while the other cases run
and count; the skip carries the artifact's kind and path in its message, its
JUnit properties and its Allure labels; a record naming no registered kind, no
path or no explanation is refused; and a run holding such a skip exits 3.

Specified by ``docs/design/harness_test_taxonomy.md`` section 5.1.3. A failure
here is **not a model finding**, so the module carries no priority marker, per
``framework-rules.md`` section 3.3."""

