from pathlib import Path
from xml.etree import ElementTree

import pytest

from cmn.case_steps import step
from cmn.grouping import story
from cmn.missing_artifact import ARTIFACT_MISSING, MissingArtifact, skip_for_missing_artifact
from tests.cmn.missing_artifact_support import LabelledItem
from tests.cmn.wired_session import run_wired_session

pytestmark = pytest.mark.unit

# ONE CASE MISSING ITS ARTIFACT, decided at setup as a reader would decide it.
_CONFTEST = '''
from typing import Any

from cmn.band_summary import result_lines, skipped_cases_from
from cmn.missing_artifact import MissingArtifact, skip_for_missing_artifact


def pytest_runtest_setup(item: Any) -> None:
    if item.name == "test_needs_a_missing_artifact":
        skip_for_missing_artifact(item, MissingArtifact(
            kind="carried_outcome", path="reports/carry.json",
            detail="holds no outcome for foundation 134000",
        ))


def pytest_terminal_summary(terminalreporter: Any, exitstatus: int, config: Any) -> None:
    stats = terminalreporter.stats
    for line in result_lines(
        passed=len(stats.get("passed", [])),
        failed=len(stats.get("failed", [])),
        skips=skipped_cases_from(stats.get("skipped", [])),
    ):
        terminalreporter.write_line(line)
'''

_REFUSING_CONFTEST = _CONFTEST + '''

from cmn.missing_artifact import refuse_missing_artifacts


def pytest_sessionfinish(session: Any, exitstatus: int) -> None:
    refuse_missing_artifacts(session)
'''

_CASES = '''
def test_needs_a_missing_artifact() -> None:
    raise AssertionError("a case whose artifact is missing was executed")


def test_has_its_artifacts() -> None:
    assert True


def test_fails_on_its_own() -> None:
    assert False, "a model finding"
'''

_HELD = '''
def test_has_its_artifacts() -> None:
    assert True
'''


class TestMQCMissingArtifact:
    """A missing artifact skips its own case at setup, and the run says so."""

    @story("A missing artifact skips only its case")
    def MQC_CMN_UNI_112446_a_missing_artifact_skips_only_its_case(
        self, tmp_path: Path
    ) -> None:
        """The case missing its artifact skips unexecuted; the others pass and fail.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.

        Args:
            tmp_path (Path): Where the wired session and its cases are written.

        Returns:
            None
        """
        step(1, "run a session where one of three cases is missing its artifact")
        finished = run_wired_session(tmp_path, _CONFTEST, _CASES, extra=("-rs",))
        output = finished.stdout + finished.stderr
        assert (
            "1 failed, 1 passed, 1 skipped" in output
            and "was executed" not in output
            and f"{ARTIFACT_MISSING}: carried_outcome reports/carry.json" in output
            and "an artifact this case reads is missing" in output
        ), f"the missing artifact did not skip its case alone, unexecuted:\n{output}"

    @story("A missing artifact skips only its case")
    def MQC_CMN_UNI_112447_a_missing_artifact_skip_carries_its_kind_and_path_in_junit(
        self, tmp_path: Path
    ) -> None:
        """The skipped case carries its kind and path as JUnit properties; the others none.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.

        Args:
            tmp_path (Path): Where the wired session, its cases and its XML are written.

        Returns:
            None
        """
        step(1, "run the wired session writing JUnit, and read each case's properties")
        report = tmp_path / "junit.xml"
        run_wired_session(tmp_path, _CONFTEST, _CASES, extra=("--junitxml", str(report)))
        cases = {
            str(element.get("name")): element
            for element in ElementTree.parse(report).getroot().iter("testcase")
        }
        properties = {
            name: [(str(found.get("name")), str(found.get("value")))
                   for found in element.iter("property")]
            for name, element in cases.items()
        }
        skipped = cases["test_needs_a_missing_artifact"].find("skipped")
        assert (
            properties["test_needs_a_missing_artifact"] == [
                ("mqc_artifact_kind", "carried_outcome"),
                ("mqc_artifact_path", "reports/carry.json"),
            ]
            and skipped is not None
            and ARTIFACT_MISSING in str(skipped.get("message"))
            and properties["test_has_its_artifacts"] == []
            and properties["test_fails_on_its_own"] == []
        ), properties

    @story("A missing artifact skips only its case")
    def MQC_CMN_UNI_112448_a_missing_artifact_skip_carries_its_allure_labels(self) -> None:
        """The item gains the code, kind and path as Allure label markers before it skips.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.

        Returns:
            None
        """
        step(1, "skip an item for a missing judgement, and read its label markers")
        item = LabelledItem()
        with pytest.raises(pytest.skip.Exception, match=ARTIFACT_MISSING):
            skip_for_missing_artifact(item, MissingArtifact(
                kind="judgement", path="tests/fixtures/replay/judge.json",
                detail="is not valid JSON",
            ))
        assert item.labels() == [
            ("taxonomy_code", ARTIFACT_MISSING),
            ("artifact_kind", "judgement"),
            ("artifact_path", "tests/fixtures/replay/judge.json"),
        ], item.labels()

    @story("A missing artifact skips only its case")
    def MQC_CMN_UNI_112449_a_missing_artifact_record_without_a_kind_or_path_is_refused(
        self
    ) -> None:
        """An unregistered or empty kind, an empty path and an empty explanation are refused.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.

        Returns:
            None
        """
        step(1, "build a record for each malformed entry, and collect what was accepted")
        malformed = {
            "unregistered kind": ("carry_file", "reports/carry.json", "is absent"),
            "empty kind": ("", "reports/carry.json", "is absent"),
            "empty path": ("carried_outcome", " ", "is absent"),
            "empty explanation": ("carried_outcome", "reports/carry.json", ""),
        }
        accepted = []
        for name, (kind, path, detail) in malformed.items():
            try:
                MissingArtifact(kind=kind, path=path, detail=detail)
            except ValueError:
                continue
            accepted.append(name)
        assert not accepted, f"malformed records were accepted: {accepted}"

    @story("A missing artifact skips only its case")
    def MQC_CMN_UNI_112450_a_run_with_a_missing_artifact_exits_3(self, tmp_path: Path) -> None:
        """A run holding a missing-artifact skip exits 3, over a failure; a clean one exits 0.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.

        Args:
            tmp_path (Path): Where the two wired sessions and their cases are written.

        Returns:
            None
        """
        step(1, "run the refusing session with a missing artifact beside a failure")
        missing = tmp_path / "missing"
        missing.mkdir()
        finished = run_wired_session(missing, _REFUSING_CONFTEST, _CASES)
        held = tmp_path / "held"
        held.mkdir()
        clean = run_wired_session(held, _REFUSING_CONFTEST, _HELD)
        assert (finished.returncode, clean.returncode) == (3, 0), (
            f"exit {finished.returncode} with a missing artifact and {clean.returncode} "
            f"without one:\n{finished.stdout}{clean.stdout}"
        )
