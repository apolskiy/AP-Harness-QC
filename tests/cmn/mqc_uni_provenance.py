# EVERY FIELD, IN THE ORDER A REPORT RENDERS THEM. Written here rather than
# imported from the private tuple it mirrors, so a reordering is a failure
# here rather than a silent change to what a reader sees. **On one line**,
# because the same names stacked one per line are the module's own literal
# again and pylint reports the pair as duplicated.
_FIELDS: tuple[str, ...] = tuple(
    "engine mode requested_model served_version served_digest".split()
)

_RUNNER_FIELDS: tuple[str, ...] = tuple(
    ("runner_os runner_os_release runner_machine python_version package_openai "
     "package_anthropic package_google_genai package_httpx package_httpcore").split()
)

_SPEND_FIELDS: tuple[str, ...] = tuple(
    "candidate_spend_usd judge_spend_usd total_spend_usd max_spend_usd unpriced_models".split()
)

_FAILED_FIELDS: tuple[str, ...] = ("candidate_failed_attempts", "judge_failed_attempts")

_SERVED: dict[str, str] = {
    "served_version": "3.0",
    "served_digest": "ec1d75e892b80a28",
}


class TestMQCProvenanceFields:
    """What a run's provenance carries, and what it says when it knows less."""

    def MQC_CMN_UNI_450000_every_field_is_carried_whatever_the_run_knew(
        self,
    ) -> None:
        """A collector reading two runs compares the same fields.

        **Every key is always present.** A run that wrote fewer fields would
        make two runs incomparable in the one direction provenance exists to
        serve, and the collector would have to tell a field nobody wrote from a
        field whose value happened to be absent.

        Returns:
            None
        """
        fields = provenance_fields(
            engine="gemini",
            mode="live",
            requested_model="gemini-3.8-flash",
            served=_SERVED,
        )
        assert tuple(fields) == _FIELDS
        assert fields["engine"] == "gemini"
        assert fields["mode"] == "live"
        assert fields["requested_model"] == "gemini-3.8-flash"
        assert fields["served_version"] == "3.0"
        assert fields["served_digest"] == "ec1d75e892b80a28"

    def MQC_CMN_UNI_450001_an_absent_value_reads_unrecorded_not_empty(
        self,
    ) -> None:
        """The boundary between a value that is absent and one that is blank.

        **Stated at the empty string exactly**, which is the value a defaulted
        flag and an unreadable provider both produce. A reader handed an empty
        value cannot tell it from a field nobody wrote, and the whole purpose
        of this mapping is that a report states what it knows and what it does
        not.

        Returns:
            None
        """
        fields = provenance_fields(
            engine="", mode="", requested_model="   ", served={}
        )
        assert set(fields.values()) == {"unrecorded"}
        assert tuple(fields) == _FIELDS

    def MQC_CMN_UNI_450002_a_replay_run_records_what_it_replayed(self) -> None:
        """A replay run is not missing its provenance, it has a different one.

        It knows the engine, the mode and the model it asked for, and the
        version that produced its responses is in the fixture rather than at
        the provider. Reporting the version the provider serves **today**
        against a recording made earlier would be the one wrong answer
        available.

        Returns:
            None
        """
        fields = provenance_fields(
            engine="grok",
            mode="replay",
            requested_model="grok-4.7",
            served={},
        )
        assert fields["engine"] == "grok"
        assert fields["mode"] == "replay"
        assert fields["requested_model"] == "grok-4.7"
        assert fields["served_version"] == "unrecorded"
        assert fields["served_digest"] == "unrecorded"


class TestMQCProvenanceRenderings:
    """One mapping, rendered for each artifact that carries it."""

    def MQC_CMN_UNI_450003_the_properties_file_is_written_where_a_report_reads_it(
        self,
        tmp_path: Path,
    ) -> None:
        """An Allure environment block is built from this file and nothing else.

        **The name is not ours to choose**, which is why it is asserted: the
        report reads ``environment.properties`` in the results directory, so a
        file written anywhere else or under any other name produces a report
        naming no model while the run believed it had labelled itself.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        fields = provenance_fields(
            engine="claude",
            mode="live",
            requested_model="claude-opus-5-5",
            served=_SERVED,
        )
        results = tmp_path / "allure-results"
        written = write_provenance(results, fields)

        assert written == results / PROVENANCE_FILE
        assert written.name == "environment.properties"
        lines = written.read_text(encoding="utf-8").splitlines()
        assert lines == [f"{name}={fields[name]}" for name in _FIELDS]

    def MQC_CMN_UNI_450004_the_junit_properties_carry_the_same_mapping(
        self,
    ) -> None:
        """The two artifacts agree because one mapping renders both.

        **This is the drift a single registry prevents, applied to a label.**
        Two writers each composing their own fields is how a JUnit report and
        an Allure report come to disagree about which model a run measured, and
        a collector parsing the first would then contradict the person reading
        the second.

        Returns:
            None
        """
        fields = provenance_fields(
            engine="openai",
            mode="live",
            requested_model="gpt-4.1",
            served=_SERVED,
        )
        pairs = testsuite_properties(fields)

        assert [name for name, _ in pairs] == [
            f"{PROVENANCE_PREFIX}{name}" for name in _FIELDS
        ]
        assert [value for _, value in pairs] == [fields[name] for name in _FIELDS]


class TestMQCProvenanceAdoption:
    """When a run asks a provider what it serves, and when it must not."""

    def MQC_CMN_UNI_450005_a_run_that_is_not_live_asks_no_provider(self) -> None:
        """The split that keeps 960 preconditions off four vendors' endpoints.

        **Asserted by whether the reader was called**, not by what the fields
        say. A run that asked a provider and discarded the answer would produce
        identical fields and spend the call, and the call is the cost: the
        precondition suite runs on every pull request, holds no credential, and
        has nothing to ask.

        Returns:
            None
        """
        replay = Config(engine="gemini", mode="replay")
        live = Config(engine="gemini", mode="live")
        unnamed = Config(engine="", mode="live")

        assert asks_the_provider(live) is True
        assert asks_the_provider(replay) is False
        assert asks_the_provider(unnamed) is False

        reader = Reader(_SERVED)
        fields = adopt_provenance(replay, reader)
        assert not reader.asked
        assert fields["served_version"] == "unrecorded"

        asked = Reader(_SERVED)
        fields = adopt_provenance(live, asked)
        assert asked.asked == [("gemini", "gemini-4-argon")]
        assert fields["served_version"] == "3.0"

    def MQC_CMN_UNI_450006_a_run_writing_no_allure_results_writes_no_file(
        self,
    ) -> None:
        """Provenance is a label, so its absence costs a label and nothing else.

        A run given no Allure destination still builds the mapping, because the
        JUnit rendering is selected by a different flag, and it writes no file
        rather than raising or inventing a directory.

        Returns:
            None
        """
        for config in (
            Config(engine="gemini", mode="replay"),
            Config(engine="gemini", mode="replay", allure_report_dir=""),
            Config(engine="gemini", mode="replay", allure_report_dir=None),
        ):
            fields = adopt_provenance(config, Reader({}))
            assert tuple(fields) == _FIELDS + _RUNNER_FIELDS


class TestMQCRunnerFingerprint:
    """The runner a run ran on, recorded once beside its provenance."""

    def MQC_CMN_UNI_450009_the_runner_fingerprint_names_the_os_python_and_sdk_versions(
        self,
    ) -> None:
        """The fields two runners are compared on, read from this interpreter.

        Design: ``cmn_verdict_and_cli.md`` section 5.6.5.

        Returns:
            None
        """
        fingerprint = runner_fingerprint()
        assert tuple(fingerprint) == _RUNNER_FIELDS, tuple(fingerprint)
        assert fingerprint["runner_os"] == platform.system(), fingerprint
        assert fingerprint["python_version"] == platform.python_version(), fingerprint
        assert fingerprint["package_httpx"] == metadata.version("httpx"), fingerprint
        assert fingerprint["package_openai"] == metadata.version("openai"), fingerprint

    def MQC_CMN_UNI_450010_a_package_not_installed_reads_absent_not_empty(
        self,
    ) -> None:
        """A package the runner lacks is a fact, not a record that failed.

        Returns:
            None
        """

        def missing(name: str) -> str:
            """Report every package as not installed.

            Args:
                name (str): The distribution asked for.

            Returns:
                str: Never returns.

            Raises:
                metadata.PackageNotFoundError: Always.
            """
            raise metadata.PackageNotFoundError(name)

        fingerprint = runner_fingerprint(version_of=missing)
        packages = {name: value for name, value in fingerprint.items()
                    if name.startswith("package_")}
        assert set(packages.values()) == {"absent"}, packages
        assert all(fingerprint.values()), fingerprint

    def MQC_CMN_UNI_450011_the_fingerprint_reaches_both_artifacts_beside_the_provenance(
        self, tmp_path: Path,
    ) -> None:
        """The properties file and the JUnit properties both carry the runner.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        results = tmp_path / "allure-results"
        fields = adopt_provenance(
            Config(engine="gemini", mode="replay", allure_report_dir=str(results)), Reader({})
        )
        assert fields["runner_os"] == platform.system(), fields
        written = (results / PROVENANCE_FILE).read_text(encoding="utf-8").splitlines()
        assert f"runner_os={platform.system()}" in written, written
        names = [name for name, _ in testsuite_properties(fields)]
        assert f"{PROVENANCE_PREFIX}package_openai" in names, names


class TestMQCRunSpend:
    """What a run spent, by role, rendered beside its provenance."""

    def MQC_CMN_UNI_450007_the_spend_fields_carry_each_role_whatever_the_run_priced(
        self,
    ) -> None:
        """Every field is present; a run with no price table reads ``unpriced``.

        Design: ``cmn_verdict_and_cli.md`` section 5.6.4.

        Returns:
            None
        """
        priced = spend_fields(candidate=0.0123456, judge=0.002, max_spend=7.25,
                              priced=True, unpriced=set())
        unpriced = spend_fields(candidate=0.0, judge=0.0, max_spend=0.0,
                                priced=False, unpriced={"model-b", "model-a"})

        assert tuple(priced) == _SPEND_FIELDS and tuple(unpriced) == _SPEND_FIELDS
        assert priced == {
            "candidate_spend_usd": "0.0123", "judge_spend_usd": "0.0020",
            "total_spend_usd": "0.0143", "max_spend_usd": "7.2500",
            "unpriced_models": "none",
        }, priced
        assert unpriced == {
            "candidate_spend_usd": "unpriced", "judge_spend_usd": "unpriced",
            "total_spend_usd": "unpriced", "max_spend_usd": "none",
            "unpriced_models": "model-a,model-b",
        }, unpriced

    def MQC_CMN_UNI_450008_the_spend_reaches_both_artifacts_beside_the_provenance(
        self, tmp_path: Path,
    ) -> None:
        """JUnit gets the spend as prefixed properties; the Allure file gets both mappings.

        Design: ``cmn_verdict_and_cli.md`` section 5.6.4.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        provenance = provenance_fields(engine="gemini", mode="live",
                                       requested_model="gemini-4-argon", served=_SERVED)
        spend = spend_fields(candidate=0.5, judge=0.25, max_spend=7.25,
                             priced=True, unpriced=set())
        results = tmp_path / "allure-results"
        recorded: list[tuple[str, str]] = []

        publish_run_spend(lambda name, value: recorded.append((name, value)),
                          Config(allure_report_dir=str(results)), provenance, spend)

        assert recorded == [(f"{PROVENANCE_PREFIX}{name}", value)
                            for name, value in spend.items()], recorded
        assert (results / PROVENANCE_FILE).is_file(), "no environment.properties was written"
        lines = (results / PROVENANCE_FILE).read_text(encoding="utf-8").splitlines()
        assert lines == [f"{name}={value}" for name, value in
                         [*provenance.items(), *spend.items()]], lines

        unwritten: list[tuple[str, str]] = []
        publish_run_spend(lambda name, value: unwritten.append((name, value)),
                          Config(allure_report_dir=""), provenance, spend)
        assert unwritten == recorded

    def MQC_CMN_UNI_450012_failed_attempts_reach_both_artifacts_per_role_with_retries(
        self, monkeypatch: pytest.MonkeyPatch, minimal_case: EvaluationCase, tmp_path: Path,
    ) -> None:
        """An SDK retry after a 500 counts one failed attempt for each role, in both artifacts.

        Design: ``cmn_verdict_and_cli.md`` section 5.6.4.

        Args:
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.
            minimal_case (EvaluationCase): The candidate case.
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        monkeypatch.setenv("XAI_API_KEY", PLANTED_KEY)
        session = DispatchSession(delay=lambda _seconds: None)
        serve_mock(monkeypatch, reply_handler(WIRE_ENGINES["grok"].reply, failures=(500,)))
        answered = dispatch_case(minimal_case, "grok",
                                 DispatchPlan(mode="live", fixture_root=tmp_path), session, 0)
        assert answered.measured and len(answered.wire_attempts) == 2, answered

        judged = json.loads(json.dumps(WIRE_ENGINES["grok"].reply))
        judged["choices"][0]["message"]["content"] = json.dumps(AWARDED)
        serve_mock(monkeypatch, reply_handler(judged, failures=(500,)))
        channel = JudgeChannel("grok", model="grok-wire", plan=JudgementPlan(budget=session))
        assert channel.invoke(JudgeRequestDouble()) == AWARDED

        spend = session.spend_summary()
        counts = (spend.get("candidate_failed_attempts"), spend.get("judge_failed_attempts"))
        assert counts == ("1", "1"), spend
        recorded: list[tuple[str, str]] = []
        publish_run_spend(lambda name, value: recorded.append((name, value)),
                          Config(allure_report_dir=str(tmp_path / "allure-results")),
                          provenance_fields(engine="grok", mode="live",
                                            requested_model="grok-wire", served={}),
                          spend)
        assert (f"{PROVENANCE_PREFIX}judge_failed_attempts", "1") in recorded, recorded
        written = (tmp_path / "allure-results" / PROVENANCE_FILE).read_text(encoding="utf-8")
        assert "candidate_failed_attempts=1" in written.splitlines(), written

    def MQC_CMN_UNI_450013_a_run_with_no_failed_attempt_publishes_zero_not_none(
        self,
    ) -> None:
        """A run that failed nothing states zero for each role, and the fields follow the spend.

        Design: ``cmn_verdict_and_cli.md`` section 5.6.4.

        Returns:
            None
        """
        spend = DispatchSession().spend_summary()
        assert tuple(spend) == (*_SPEND_FIELDS, *_FAILED_FIELDS), tuple(spend)
        assert [spend[name] for name in _FAILED_FIELDS] == ["0", "0"], spend
