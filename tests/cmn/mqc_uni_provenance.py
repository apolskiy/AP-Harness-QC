"""Unit cases for what a run records about the model it measured against.

Created: 2026-10-29
Last updated: 2026-10-29

Its cases check :mod:`cmn.provenance` and the two functions in
:mod:`cmn.pytest_support` that drive it. ``provenance_fields`` carries every
field whatever it was given and reads an absent value as ``unrecorded``;
``write_provenance`` writes the file an Allure environment block is built from;
``testsuite_properties`` renders the same mapping as the properties a JUnit
report carries; and ``adopt_provenance`` asks the provider only where there is
one to ask.

A report that names no model cannot be compared with the one before it, so a
defect here costs the comparison rather than the measurement: every function
under test is permitted to return nothing rather than raise, and the cases hold
that permission to its stated limits. The live and replay split is the one that
costs quota, which is why it is asserted by whether a recording reader was
called at all.

Its cases are listed in the block below, inventoried in
``docs/design/cmn_verdict_and_cli.md`` section 5.6.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.
"""

