from pathlib import Path

import pytest

from cmn.provenance import (
    PROVENANCE_FILE,
    PROVENANCE_PREFIX,
    provenance_fields,
    testsuite_properties,
    write_provenance,
)
from cmn.pytest_support import adopt_provenance, asks_the_provider
from tests.cmn.provenance_support import Config, Reader

pytestmark = pytest.mark.unit

# EVERY FIELD, IN THE ORDER A REPORT RENDERS THEM. Written here rather than
# imported from the private tuple it mirrors, so a reordering is a failure
# here rather than a silent change to what a reader sees. **On one line**,
# because the same names stacked one per line are the module's own literal
# again and pylint reports the pair as duplicated.
_FIELDS: tuple[str, ...] = tuple(
    "engine mode requested_model served_version served_digest".split()
)

_SERVED: dict[str, str] = {
    "served_version": "3.0",
    "served_digest": "ec1d75e892b80a28",
}


class TestMQCProvenanceFields:
    """What a run's provenance carries, and what it says when it knows less."""

    def MQC_CMN_UNI_450000_every_field_is_carried_whatever_the_run_knew(
        self,
    ) -> None:
        """A collector reading two runs compares the same fields.

        **Every key is always present.** A run that wrote fewer fields would
        make two runs incomparable in the one direction provenance exists to
        serve, and the collector would have to tell a field nobody wrote from a
        field whose value happened to be absent.

        Returns:
            None
        """
        fields = provenance_fields(
            engine="gemini",
            mode="live",
            requested_model="gemini-3.8-flash",
            served=_SERVED,
        )
        assert tuple(fields) == _FIELDS
        assert fields["engine"] == "gemini"
        assert fields["mode"] == "live"
        assert fields["requested_model"] == "gemini-3.8-flash"
        assert fields["served_version"] == "3.0"
        assert fields["served_digest"] == "ec1d75e892b80a28"

    def MQC_CMN_UNI_450001_an_absent_value_reads_unrecorded_not_empty(
        self,
    ) -> None:
        """The boundary between a value that is absent and one that is blank.

        **Stated at the empty string exactly**, which is the value a defaulted
        flag and an unreadable provider both produce. A reader handed an empty
        value cannot tell it from a field nobody wrote, and the whole purpose
        of this mapping is that a report states what it knows and what it does
        not.

        Returns:
            None
        """
        fields = provenance_fields(
            engine="", mode="", requested_model="   ", served={}
        )
        assert set(fields.values()) == {"unrecorded"}
        assert tuple(fields) == _FIELDS

    def MQC_CMN_UNI_450002_a_replay_run_records_what_it_replayed(self) -> None:
        """A replay run is not missing its provenance, it has a different one.

        It knows the engine, the mode and the model it asked for, and the
        version that produced its responses is in the fixture rather than at
        the provider. Reporting the version the provider serves **today**
        against a recording made earlier would be the one wrong answer
        available.

        Returns:
            None
        """
        fields = provenance_fields(
            engine="grok",
            mode="replay",
            requested_model="grok-4.7",
            served={},
        )
        assert fields["engine"] == "grok"
        assert fields["mode"] == "replay"
        assert fields["requested_model"] == "grok-4.7"
        assert fields["served_version"] == "unrecorded"
        assert fields["served_digest"] == "unrecorded"


class TestMQCProvenanceRenderings:
    """One mapping, rendered for each artifact that carries it."""

    def MQC_CMN_UNI_450003_the_properties_file_is_written_where_a_report_reads_it(
        self,
        tmp_path: Path,
    ) -> None:
        """An Allure environment block is built from this file and nothing else.

        **The name is not ours to choose**, which is why it is asserted: the
        report reads ``environment.properties`` in the results directory, so a
        file written anywhere else or under any other name produces a report
        naming no model while the run believed it had labelled itself.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        fields = provenance_fields(
            engine="claude",
            mode="live",
            requested_model="claude-opus-5-5",
            served=_SERVED,
        )
        results = tmp_path / "allure-results"
        written = write_provenance(results, fields)

        assert written == results / PROVENANCE_FILE
        assert written.name == "environment.properties"
        lines = written.read_text(encoding="utf-8").splitlines()
        assert lines == [f"{name}={fields[name]}" for name in _FIELDS]

    def MQC_CMN_UNI_450004_the_junit_properties_carry_the_same_mapping(
        self,
    ) -> None:
        """The two artifacts agree because one mapping renders both.

        **This is the drift a single registry prevents, applied to a label.**
        Two writers each composing their own fields is how a JUnit report and
        an Allure report come to disagree about which model a run measured, and
        a collector parsing the first would then contradict the person reading
        the second.

        Returns:
            None
        """
        fields = provenance_fields(
            engine="openai",
            mode="live",
            requested_model="gpt-4.1",
            served=_SERVED,
        )
        pairs = testsuite_properties(fields)

        assert [name for name, _ in pairs] == [
            f"{PROVENANCE_PREFIX}{name}" for name in _FIELDS
        ]
        assert [value for _, value in pairs] == [fields[name] for name in _FIELDS]


class TestMQCProvenanceAdoption:
    """When a run asks a provider what it serves, and when it must not."""

    def MQC_CMN_UNI_450005_a_run_that_is_not_live_asks_no_provider(self) -> None:
        """The split that keeps 960 preconditions off four vendors' endpoints.

        **Asserted by whether the reader was called**, not by what the fields
        say. A run that asked a provider and discarded the answer would produce
        identical fields and spend the call, and the call is the cost: the
        precondition suite runs on every pull request, holds no credential, and
        has nothing to ask.

        Returns:
            None
        """
        replay = Config(engine="gemini", mode="replay")
        live = Config(engine="gemini", mode="live")
        unnamed = Config(engine="", mode="live")

        assert asks_the_provider(live) is True
        assert asks_the_provider(replay) is False
        assert asks_the_provider(unnamed) is False

        reader = Reader(_SERVED)
        fields = adopt_provenance(replay, reader)
        assert not reader.asked
        assert fields["served_version"] == "unrecorded"

        asked = Reader(_SERVED)
        fields = adopt_provenance(live, asked)
        assert asked.asked == [("gemini", "gemini-3.8-flash")]
        assert fields["served_version"] == "3.0"

    def MQC_CMN_UNI_450006_a_run_writing_no_allure_results_writes_no_file(
        self,
    ) -> None:
        """Provenance is a label, so its absence costs a label and nothing else.

        A run given no Allure destination still builds the mapping, because the
        JUnit rendering is selected by a different flag, and it writes no file
        rather than raising or inventing a directory.

        Returns:
            None
        """
        for config in (
            Config(engine="gemini", mode="replay"),
            Config(engine="gemini", mode="replay", allure_report_dir=""),
            Config(engine="gemini", mode="replay", allure_report_dir=None),
        ):
            fields = adopt_provenance(config, Reader({}))
            assert tuple(fields) == _FIELDS
