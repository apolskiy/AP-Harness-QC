from pathlib import Path

import pytest

from cmn.grouping import story

from tools.enumerate_consumers import paired_consumers
from tools.resolve_requested_tests import (
    requested_names,
    selection_expression,
    unmatched_names,
)
from tools.enumerate_consumers import main as enumerate_main
from tools.resolve_requested_tests import main as resolve_main

pytestmark = pytest.mark.unit

_ENCODING = "utf-8"

# A COLLECTION TRANSCRIPT, not a real one. The resolver asks only whether a
# requested name appears in what pytest printed, so a planted transcript
# exercises it without a collection that takes a minute.
_COLLECTED = (
    "tests/cmn/mqc_uni_verdict.py::TestMQCPriorityGate::"
    "MQC_CMN_UNI_112000_green_when_all_rules_satisfied\n"
    "tests/cmn/mqc_uni_verdict.py::TestMQCPriorityGate::"
    "MQC_CMN_UNI_112001_red_when_p0_observation_fails\n"
)

_REGISTRY = (
    "consumers:\n"
    "  - name: AP-Model-QC\n"
    "    default_ref: main\n"
    "    refs:\n"
    "      harness-candidate: cases-candidate\n"
)


class TestMQCStepPrograms:
    """What each step program accepts, and what it refuses rather than gates on."""

    @story("The step programs")
    def MQC_CMN_UNI_112435_a_step_program_refuses_what_would_measure_or_verify_nothing(
        self, tmp_path: Path
    ) -> None:
        """The resolver and the enumerator each refuse their green-run input.

        Asserts, for ``tools.resolve_requested_tests``:

        * A collected identifier resolves, and the expression it builds joins
          several with ``or``, which is the union pytest's selector takes.
        * An unknown identifier is reported and ``main`` exits 3, rather than
          leaving pytest to select nothing and exit 0.
        * An empty request exits 3 for the same reason.

        And for ``tools.enumerate_consumers``:

        * A harness branch the registry maps resolves to its mapped ref.
        * One it does not map falls back to the consumer's ``default_ref``,
          which is the behaviour that cannot be expressed in a workflow
          expression and is why this is a program at all.
        * An absent registry refuses, rather than returning an empty list that
          would fan out over nothing and report success.

        Args:
            tmp_path (Path): pytest's per-test directory, which is where every
                registry and output file goes (`code-style.md` section 8.0).

        Returns:
            None
        """
        assert requested_names(" a , b \n\n c ") == ["a", "b", "c"], (
            "QC_HARNESS_ASSERTION_FAILED: identifiers split on commas and "
            "newlines, blanks dropped and order kept"
        )
        assert selection_expression(["one", "two"]) == "one or two", (
            "QC_HARNESS_ASSERTION_FAILED: the expression joins with or, which "
            "selects the union"
        )
        assert not unmatched_names(["MQC_CMN_UNI_112000"], _COLLECTED)
        assert unmatched_names(["MQC_CMN_UNI_999999"], _COLLECTED) == [
            "MQC_CMN_UNI_999999"
        ], (
            "QC_HARNESS_ASSERTION_FAILED: an identifier the collection does "
            "not contain is reported, because selecting nothing reads as a run "
            "where everything passed"
        )

        # THE EMPTY REQUEST REFUSES WITH 3, a precondition failure: nothing was
        # measured and nothing should be.
        output = tmp_path / "step_output.txt"
        output.write_text("", encoding=_ENCODING, newline="\n")
        assert resolve_main(["--tests", "  ", "--output", str(output)]) == 3, (
            "QC_HARNESS_ASSERTION_FAILED: an empty request exits 3 rather than "
            "resolving to an expression that selects everything"
        )
        assert not output.read_text(encoding=_ENCODING), (
            "QC_HARNESS_ASSERTION_FAILED: a refusal writes no output, so a "
            "later step cannot read a resolution that was never made"
        )

        registry = tmp_path / "consumers.yaml"
        registry.write_text(_REGISTRY, encoding=_ENCODING, newline="\n")

        mapped = paired_consumers(registry, "harness-candidate")
        assert [entry["ref"] for entry in mapped] == ["cases-candidate"], (
            "QC_HARNESS_ASSERTION_FAILED: a mapped branch takes its mapped "
            f"ref, got {mapped}"
        )
        # THE FALLBACK IS WHY THIS IS A PROGRAM. A workflow expression cannot
        # express it without naming branches.
        unmapped = paired_consumers(registry, "some-other-branch")
        assert [entry["ref"] for entry in unmapped] == ["main"], (
            "QC_HARNESS_ASSERTION_FAILED: an unmapped branch falls back to "
            f"default_ref, got {unmapped}"
        )

        with pytest.raises(ValueError, match="QC_HARNESS_PARSER_ERROR"):
            paired_consumers(tmp_path / "absent.yaml", "main")

        assert enumerate_main([
            "--branch", "main", "--sha", "abc123",
            "--registry", str(tmp_path / "absent.yaml"),
            "--output", str(output),
        ]) == 4, (
            "QC_HARNESS_ASSERTION_FAILED: an absent registry exits 4 rather "
            "than fanning out over an empty list and reporting success"
        )

        assert enumerate_main([
            "--branch", "harness-candidate", "--sha", "abc123",
            "--registry", str(registry), "--output", str(output),
        ]) == 0
        written = output.read_text(encoding=_ENCODING)
        assert "cases-candidate" in written and "harness_sha=abc123" in written, (
            "QC_HARNESS_ASSERTION_FAILED: the enumerator writes the resolved "
            f"ref and the commit the matrix reads, got {written!r}"
        )
