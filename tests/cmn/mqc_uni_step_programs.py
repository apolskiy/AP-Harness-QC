"""Preconditions for the two programs a workflow step runs, moved out of the YAML.

Created: 2026-10-29
Last updated: 2026-10-29

This file contains ``TestMQCStepPrograms``, which exercises
``tools.resolve_requested_tests`` and ``tools.enumerate_consumers`` against
registries and output files it builds under ``tmp_path``, and asserts each
refuses the input that would otherwise produce a green run having measured or
verified nothing.

It runs in Gate 2 as an ungraded precondition. Both programs gate a job: the
resolver decides whether a debug run selects anything, and the enumerator
decides which consumer refs a harness candidate is verified against. A failure
here means one of those gates is open.

Specified by ``docs/design/harness_ci_pipeline.md`` section 8.10.

**Both defects these guard are green runs.** A mistyped identifier passing
validation leaves pytest running zero tests and the job reporting success, and
an empty consumer fan-out reports success having verified nothing. Neither is
visible from the job's own status, which is why the refusal is the assertion.
"""

