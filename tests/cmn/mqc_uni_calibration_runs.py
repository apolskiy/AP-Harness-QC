from pathlib import Path

import pytest

from cmn.calibration_runs import deselect_unrequested_calibration
from tests.cmn.calibration_runs_support import MarkedItem
from tests.cmn.mutation_tool_support import AuditConfig

pytestmark = pytest.mark.unit

_CALIBRATION = "MQC_CAS_EVAL_134900_exemplars_score_at_their_level"
_GRADED = "MQC_CAS_EVAL_134000_a_graded_case"


class TestMQCCalibrationRuns:
    """A calibration case runs only where a run asks for it, under a live judge."""

    def MQC_CMN_UNI_112618_a_calibration_case_the_run_did_not_ask_for_is_deselected(
        self, tmp_path: Path
    ) -> None:
        """Every expression not naming calibration, or excluding it, deselects it.

        Design: ``tier3_evaluation.md`` section 9.2.

        Args:
            tmp_path (Path): The repository root.

        Returns:
            None
        """
        calibration = MarkedItem(_CALIBRATION, "evaluator", "calibration")
        graded = MarkedItem(_GRADED, "evaluator")
        for options in (
            {"markexpr": "evaluator or tool or sec", "--mode": "replay"},
            {"markexpr": "evaluator or tool or sec", "--mode": "replay",
             "--judge-mode": "live"},
            {"markexpr": "evaluator and not calibration", "--mode": "replay",
             "--judge-mode": "live"},
            {"markexpr": "", "--mode": "live"},
        ):
            config = AuditConfig(tmp_path, [], options)
            items = [calibration, graded]
            dropped = deselect_unrequested_calibration(config, items)
            assert items == [graded] and dropped == 1, f"{options} kept {items}"
            assert config.hook.deselected == [calibration]

    def MQC_CMN_UNI_112619_a_calibration_case_asked_for_under_a_live_judge_is_kept(
        self, tmp_path: Path
    ) -> None:
        """A marker expression naming calibration, with the judge live, keeps it.

        Design: ``tier3_evaluation.md`` section 9.2.

        Args:
            tmp_path (Path): The repository root.

        Returns:
            None
        """
        calibration = MarkedItem(_CALIBRATION, "evaluator", "calibration")
        for options in (
            {"markexpr": "calibration", "--mode": "replay", "--judge-mode": "live"},
            {"markexpr": "calibration", "--mode": "live"},
        ):
            config = AuditConfig(tmp_path, [], options)
            items = [calibration]
            assert deselect_unrequested_calibration(config, items) == 0
            assert items == [calibration]
            assert not config.hook.deselected

    def MQC_CMN_UNI_112620_calibration_asked_for_without_a_live_judge_is_refused(
        self, tmp_path: Path
    ) -> None:
        """Asking for calibration with a replayed or withheld judge raises.

        Design: ``tier3_evaluation.md`` section 9.2.

        Args:
            tmp_path (Path): The repository root.

        Returns:
            None
        """
        calibration = MarkedItem(_CALIBRATION, "evaluator", "calibration")
        for options in (
            {"markexpr": "calibration", "--mode": "replay"},
            {"markexpr": "calibration", "--mode": "replay", "--judge-mode": "off"},
        ):
            config = AuditConfig(tmp_path, [], options)
            with pytest.raises(ValueError, match="QC_HARNESS_PARSER_ERROR"):
                deselect_unrequested_calibration(config, [calibration])
