from dataclasses import FrozenInstanceError
from pathlib import Path

import pytest

from cmn.code_standards import _MUTABLE_BY_DESIGN, unfrozen_records
from cmn.verdict import Thresholds
from tests.cmn.frozen_support import unfrozen_class_names

pytestmark = pytest.mark.unit

_ROOT = Path(__file__).resolve().parents[2]


class TestMQCFrozenRecords:
    """A validated value cannot be replaced after construction."""

    def MQC_CMN_UNI_112359_a_mutable_production_record_is_reported(self) -> None:
        """Every production record is frozen, or is a declared accumulator.

        **This is what makes the threshold domain check a guarantee.** It runs
        in ``__post_init__``, so an unfrozen record accepts an assignment that
        skips it: a `pass_floor` of `-1` would reach the comparison and the run
        would be judged against a standard nothing validated.

        Returns:
            None
        """
        problems = unfrozen_records(_ROOT)

        assert not problems, (
            f"{len(problems)} mutable production record(s):\n  "
            + "\n  ".join(problems)
        )

        # AND THE RECORD THAT MATTERS MOST REFUSES THE ASSIGNMENT, which is
        # the property the scan above infers from a decorator. Both halves are
        # here because the decorator is what a reader checks and the refusal
        # is what the validation depends on.
        settings = Thresholds()
        with pytest.raises(FrozenInstanceError):
            settings.pass_floor = -1.0

        assert settings.pass_floor == 0.90, (
            "the assignment raised and still took effect, so the record is "
            "frozen in name only"
        )

        # AND THE SCAN IS NOT VACUOUS, proved against the three records that
        # are mutable on purpose: each is genuinely unfrozen, so the scan
        # passing above is the declaration working rather than the walk
        # finding nothing. A declaration naming a frozen record would mean
        # the exemption had outlived its reason.
        for name, reason in _MUTABLE_BY_DESIGN.items():
            assert reason, f"{name} is declared with no reason"
        assert set(_MUTABLE_BY_DESIGN) == unfrozen_class_names(_ROOT), (
            f"the accumulator declaration and the unfrozen records disagree: "
            f"declared {sorted(_MUTABLE_BY_DESIGN)}, found "
            f"{sorted(unfrozen_class_names(_ROOT))}"
        )
