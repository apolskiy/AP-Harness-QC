# FOURTEEN PHASES: seven steps, each an action and a verification. Section 8
# requires both, and a step declaring only an action is one nobody verified.
_PHASES: Final[int] = 14


class TestMQCStepLedger:
    """What a reader is told when a case failed partway through."""

    def MQC_CMN_UNI_112336_a_ledger_names_every_step_and_the_phase_it_stopped_at(
        self,
    ) -> None:
        """Seven steps, two phases each, and the ones that never ran.

        **An early stop hides every later failure**, in the harness and in the
        model both, so the steps nobody reached are reported rather than
        omitted. Section 8.1 keeps the two phases apart because a step can fail
        in either and the diagnoses differ: an action that could not be
        performed is ours and skips, a verification that did not hold is a
        measurement and fails.

        Design: ``harness_test_taxonomy.md`` section 8.

        Returns:
            None
        """
        # A CASE THAT PASSED: every phase ran and nothing stopped.
        entries = ledger(dispatched(), evaluated())
        assert len(entries) == _PHASES, (
            f"a ledger of {len(entries)} phases cannot be seven steps of two, "
            f"so a step is declared without a verification or the reverse"
        )
        assert stopped_at(entries) is None, (
            "a passing observation reports a stop, so every failing one is "
            "indistinguishable from it"
        )
        assert not stopped_line(entries), (
            "a passing observation carries a stopped line, which would reach "
            "every failure message that appends one"
        )

        # AN ASSERTION THAT DID NOT HOLD: the verification fails and the judge
        # steps never run.
        failed = ledger(dispatched(), failed_check())
        halt = stopped_at(failed)
        assert halt is not None and halt.number == 5 and halt.phase == "VERIFY", (
            f"the stop is not reported at the verification of step 5: {halt}"
        )
        assert halt.taxonomy_code == "QC_LLM_SOURCE_ALTERATION", (
            f"the stop carries no model code, so a reader cannot classify it: "
            f"{halt}"
        )
        unrun = [entry for entry in failed if entry.outcome == "not run"]
        assert len(unrun) == 4, (
            f"{len(unrun)} phases are reported as unrun where steps 6 and 7 "
            f"are four, so the steps an early stop hides are not all named"
        )
        assert "4 later phase(s) did not run" in stopped_line(failed), (
            f"the line does not say how much went unmeasured: "
            f"{stopped_line(failed)}"
        )

        # A STEP THAT COULD NOT BE PERFORMED, which is ours and not the
        # model's: section 8.1 makes it a skip, and every later step is unrun.
        stale = ledger(
            dispatched(taxonomy_code="QC_HARNESS_FIXTURE_STALE", response=None),
            None,
        )
        halt = stopped_at(stale)
        assert halt is not None and halt.number == 2, (
            f"a response that never arrived is not reported at step 2: {halt}"
        )
        assert halt.taxonomy_code == "QC_HARNESS_FIXTURE_STALE", (
            f"the stop does not name the harness code, so an instrument defect "
            f"reads as "
            f"a model finding: {halt}"
        )

        # AND EVERY LINE CARRIES THE CASE, per section 8.2.
        lines = summary(_CASE, failed)
        assert all(line.startswith(_CASE) for line in lines), (
            "a line omits the case identifier, so a collector cannot attribute "
            "it"
        )
        assert all("PHASE_" in line for line in lines[:_PHASES]), (
            "a phase line carries no PHASE_ name, so nothing parses it"
        )
        # A PHASE IS NEVER CALLED A STEP, which is section 8.2.2: a step is a
        # dispatch, and "STEP_05" naming a phase is what that section retired.
        assert not any("STEP_" in line for line in lines), (
            f"a pipeline phase is still labelled as a step: {lines[0]}"
        )

    def MQC_CMN_UNI_112337_a_rule_without_a_rubric_reports_its_judge_steps_inapplicable(
        self,
    ) -> None:
        """A suite decided by its assertions did not stop short.

        **Twenty-one security rules and eight tool rules author no rubric**,
        declaring themselves decided by their deterministic checks. Reading
        their unjudged steps as an early halt would report every one of them as
        having stopped early, which is the boundary this case holds.

        Design: ``harness_test_taxonomy.md`` section 8.2.1.

        Returns:
            None
        """
        entries = ledger(
            dispatched(), evaluated(rubric_authored=False, score=None)
        )
        judge = [entry for entry in entries if entry.number >= 6]
        assert len(judge) == 4, "steps 6 and 7 are not four phases"
        assert all(entry.outcome == "not applicable" for entry in judge), (
            f"a rubricless rule reports its judge steps as something other "
            f"than inapplicable: {[entry.outcome for entry in judge]}"
        )
        assert stopped_at(entries) is None, (
            "a rule decided by its assertions is reported as having stopped "
            "early, which would describe the whole security suite that way"
        )
        assert not stopped_line(entries), (
            "a rubricless rule carries a stopped line, which would append to "
            "every security failure message"
        )
        assert "not applicable" in summary(_CASE, entries)[-1], (
            f"the closing line does not say the rest was inapplicable: "
            f"{summary(_CASE, entries)[-1]}"
        )

        # AND A RULE THAT DOES AUTHOR ONE STILL REPORTS A MISSING JUDGEMENT,
        # or this exemption would swallow the gap it was written beside.
        absent = ledger(dispatched(), evaluated(
            score=None, judge_skipped_reason="judgement_unavailable",
            taxonomy_codes=["QC_HARNESS_FIXTURE_MISSING"],
        ))
        halt = stopped_at(absent)
        assert halt is not None and halt.number == 6, (
            f"a rubric that went unscored is not reported: {halt}"
        )
        assert halt.taxonomy_code == "QC_HARNESS_FIXTURE_MISSING", (
            f"the missing judgement does not name its code: {halt}"
        )

    def MQC_CMN_UNI_112398_a_rubric_only_rule_reports_its_check_step_inapplicable(
        self,
    ) -> None:
        """A judged rule carrying no assertion did not stop before its judgement.

        Design: ``harness_test_taxonomy.md`` section 8.2.1.

        Returns:
            None
        """
        # A JUDGED RULE THAT DECLARES NO ASSERTION reaches its judge.
        entries = ledger(dispatched(), evaluated(assertion_results=[]))
        check = [entry for entry in entries if entry.number == 5]
        assert all(entry.outcome == "not applicable" for entry in check), (
            f"a rubric-only rule reports its check step as "
            f"{[entry.outcome for entry in check]}, not as inapplicable"
        )

        assert stopped_at(entries) is None, (
            "a judged rubric-only rule is reported as having stopped before its judge"
        )

        # AND A RESULT NEITHER JUDGED NOR CARRYING AN ASSERTION is still a stop,
        # or this exemption would swallow a check that never ran.
        unjudged = ledger(dispatched(), evaluated(
            assertion_results=[], score=None, judge_skipped_reason="no_judge_configured",
        ))
        halt = stopped_at(unjudged)
        assert halt is not None and halt.number == 5, (
            f"a result that measured nothing is not reported as a stop at step 5: {halt}"
        )


class TestMQCCaseSteps:
    """A graded case's steps are its dispatches, then one comparison."""

    def MQC_CMN_UNI_112388_an_observation_step_verifies_one_request(self) -> None:
        """One dispatch is one step: an action, one verification, its phases beneath.

        Design: ``harness_test_taxonomy.md`` section 8.2.2.

        Returns:
            None
        """
        step = observation_step(2, dispatched(), evaluated())
        assert step.number == 2, step
        assert step.action.label.startswith("STEP_02_ACTION: "), step.action.label
        assert step.verification.label.startswith("STEP_02_VERIFY: "), (
            step.verification.label
        )
        assert (step.action.outcome, step.verification.outcome) == ("ok", "ok"), step

        # THE PIPELINE PHASES SIT BENEATH THE STEP, dispatch under the action
        # and evaluation under the verification, and none is called a step.
        assert len(step.phases) == _PHASES, len(step.phases)
        assert all(entry.label.startswith("PHASE_") for entry in step.phases), (
            [entry.label for entry in step.phases]
        )
        assert [entry.number for entry in step.action_phases] == [1, 1, 2, 2, 3, 3]
        assert {entry.number for entry in step.verification_phases} == {4, 5, 6, 7}

        # A WRONG ANSWER FAILS THE VERIFICATION with the model's code, and the
        # dispatch that produced it stands.
        wrong = observation_step(1, dispatched(), failed_check())
        assert wrong.action.outcome == "ok", wrong.action
        assert wrong.verification.outcome == "failed", wrong.verification
        assert wrong.verification.taxonomy_code == "QC_LLM_SOURCE_ALTERATION", (
            wrong.verification
        )
        # AND THE STEP NAMES THE PHASE, never what the model wrote.
        assert "PHASE_05_VERIFY" in wrong.verification.detail, wrong.verification
        assert "required substring" not in wrong.verification.detail, (
            "the step detail quotes the assertion's finding, which on a security "
            "case is the model's own text"
        )

        # A DISPATCH THAT PRODUCED NOTHING FAILS THE ACTION, a harness event,
        # and leaves the verification unrun rather than failed (section 8.1).
        stale = observation_step(
            1,
            dispatched(taxonomy_code="QC_HARNESS_FIXTURE_STALE", response=None),
            None,
        )
        assert stale.action.outcome == "failed", stale.action
        assert stale.action.taxonomy_code == "QC_HARNESS_FIXTURE_STALE", stale.action
        assert stale.verification.outcome == "not run", stale.verification
        # AND IT SAYS WHY, rather than naming a phase nobody reached.
        assert "PHASE_" not in stale.verification.detail, stale.verification
        assert "no measurement" in stale.verification.detail, stale.verification

        # ONE VERIFICATION LINE PER STEP, every line carrying the case.
        lines = step_lines(_CASE, [wrong])
        assert all(line.startswith(_CASE) for line in lines), lines
        verifications = [line for line in lines if "STEP_" in line and "_VERIFY" in line]
        assert len(verifications) == 1, verifications

    def MQC_CMN_UNI_112389_escalation_steps_not_taken_are_recorded_as_not_run(
        self,
    ) -> None:
        """Steps k+1 and k+2 appear whether or not the case escalated.

        Design: ``harness_test_taxonomy.md`` section 8.2.2.

        Returns:
            None
        """
        size = escalation_size()
        assert size == 2, size

        # THREE AGREED, SO NOTHING WAS EARNED, and the two steps say so.
        agreed = case_steps([(dispatched(), evaluated())] * 3, configured=3)
        assert [step.number for step in agreed] == [1, 2, 3, 4, 5, 6], (
            [step.number for step in agreed]
        )
        for step in agreed[3:5]:
            assert (step.action.outcome, step.verification.outcome) == (
                "not run", "not run"
            ), step
            assert "agreed" in step.action.detail, step.action
            assert not step.phases, "a step that dispatched nothing carries phases"

        # ONE FAILED, SO TWO WERE EARNED AND TAKEN, as observation steps.
        mixed = mixed_observations()
        escalated = case_steps(mixed, configured=3)
        assert len(escalated) == 6, len(escalated)
        for step in escalated[3:5]:
            assert step.action.outcome == "ok", step.action
            assert step.phases, "a taken escalation step carries no phases"

        # EARNED AND NOT DISPATCHED is not agreement, and the record says which.
        short = case_steps(mixed[:3], configured=3)
        assert len(short) == 6, len(short)
        assert short[3].action.outcome == "not run", short[3].action
        assert "agreed" not in short[3].action.detail, short[3].action
        assert "not dispatched" in short[3].action.detail, short[3].action

    def MQC_CMN_UNI_112390_the_last_step_verifies_only_the_agreement(self) -> None:
        """The comparison fails on disagreement alone and touches no request.

        Design: ``harness_test_taxonomy.md`` section 8.2.2.

        Returns:
            None
        """
        agreed = case_steps([(dispatched(), evaluated())] * 3, configured=3)
        last = agreed[-1]
        assert last.action.label.startswith("STEP_06_ACTION: "), last.action.label
        assert last.verification.outcome == "ok", last.verification
        assert not last.phases, "the comparison step verifies a request"

        # A DISAGREEMENT FAILS THE COMPARISON ONLY. The observation that failed
        # keeps its own code and the others stay verified.
        mixed = case_steps(mixed_observations(), configured=3)
        assert mixed[-1].verification.outcome == "failed", mixed[-1].verification
        assert mixed[-1].verification.taxonomy_code == "QC_LLM_INCONSISTENT", (
            mixed[-1].verification
        )
        assert "4 of 5" in mixed[-1].verification.detail, mixed[-1].verification
        assert [step.verification.outcome for step in mixed[:5]] == [
            "ok", "failed", "ok", "ok", "ok"
        ], [step.verification.outcome for step in mixed[:5]]
        assert mixed[1].verification.taxonomy_code == "QC_LLM_SOURCE_ALTERATION"

        # FAILING EVERY TIME IS AGREEMENT. The observation steps carry the
        # failure; the comparison verifies only that they concur.
        failing = case_steps([(dispatched(), failed_check())] * 5, configured=3)
        assert failing[-1].verification.outcome == "ok", failing[-1].verification
        assert all(step.verification.outcome == "failed" for step in failing[:5])

        # AN OBSERVATION THAT MEASURED NOTHING IS NOT A DISAGREEMENT.
        holed = case_steps(
            [(dispatched(), evaluated()), (dispatched(), unmeasured())]
            + [(dispatched(), evaluated())] * 3,
            configured=3,
        )
        assert holed[1].verification.outcome == "not run", holed[1].verification
        assert holed[-1].verification.outcome == "ok", holed[-1].verification
        assert "4 measured" in holed[-1].verification.detail, holed[-1].verification



class TestMQCCaseAnnouncement:
    """A case says its own name before it runs, whatever happens next."""

    def MQC_CMN_UNI_112347_a_case_announces_its_node_identifier_before_running(
        self, caplog: pytest.LogCaptureFixture
    ) -> None:
        """The line carries the module, the class and the case.

        **A traceback names the line that raised, not the case that reached
        it**, and the two differ whenever a helper is shared, which in this
        suite is most of the time. A process killed mid-request leaves no
        traceback at all, so the last announced name is the only thing that
        locates the work.

        Design: ``harness_test_taxonomy.md`` section 8.3.1.

        Returns:
            None
        """
        node = (
            "tests/cmn/mqc_uni_steps.py::TestMQCProbe::"
            "MQC_CMN_UNI_119000_a_probe"
        )
        announced = announce_test(Announced(node))

        assert announced == f"RUNNING {node}", announced

        # THE MODULE, THE CLASS AND THE CASE, which is the code segment a
        # reader opens. The callable's name alone names no file.
        for part in ("mqc_uni_steps.py", "TestMQCProbe", "MQC_CMN_UNI_119000"):
            assert part in announced, f"{part} is absent from {announced}"

        # AND IT IS LOGGED, not only returned, because the log is what survives
        # a crash and reaches the JUnit artifact on a failure.
        with caplog.at_level(logging.INFO, logger="cmn.pytest_support"):
            announce_test(Announced(node))
        assert any(
            record.getMessage() == f"RUNNING {node}"
            for record in caplog.records
        ), (
            "the announcement was not logged: "
            f"{[entry.getMessage() for entry in caplog.records]}"
        )

        # AN ITEM CARRYING NO IDENTIFIER STILL ANNOUNCES SOMETHING, because a
        # hook that raised here would turn a reporting aid into a run failure.
        assert announce_test(Announced(None)) == "RUNNING ?"
