from pathlib import Path

import pytest

from cmn.case_steps import step
from cmn.code_standards import unregistered_code_literals

pytestmark = pytest.mark.unit


class TestMQCCodeRegistration:
    """A code is registered before any production code names it."""

    def MQC_CMN_UNI_112262_every_code_production_code_names_is_registered(
        self, tmp_path: Path
    ) -> None:
        """The harness names no unregistered code, and a planted one is reported.

        Args:
            tmp_path (Path): A repository root for the positive control.

        Returns:
            None
        """
        step(1, "read this repository's production code")
        found = unregistered_code_literals(Path(__file__).resolve().parents[2])
        assert not found, "production code names unregistered codes: " + "; ".join(found)

        step(2, "plant a module naming one registered and one unregistered code")
        (tmp_path / "cmn").mkdir()
        (tmp_path / "cmn" / "planted.py").write_text(
            'FOUND = "QC_HARNESS_PARSER_ERROR"\n'
            'MISSING = f"QC_HARNESS_INVENTED_HERE: {FOUND}"\n',
            encoding="utf-8",
        )
        (tmp_path / "tests").mkdir()
        (tmp_path / "tests" / "planted_case.py").write_text(
            'IGNORED = "QC_LLM_INVENTED_IN_A_TEST"\n', encoding="utf-8"
        )
        assert unregistered_code_literals(tmp_path) == [
            "cmn/planted.py:2 QC_HARNESS_INVENTED_HERE"
        ], f"the planted tree reported {unregistered_code_literals(tmp_path)}"
