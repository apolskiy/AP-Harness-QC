class TestMQCMutationBaseline:
    """The audit refuses a baseline it cannot vouch for."""

    @story("A baseline that is not the declared one")
    def MQC_CMN_UNI_112363_a_module_not_matching_its_declared_digest_is_refused(
        self, tmp_path: Path
    ) -> None:
        """An unparsed module is refused although it parses and passes.

        **This is the state the backup could not detect.** Unparsing is
        idempotent, so an already-stripped module changes nothing when the
        control gate unparses it and the control passes; the digest is what
        separates it from the module the survivors were measured against.

        Both directions are asserted: the declared content is accepted, and
        an undeclared module is refused rather than defaulting to trusted.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        digest = module_digest(SOURCE)
        manifest = write_manifest(tmp_path, digest)

        assert baseline_problem(manifest, MODULE, SOURCE) is None

        stripped = ast.unparse(ast.parse(SOURCE))
        assert stripped != SOURCE, "the fixture must carry strippable prose"
        refusal = baseline_problem(manifest, MODULE, stripped)
        assert refusal is not None, (
            "QC_HARNESS_PARSER_ERROR: an unparsed baseline was accepted, "
            "which is the state that perpetuated itself"
        )
        assert module_digest(stripped) in refusal, refusal

        # AND THE REFUSAL NAMES THE REMEDY, which is what separates this from
        # the mismatch above. Asserting only that something was refused passes
        # on the mismatch message, which tells a reader the module hashes to
        # one value and None was declared: true, and no help.
        undeclared = baseline_problem(manifest, "cmn/absent.py", SOURCE)
        assert undeclared is not None, (
            "QC_HARNESS_PARSER_ERROR: a module declaring no digest was "
            "accepted, so nothing establishes what it should contain"
        )
        assert "declares no baseline digest" in undeclared, undeclared
        assert f"digest: {digest}" in undeclared, (
            "QC_HARNESS_PARSER_ERROR: the refusal does not carry the value to "
            f"declare, so a reader has to compute it: {undeclared}"
        )

    @story("A control killed part-way through")
    def MQC_CMN_UNI_112364_a_control_rewrite_leaves_a_recoverable_backup(
        self, tmp_path: Path
    ) -> None:
        """The control's unparse happens with the backup already on disk.

        **The backup was written after the control and is now written before
        it.** The control is a full suite run while a mutant stops at its
        first failure, so this was the longest unguarded window in the audit:
        a run killed inside it left a stripped module and no backup at all.

        Asserted by rewriting as the control does, abandoning it, and checking
        that recovery restores the original rather than the rewrite.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        module = tmp_path / "sample.py"
        module.write_text(SOURCE, encoding="utf-8", newline="\n")
        backup = module.with_suffix(module.suffix + _BACKUP_SUFFIX)
        backup.write_text(SOURCE, encoding="utf-8", newline="\n")

        # THE CONTROL'S OWN REWRITE, abandoned rather than restored, which is
        # what a killed process leaves.
        module.write_text(
            ast.unparse(ast.parse(SOURCE)), encoding="utf-8", newline="\n"
        )
        assert module.read_text(encoding="utf-8") != SOURCE

        recovered = recover(module)
        assert recovered is not None, (
            "QC_HARNESS_PARSER_ERROR: an abandoned control rewrite was not "
            "reported, so the next run would adopt it as its baseline"
        )
        assert module.read_text(encoding="utf-8") == SOURCE
        assert not backup.exists(), "the backup is consumed by the recovery"

        # AND THE CONTROL TAKES ITS BASELINE FROM THE CALLER, which is what
        # keeps its rewrite inside the window the backup above guards.
        names = control_problem.__code__.co_varnames[
            : control_problem.__code__.co_argcount
        ]
        assert "original" in names, (
            "QC_HARNESS_PARSER_ERROR: the control reads the module itself "
            "again, which puts its rewrite outside the backup window"
        )

    @story("Declaring a digest keeps the reasons")
    def MQC_CMN_UNI_112365_a_declared_digest_is_written_without_losing_the_reasons(
        self, tmp_path: Path
    ) -> None:
        """The writer edits in place, so comments and expiries survive it.

        **Re-serializing would pass a round-trip and lose the file.** Dumping
        the parsed mapping back produces a manifest that reads correctly and
        carries no reasons, and section 15.2 requires every accepted survivor
        to state one. So the assertion is on the prose as much as on the
        value.

        Three states are covered: a module with an entry and no digest, a
        module whose digest is replaced, and a module with no entry at all.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        manifest = tmp_path / "mutation_survivors.yaml"
        manifest.write_text(
            "# why each entry is accepted\n"
            "survivors:\n"
            f"  {MODULE}:\n"
            "    accepted:\n"
            '      - mutation: "line 1: True to False"\n'
            "        kind: equivalent\n"
            "        reason: the branch is unreachable\n"
            "        expires_on: 2026-12-31\n",
            encoding="utf-8", newline="\n",
        )

        first = module_digest(SOURCE)
        declare_digest(manifest, MODULE, first)
        assert declared_survivors(manifest)[MODULE]["digest"] == first

        # THE REASONS SURVIVE, which re-serializing would not manage.
        kept = manifest.read_text(encoding="utf-8")
        assert "# why each entry is accepted" in kept, kept
        assert "the branch is unreachable" in kept, kept
        assert "expires_on: 2026-12-31" in kept, kept

        # AND A SECOND DECLARATION REPLACES RATHER THAN ACCUMULATES.
        second = module_digest(SOURCE + "\n# edited\n")
        declare_digest(manifest, MODULE, second)
        assert declared_survivors(manifest)[MODULE]["digest"] == second
        assert manifest.read_text(encoding="utf-8").count("digest:") == 1

        # A MODULE WITH NO ENTRY AT ALL, which is audited and accepts nothing.
        declare_digest(manifest, "cmn/other.py", first)
        declared = declared_survivors(manifest)
        assert declared["cmn/other.py"]["digest"] == first
        assert "accepted" not in declared["cmn/other.py"]
        assert declared[MODULE]["digest"] == second, "the first entry moved"


class TestMQCMutationLock:
    """One audit at a time, and a dead one does not hold a module forever."""

    @story("A live audit holds the module")
    def MQC_CMN_UNI_112377_an_audit_refuses_a_module_a_live_audit_holds(
        self, tmp_path: Path
    ) -> None:
        """A lock naming a live process refuses the audit and names it.

        This process is the live holder. On Windows the liveness check must not
        signal it, or asking would terminate the test itself.

        Design: ``harness_test_taxonomy.md`` section 15.11.

        Args:
            tmp_path (Path): Where the module and its lock are written.

        Returns:
            None
        """
        module = tmp_path / "held.py"
        module.write_text("VALUE = 1\n", encoding="utf-8")
        assert process_alive(os.getpid()), "this process reads as not running"

        acquire_lock(module)
        try:
            with pytest.raises(MutationRefusal, match=str(os.getpid())):
                acquire_lock(module)
        finally:
            release_lock(module)
        assert not list(tmp_path.glob("*.mutation-lock")), "the lock outlived its audit"

    @story("A dead audit's lock is cleared")
    def MQC_CMN_UNI_112378_a_lock_left_by_a_dead_audit_is_cleared(
        self, tmp_path: Path
    ) -> None:
        """A lock whose process has exited is replaced, not obeyed.

        Design: ``harness_test_taxonomy.md`` section 15.11.

        Args:
            tmp_path (Path): Where the module and its lock are written.

        Returns:
            None
        """
        finished = subprocess.run(
            [sys.executable, "-c", "import os; print(os.getpid())"],
            capture_output=True, text=True, check=True, timeout=60,
            stdin=subprocess.DEVNULL,
        )
        dead = int(finished.stdout.strip())
        assert not process_alive(dead), f"process {dead} exited and reads as running"

        module = tmp_path / "abandoned.py"
        module.write_text("VALUE = 1\n", encoding="utf-8")
        lock = module.with_suffix(".py.mutation-lock")
        lock.write_text(f'{{"pid": {dead}, "started": "2026-10-13T00:00:00"}}',
                        encoding="utf-8")

        acquire_lock(module)
        try:
            assert str(os.getpid()) in lock.read_text(encoding="utf-8"), (
                "a dead audit's lock was not replaced by this one"
            )
        finally:
            release_lock(module)


class TestMQCMutationCrash:
    """An audit runs without a terminal and leaves nothing behind when it crashes."""

    @story("No standard input")
    def MQC_CMN_UNI_112383_an_audit_run_reads_no_standard_input(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """Every pytest run the audit starts reads ``DEVNULL``.

        Design: ``harness_test_taxonomy.md`` section 15.5.1.

        Args:
            tmp_path (Path): The directory the run is started in.
            monkeypatch (pytest.MonkeyPatch): Replaces the process launcher.

        Returns:
            None
        """
        seen: list[dict[str, Any]] = []

        def launched(command: list[str], **options: Any) -> subprocess.CompletedProcess:
            seen.append(options)
            return subprocess.CompletedProcess(command, 0, "1 passed", "")

        monkeypatch.setattr(mutation_audit.subprocess, "run", launched)
        run_targets(tmp_path, ["tests/x.py"], stop_early=True)

        assert seen and seen[0].get("stdin") is subprocess.DEVNULL, (
            "QC_HARNESS_PREFLIGHT_FAILURE: an audit run inherits the caller's "
            "standard input, so a session without one cannot start it"
        )

    @story("A crashed control leaves no backup")
    def MQC_CMN_UNI_112384_a_control_that_raises_leaves_no_backup(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A control that raises restores the module and removes its backup.

        Design: ``harness_test_taxonomy.md`` section 15.5.1.

        Args:
            tmp_path (Path): The repository root the audit works in.
            monkeypatch (pytest.MonkeyPatch): Makes the control's run raise.

        Returns:
            None
        """
        module = tmp_path / MODULE
        module.parent.mkdir(parents=True)
        module.write_text(SOURCE, encoding="utf-8", newline="\n")
        manifest = tmp_path / "config" / "mutation_survivors.yaml"
        manifest.parent.mkdir()
        write_manifest(manifest.parent, module_digest(SOURCE))

        def crashed(*_: Any, **__: Any) -> subprocess.CompletedProcess:
            raise OSError("the handle is invalid")

        monkeypatch.setattr(mutation_audit, "run_targets", crashed)
        with pytest.raises(OSError):
            survivors(tmp_path, module, ["tests/x.py"])

        assert module.read_text(encoding="utf-8") == SOURCE, "the module was not restored"
        backup = module.with_suffix(module.suffix + _BACKUP_SUFFIX)
        assert not backup.exists(), (
            "QC_HARNESS_AUDIT_REFUSED: a control that raised left its backup, so "
            "every later audit refuses a module that is not mutated"
        )


class TestMQCMutationQuarantine:
    """An audit says which cases it set aside, so nobody has to guess."""

    def MQC_CMN_UNI_410005_an_audit_names_the_cases_it_set_aside(self) -> None:
        """The closing line reads the targets, and an empty list reads as none.

        **Nothing can decide the list for the audit**, because the question a
        check would answer is the control run itself: does this case read a
        file the mutator rewrites. What was missing was the visibility, and
        twice a case belonged on the list with nobody seeing it.

        Design: ``harness_test_taxonomy.md`` section 15.7.1.2.

        Returns:
            None
        """
        step(1, "every deselected case is named")
        deselected = [
            AUDIT_TARGETS[index + 1]
            for index, argument in enumerate(AUDIT_TARGETS[:-1])
            if argument == "--deselect"
        ]
        assert len(quarantined_cases()) == len(deselected), (
            f"the audit deselects {len(deselected)} case(s) and names "
            f"{len(quarantined_cases())}, so a reader of the line cannot tell "
            f"what ran against the mutants"
        )

        step(2, "and each identifier it names is one the targets deselect")
        unnamed = [
            identifier for identifier in quarantined_cases()
            if not any(identifier in node for node in deselected)
        ]
        assert not unnamed, (
            f"the line names {unnamed}, which the targets do not deselect"
        )

        step(3, "the line carries the count and the identifiers")
        reported = quarantine_report()
        assert all(identifier in reported for identifier in quarantined_cases()), (
            f"the closing line omits an identifier it counted: {reported!r}"
        )

        step(4, "and a target list deselecting nothing reads as none")
        assert quarantine_report(["-m", "unit"]).endswith("none"), (
            "a run that set nothing aside does not say so, so an empty list "
            "and an unread one look alike"
        )

        step(5, "the suite Gate 8 runs closes with the line")
        root = Path(__file__).resolve().parents[2]
        conftest = ast.parse(
            (root / "tests/mutation/conftest.py").read_text(encoding="utf-8")
        )
        closing = [
            node for node in conftest.body
            if isinstance(node, ast.FunctionDef) and node.name == "pytest_terminal_summary"
        ]
        assert closing and "quarantine_report" in ast.unparse(closing[0]), (
            "the mutation suite does not close by naming what it set aside, so "
            "the line exists only on the command-line path, which Gate 8 never "
            "takes: the first completed audit carried it zero times"
        )

        step(6, "and the job puts it in its summary")
        workflow = _WORKFLOW.read_text(encoding="utf-8")
        assert "--quarantined" in workflow and "quarantined" in workflow, (
            "Gate 8's job does not ask the tool what it set aside, so a reader "
            "of the job summary cannot see which cases did not run"
        )


class TestMQCMutationWorkflow:
    """Gate 8 runs when the harness changes, and says when it could not."""

    @story("The audit is dispatched, never triggered")
    def MQC_CMN_UNI_410006_the_audit_runs_only_when_somebody_asks_for_it(self) -> None:
        """The workflow has one trigger, a dispatch, and takes what to audit.

        **`112379` is retired with the behaviour it asserted.** It required a
        push to `main` to audit every module, which is the tax the project
        owner's ruling of 2026-10-24 removed: the audit measures neither the
        harness nor a model and cost about ten hours of project time in a
        week.

        Design: ``harness_test_taxonomy.md`` section 15.6A,
        ``harness_ci_pipeline.md`` section 5A.

        Returns:
            None
        """
        source = _WORKFLOW.read_text(encoding="utf-8")
        workflow = yaml.safe_load(source)
        # PyYAML reads the key `on` as the boolean True.
        triggers = workflow.get("on", workflow.get(True)) or {}

        step(1, "a dispatch is the only way in")
        assert set(triggers) == {"workflow_dispatch"}, (
            f"the audit is triggered by {sorted(triggers)}, so it is a tax on "
            f"something rather than a tool somebody reaches for"
        )

        step(2, "and it takes the module and the ref to narrow to")
        inputs = set((triggers.get("workflow_dispatch") or {}).get("inputs") or {})
        assert {"module", "since"} <= inputs, (
            f"the dispatch offers {sorted(inputs)}, so an operator cannot point "
            f"it at one module or at the lines that changed"
        )

        step(3, "it still runs the audit")
        assert "pytest -m mutation tests/mutation" in source, "the audit is not run"

        step(4, "and still reddens on a refusal")
        assert "QC_HARNESS_AUDIT_REFUSED" in source and "exit 1" in source, (
            "a refused audit leaves the run green, so an unmeasured change reads "
            "as measured"
        )

        step(5, "and it reaches no credential")
        assert "secrets." not in source, (
            "an audit of our own code references a credential"
        )

    @story("The declarations are compared before anything is measured")
    def MQC_CMN_UNI_410004_the_job_compares_the_declarations_before_it_measures(
        self,
    ) -> None:
        """A step compares every declaration, and it precedes the measurement step.

        **The order is the whole of the saving.** The same comparison made
        after the measurement reports the same disagreement and saves nothing,
        which is the state this came from: one stale declaration cost five
        measurements and about twenty-one minutes, and the job went red anyway.

        Design: ``harness_test_taxonomy.md`` section 15.7.2,
        ``harness_ci_pipeline.md`` section 5A.

        Returns:
            None
        """
        workflow = yaml.safe_load(_WORKFLOW.read_text(encoding="utf-8"))
        runs = [str(stage.get("run") or "") for stage in workflow["jobs"]["audit"]["steps"]]

        step(1, "find the step comparing the declarations, and the step measuring")
        compared = [index for index, run in enumerate(runs)
                    if "tools.mutation_declarations" in run]
        measured = [index for index, run in enumerate(runs) if "pytest -m mutation" in run]
        assert compared, (
            "no step compares the declarations, so a manifest that cannot describe "
            "the commit is paid for in full before anything reports it"
        )

        step(2, "assert a measurement step exists at all")
        assert measured, "no step measures anything, so the job is not Gate 8"

        step(3, "assert the comparison runs first")
        assert compared[0] < measured[0], (
            f"the declarations are compared at step {compared[0]} and the measurement "
            f"starts at step {measured[0]}, so the comparison saves nothing"
        )

        step(4, "assert the summary states what the measurement took")
        reported = [run for run in runs if "GITHUB_STEP_SUMMARY" in run]
        assert any("elapsed" in run for run in reported), (
            "the summary does not state how long the measurement took, and the "
            "history this gate came from was legible only as a duration"
        )


