#   410002  a_remeasure_takes_the_module_on_disk_and_refuses_damage
# ------------------------------------------------------------ end of cases

import ast
from pathlib import Path

import pytest

from cmn.case_steps import step
from cmn.mutation_guard import module_digest
from tools.mutation_declarations import (
    AUDITED,
    baseline_refusal,
    declaration_problems,
)

from tests.cmn.mutation_tool_support import MODULE, SOURCE, write_manifest

pytestmark = pytest.mark.unit

_ROOT = Path(__file__).resolve().parents[2]


class TestMQCMutationDeclarations:
    """The manifest describes the modules on disk, and a re-measurement says so."""

    def MQC_CMN_UNI_410000_every_audited_module_hashes_to_its_declared_digest(
        self,
    ) -> None:
        """Every audited module of this repository is the module its survivors describe.

        Design: ``harness_test_taxonomy.md`` section 15.10.1.

        Returns:
            None
        """
        step(1, "hash each audited module and compare it with its declaration")
        problems = declaration_problems(_ROOT)
        assert not problems, (
            f"{len(problems)} of {len(AUDITED)} audited module(s) are not what the "
            f"manifest describes, so the survivors declared for them were measured "
            f"against other content: " + "; ".join(problems)
        )

    def MQC_CMN_UNI_410002_a_remeasure_takes_the_module_on_disk_and_refuses_damage(
        self, tmp_path: Path
    ) -> None:
        """A re-measurement takes the content on disk, and refuses one reading as its unparse.

        Design: ``harness_test_taxonomy.md`` section 15.10.2.

        Returns:
            None
        """
        manifest = write_manifest(tmp_path, module_digest(SOURCE))
        edited = SOURCE.replace("value * 2", "value * 3")

        step(1, "compare an edited module with the declared digest")
        stale = baseline_refusal(manifest, MODULE, edited, remeasure=False)
        assert stale is not None and "--remeasure" in stale, (
            f"an edited module was accepted as its own baseline, or the refusal "
            f"names no remedy: {stale!r}"
        )

        step(2, "take the same edited module as the baseline instead")
        assert baseline_refusal(manifest, MODULE, edited, remeasure=True) is None, (
            "a run asked to re-measure still refused the module on disk, which "
            "leaves a stale declaration with no remedy at all"
        )

        step(3, "take a module reading exactly as its own unparse as the baseline")
        stripped = ast.unparse(ast.parse(SOURCE))
        refused = baseline_refusal(manifest, MODULE, stripped, remeasure=True)
        assert refused is not None and "unparse" in refused, (
            f"a stripped module was adopted as a baseline, which is the damage the "
            f"declared digest exists for: {refused!r}"
        )

        step(4, "declare nothing as a side effect of either answer")
        assert module_digest(SOURCE) in manifest.read_text(encoding="utf-8"), (
            "the refusal rewrote the manifest, so a declaration moved without a "
            "measurement behind it"
        )
