"""Unit preconditions for a replay case skipped whole because a recording or judgement is missing.

Created: 2026-11-17
Last updated: 2026-11-17

The cases here check ``cmn.missing_artifact``. A case any of whose observations
lacks its judgement skips whole with ``QC_HARNESS_ARTIFACT_MISSING``, whatever
the other observations measured; a stale judgement skips it with
``QC_HARNESS_FIXTURE_STALE``; a case with no replay gap is left to its caller;
and a missing-artifact skip raised during the call carries its JUnit
properties and Allure labels and makes the run exit 3.

Specified by ``docs/design/harness_test_taxonomy.md`` section 5.1.3.1. A
failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3."""

