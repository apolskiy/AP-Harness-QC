from pathlib import Path
from xml.etree import ElementTree

import pytest

from cmn.case_steps import step
from cmn.missing_artifact import (
    ARTIFACT_MISSING,
    MissingArtifactSkip,
    label_missing_artifact_skip,
    raise_missing_artifact,
    skip_unreplayed_case,
)
from execution.replay import FixtureMissing
from tests.cmn.missing_artifact_support import LabelledItem
from tests.cmn.replay_gap_support import (
    CALL_TIME_CASES,
    CALL_TIME_CONFTEST,
    CALL_TIME_MESSAGE,
    MISSING_JUDGEMENT,
    ReportDouble,
    call_raising,
    observation,
)
from tests.cmn.wired_session import run_wired_session

pytestmark = pytest.mark.unit

_STALE = "QC_HARNESS_FIXTURE_STALE"


class TestMQCReplayGap:
    """A replay case missing any recording or judgement is skipped whole, and says which."""

    def MQC_CMN_UNI_112463_a_replay_gap_in_any_observation_skips_the_whole_case(
        self
    ) -> None:
        """A missing judgement beside a measured pass and a measured failure skips the case.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.1.

        Returns:
            None
        """
        step(1, "decide a case whose third observation has no judgement")
        results = [
            observation(), observation(passed=False),
            observation(unavailable=ARTIFACT_MISSING, missing=MISSING_JUDGEMENT),
        ]
        with pytest.raises(MissingArtifactSkip) as caught:
            skip_unreplayed_case(results)

        step(2, "read the skip it raised")
        assert (
            caught.value.missing == MISSING_JUDGEMENT
            and isinstance(caught.value, pytest.skip.Exception)
            and str(caught.value.msg).startswith(
                f"{ARTIFACT_MISSING}: judgement {MISSING_JUDGEMENT.path}"
            )
        ), caught.value.msg

    def MQC_CMN_UNI_112464_a_stale_judgement_skips_the_whole_case_with_its_code(
        self
    ) -> None:
        """A judgement that no longer answers its request skips the case with the stale code.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.1.

        Returns:
            None
        """
        step(1, "decide a case whose second observation read a stale judgement")
        results = [observation(), observation(unavailable=_STALE), observation()]
        with pytest.raises(pytest.skip.Exception) as caught:
            skip_unreplayed_case(results)

        step(2, "read the skip it raised")
        assert str(caught.value.msg).startswith(f"{_STALE}:"), caught.value.msg

    def MQC_CMN_UNI_112465_a_case_with_no_replay_gap_is_left_to_its_caller(self) -> None:
        """Measured observations, an unreachable judge and a withheld one raise nothing.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.1.

        Returns:
            None
        """
        step(1, "decide each case carrying no gap in the replay store, and collect skips")
        cases = {
            "measured": [observation(), observation(passed=False), observation()],
            "judge unreachable": [
                observation(), observation(unavailable="QC_HARNESS_ENGINE_UNREACHABLE"),
            ],
            "judge withheld": [observation(withheld=True), observation(withheld=True)],
        }
        skipped: dict[str, str] = {}
        for name, results in cases.items():
            try:
                skip_unreplayed_case(results)
            except pytest.skip.Exception as raised:
                skipped[name] = str(raised.msg)
        assert not skipped, skipped

    def MQC_CMN_UNI_112466_a_missing_artifact_raised_in_the_call_is_labelled_in_junit(
        self, tmp_path: Path
    ) -> None:
        """A skip raised during the call carries its kind and path in JUnit and exits 3.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.1.

        Args:
            tmp_path (Path): Where the wired session, its cases and its XML are written.

        Returns:
            None
        """
        step(1, "run a session whose case raises the skip in its call, writing JUnit")
        report = tmp_path / "junit.xml"
        finished = run_wired_session(
            tmp_path, CALL_TIME_CONFTEST, CALL_TIME_CASES, extra=("--junitxml", str(report)),
        )
        cases = {
            str(element.get("name")): element
            for element in ElementTree.parse(report).getroot().iter("testcase")
        }
        properties = {
            name: [(str(found.get("name")), str(found.get("value")))
                   for found in element.iter("property")]
            for name, element in cases.items()
        }
        skipped = cases["test_raises_in_its_call"].find("skipped")
        assert (
            finished.returncode == 3
            and properties["test_raises_in_its_call"] == [
                ("mqc_artifact_kind", "recording"),
                ("mqc_artifact_path", "replay/gemini/MQC_TASK_a/MQC_RULE_a/2.json"),
            ]
            and skipped is not None
            and CALL_TIME_MESSAGE in str(skipped.get("message"))
            and properties["test_has_its_artifacts"] == []
        ), (finished.returncode, properties, finished.stdout)

    def MQC_CMN_UNI_112467_a_missing_artifact_raised_in_the_call_carries_allure_labels(
        self
    ) -> None:
        """Labelling a call-time skip adds the code, kind and path to the item and report.

        Design: ``harness_test_taxonomy.md`` section 5.1.3.1.

        Returns:
            None
        """
        step(1, "raise the skip, then label the item and report a makereport hook holds")
        with pytest.raises(MissingArtifactSkip) as caught:
            raise_missing_artifact(MISSING_JUDGEMENT)
        item, report = LabelledItem(), ReportDouble()
        labelled = label_missing_artifact_skip(item, call_raising(caught.value), report)

        step(2, "label a phase that crashed on an error carrying an artifact, and read both")
        other = label_missing_artifact_skip(
            LabelledItem(), call_raising(FixtureMissing(MISSING_JUDGEMENT)), ReportDouble(),
        )
        assert (
            labelled and not other
            and item.labels() == [
                ("taxonomy_code", ARTIFACT_MISSING),
                ("artifact_kind", "judgement"),
                ("artifact_path", MISSING_JUDGEMENT.path),
            ]
            and report.user_properties == [
                ("mqc_artifact_kind", "judgement"),
                ("mqc_artifact_path", MISSING_JUDGEMENT.path),
            ]
        ), (item.labels(), report.user_properties)
