"""Unit preconditions for the flags this repository's documents name.

Created: 2026-10-22
Last updated: 2026-10-22

The cases here check ``cmn.flag_citations``: that ``undeclared_flags``
reports a flag a live document names and nothing declares, that a flag the
option registry, a script of the repository, the foreign registry or the
retired registry declares is not reported, and that the changelog and the
progress log are not read at all.

**A document naming a flag is telling a reader to type it.** A flag that
never existed fails the moment they do. A flag that was renamed fails
identically and sends them to look for their own mistake, because the
document describing the behaviour is the thing that is wrong, and that is the
defect this found in the case repository on its first run.

Specified by ``docs/design/cmn_verdict_and_cli.md`` section 7.1.0.4.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.
"""

