from pathlib import Path

import pytest

from cmn.flag_citations import (
    FOREIGN_FLAGS,
    RETIRED_FLAGS,
    declared_flags,
    undeclared_flags,
)
from cmn.options import registered_options

from tests.cmn.flag_citations_support import write_document

pytestmark = pytest.mark.unit

_ROOT = Path(__file__).resolve().parents[2]


class TestMQCFlagCitations:
    """Every flag a live document names is declared by something."""

    def MQC_CMN_UNI_400000_a_flag_a_document_names_and_nothing_declares_is_reported(
        self, tmp_path: Path
    ) -> None:
        """A flag with no declaration is reported, and a renamed one with it.

        **Asserted against a constructed tree before the real one**, because
        a check that finds nothing proves nothing until it has been shown
        finding something. Both halves of the project's own history are
        built here: a flag that never existed, which is what reached section
        7.1.2's selection table twice, and a flag whose declaration moved
        under a new name, which is what the case repository held.

        Returns:
            None
        """
        # A SCRIPT OF THE TREE DECLARES ONE FLAG AND NOT THE OTHER.
        (tmp_path / "tools").mkdir()
        (tmp_path / "tools" / "runner.py").write_text(
            "import argparse\n"
            "parser = argparse.ArgumentParser()\n"
            'parser.add_argument("--hold-unreproduced")\n',
            encoding="utf-8",
        )

        write_document(
            tmp_path,
            "runbook.md",
            "Pass `--hold-unreproduced` to hold a finding.\n"
            "Pass `--invented-selector` to select nothing.\n",
        )

        reported = undeclared_flags(tmp_path)
        assert reported == ["docs/runbook.md:2 --invented-selector"], reported

        # A RENAMED FLAG IS THE SAME REPORT AND THE COSTLIER DEFECT. The
        # script declares one name and the document sends a reader to the
        # other, so the tool refuses a flag its own design told them to type.
        write_document(
            tmp_path,
            "runbook.md",
            "Pass `--withdraw-unreproduced` to hold a finding.\n",
        )
        renamed = undeclared_flags(tmp_path)
        assert renamed == ["docs/runbook.md:1 --withdraw-unreproduced"], renamed

        # THE LINE IS NAMED, because a flag appearing twice in one document
        # needs both occurrences found rather than one.
        write_document(
            tmp_path,
            "runbook.md",
            "First `--invented-selector`.\n\nAnd again `--invented-selector`.\n",
        )
        twice = undeclared_flags(tmp_path)
        assert twice == [
            "docs/runbook.md:1 --invented-selector",
            "docs/runbook.md:3 --invented-selector",
        ], twice

        # AND TWO ON ONE LINE ARE BOTH REPORTED. A command is usually written
        # whole, so a mistyped flag sits beside the others rather than alone,
        # and reporting the first would leave the reader to find the rest by
        # running it again.
        write_document(
            tmp_path,
            "runbook.md",
            "Run `gh run download --nmae mqc-reports --dri results`.\n",
        )
        together = undeclared_flags(tmp_path)
        assert together == [
            "docs/runbook.md:1 --nmae",
            "docs/runbook.md:1 --dri",
        ], together

    def MQC_CMN_UNI_400001_a_flag_declared_outside_this_repository_is_not_reported(
        self, tmp_path: Path
    ) -> None:
        """The four declarations resolve, and history is not read.

        **A registry entry naming no owner would be an exemption**, and the
        distinction this section rests on is that it is not one: an entry
        records what owns a flag, which a reader can check, rather than a
        reason to overlook it.

        Returns:
            None
        """
        # EACH ENTRY NAMES WHAT OWNS THE FLAG, and neither registry shadows a
        # flag of ours, which would hide the defect it exists to report.
        registered = {entry.cli_flag for entry in registered_options()}
        for flag, owner in {**FOREIGN_FLAGS, **RETIRED_FLAGS}.items():
            assert flag.startswith("--"), flag
            assert owner.strip(), flag
            assert flag not in registered, flag

        # A FOREIGN FLAG, A RETIRED ONE AND A REGISTERED ONE ARE ALL CLEAN.
        write_document(
            tmp_path,
            "runbook.md",
            "Run `pytest --junitxml=reports/junit.xml --mode replay`.\n"
            "`--case` was retired on 2026-10-03.\n",
        )
        assert not undeclared_flags(tmp_path), undeclared_flags(tmp_path)

        # THE OPTION REGISTRY TRAVELS WITH THE HARNESS, so a tree with no
        # script of its own still resolves every flag the harness declares.
        assert registered <= declared_flags(tmp_path)

        # HISTORY IS NOT READ. A progress record names the flags that existed
        # when it was written, and rewriting it to agree with a later state is
        # the one thing it must not do.
        (tmp_path / "CHANGELOG.md").write_text(
            "`--long-since-removed` went on 2026-09-01.\n", encoding="utf-8"
        )
        (tmp_path / "CLAUDE_LOG.md").write_text(
            "`--also-long-gone` was read once.\n", encoding="utf-8"
        )
        assert not undeclared_flags(tmp_path), undeclared_flags(tmp_path)

        # A ROOT DOCUMENT THAT IS NOT HISTORY IS READ.
        (tmp_path / "README.md").write_text(
            "Run with `--not-a-flag-of-ours`.\n", encoding="utf-8"
        )
        assert undeclared_flags(tmp_path) == [
            "README.md:1 --not-a-flag-of-ours"
        ], undeclared_flags(tmp_path)

    def MQC_CMN_UNI_400002_this_repository_names_no_undeclared_flag(self) -> None:
        """Every flag this repository's live documents name is declared.

        Returns:
            None
        """
        assert not undeclared_flags(_ROOT), undeclared_flags(_ROOT)
