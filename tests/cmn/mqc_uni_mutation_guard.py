    def MQC_CMN_UNI_112391_a_run_refuses_a_module_a_live_audit_holds_but_its_own(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A live audit's module refuses every run but the audit's own, and is left alone.

        Design: ``harness_test_taxonomy.md`` section 15.12.1.

        Args:
            tmp_path (Path): The harness root.
            monkeypatch (pytest.MonkeyPatch): Replaces the process launcher.

        Returns:
            None
        """
        module = harness_tree(tmp_path, module_digest(SOURCE))
        mutant = ast.unparse(ast.parse(SOURCE))
        module.write_text(mutant, encoding="utf-8", newline="\n")
        backup, _ = hold_module(module, os.getpid())

        step(1, "check a module this live process holds, from a run that is not its audit")
        refusal = mutation_state(tmp_path, environ={}) or ""
        assert all(
            part in refusal for part in ("QC_HARNESS_PREFLIGHT_FAILURE", MODULE, str(os.getpid()))
        ), refusal

        step(2, "confirm the refusal touched neither the mutant nor the backup")
        assert module.read_text(encoding="utf-8") == mutant and backup.is_file()

        step(3, "check the same module from a run the holding audit launched")
        assert mutation_state(tmp_path, environ={AUDIT_ENV: str(os.getpid())}) is None

        step(4, "launch an audit run and read the environment it is given")
        seen: list[dict[str, Any]] = []

        def launched(command: list[str], **options: Any) -> subprocess.CompletedProcess:
            seen.append(options)
            return subprocess.CompletedProcess(command, 0, "1 passed", "")

        monkeypatch.setattr(mutation_audit.subprocess, "run", launched)
        mutation_audit.run_targets(tmp_path, ["tests/x.py"], stop_early=True)
        assert seen and seen[0]["env"].get(AUDIT_ENV) == str(os.getpid()), (
            "QC_HARNESS_PREFLIGHT_FAILURE: an audit run does not identify itself, so "
            "the check refuses the audit's own runs"
        )

    def MQC_CMN_UNI_112392_an_abandoned_backup_is_restored_verified_and_the_run_refused(
        self, tmp_path: Path
    ) -> None:
        """A backup no live process holds is restored, verified, removed, and the run exits 3.

        Design: ``harness_test_taxonomy.md`` section 15.12.2.

        Args:
            tmp_path (Path): The harness root.

        Returns:
            None
        """
        module = harness_tree(tmp_path, module_digest(SOURCE))
        module.write_text(ast.unparse(ast.parse(SOURCE)), encoding="utf-8", newline="\n")
        backup, lock = hold_module(module, exited_pid())

        step(1, "check a module a dead audit left mutated")
        refusal = mutation_state(tmp_path, environ={}) or ""
        assert all(
            part in refusal for part in ("QC_HARNESS_PREFLIGHT_FAILURE", "restored", "run again")
        ), refusal

        step(2, "read the module, its backup and its lock after the check")
        restored = module.read_text(encoding="utf-8")
        assert restored == SOURCE and not backup.exists() and not lock.exists(), (
            "the module was not restored, or a restore that held left its backup or lock, "
            f"so the next run refuses again: backup {backup.exists()}, lock {lock.exists()}"
        )

        step(3, "leave the module mutated again and start a session against it")
        module.write_text(ast.unparse(ast.parse(SOURCE)), encoding="utf-8", newline="\n")
        hold_module(module, exited_pid())
        with pytest.raises(pytest.exit.Exception) as stopped:
            refuse_if_mutating(tmp_path)

        step(4, "read the exit code the session was given")
        assert stopped.value.returncode == 3, stopped.value.returncode

    def MQC_CMN_UNI_112393_a_failed_restore_keeps_the_backup_and_names_both_recoveries(
        self, tmp_path: Path
    ) -> None:
        """A restore that cannot write keeps the backup and names both ways out.

        The module path is a directory, which no write can replace on either
        platform.

        Design: ``harness_test_taxonomy.md`` section 15.12.2.

        Args:
            tmp_path (Path): The harness root.

        Returns:
            None
        """
        harness_tree(tmp_path, module_digest(SOURCE))
        blocked = tmp_path / "cmn" / "blocked.py"
        blocked.mkdir()
        backup = blocked.with_name(blocked.name + BACKUP_SUFFIX)
        backup.write_text(SOURCE, encoding="utf-8", newline="\n")

        step(1, "check a module whose restore cannot write")
        refusal = mutation_state(tmp_path, environ={}) or ""
        assert refusal is not None and "restoring it failed" in refusal, refusal

        step(2, "read the backup and the recoveries the refusal names")
        assert backup.is_file() and str(backup) in refusal and "with git" in refusal, (
            f"a failed restore removed the backup or named no recovery: {refusal}"
        )

    def MQC_CMN_UNI_112394_a_restore_not_matching_its_declared_digest_keeps_the_backup(
        self, tmp_path: Path
    ) -> None:
        """A restored module that is not the declared baseline keeps its backup.

        Design: ``harness_test_taxonomy.md`` section 15.12.2.

        Args:
            tmp_path (Path): The harness root.

        Returns:
            None
        """
        module = harness_tree(tmp_path, module_digest(SOURCE))
        backup, _ = hold_module(module, exited_pid())
        drifted = SOURCE + "# drifted\n"
        backup.write_text(drifted, encoding="utf-8", newline="\n")

        step(1, "check a module whose backup is not the declared baseline")
        refusal = mutation_state(tmp_path, environ={}) or ""
        assert refusal is not None and "not the baseline" in refusal, refusal

        step(2, "read the digests and the backup after the check")
        named = module_digest(drifted) in refusal and module_digest(SOURCE) in refusal
        assert named and backup.is_file(), (
            f"an unverified restore removed the backup or named no digest: {refusal}"
        )

    def MQC_CMN_UNI_112395_each_audit_event_is_flushed_to_a_log_named_for_its_start(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """Each event is on disk as soon as it is written, in a file named for the start.

        Design: ``harness_test_taxonomy.md`` section 15.12.3.

        Args:
            tmp_path (Path): The repository root.
            monkeypatch (pytest.MonkeyPatch): Replaces the audit's suite runs.

        Returns:
            None
        """
        step(1, "begin a log at a known start and read it before anything closes it")
        log = ProgressLog.begin(tmp_path, MODULE, now=_START)
        first = log.path.read_text(encoding="utf-8")
        assert log.path.name == "cmn.sample.py.mutation-progress-20261018T142301Z" and (
            first.endswith(f"started pid {os.getpid()}\n")
        ), f"{log.path.name}: {first}"

        step(2, "write one more event and read the file straight after")
        log.line("control started", now=_START)
        assert log.path.read_text(encoding="utf-8").splitlines()[-1].endswith("control started")

        step(3, "audit a module with every mutant killed and read its log")
        module = harness_tree(tmp_path / "audited", module_digest(SOURCE))

        def ran(_root: Path, _targets: list[str], *, stop_early: bool) -> Any:
            if stop_early:
                return subprocess.CompletedProcess([], 1, "", "")
            return subprocess.CompletedProcess([], 0, "3 passed", "")

        monkeypatch.setattr(mutation_audit, "run_targets", ran)
        mutation_audit.survivors(tmp_path / "audited", module, ["tests/x.py"], limit=1)
        written = next((tmp_path / "audited" / PROGRESS_DIR).iterdir())
        lines = written.read_text(encoding="utf-8").splitlines()
        events = [line.split(" ", 1)[1] for line in lines]
        assert events[0].startswith("started pid") and events[2:4] == [
            "control started", "control passed"
        ], events

        step(4, "read the events the audit wrote for its one mutant")
        assert events[4].startswith("point 1 of 1 started: line") and events[5] == (
            "point 1 of 1 killed"
        ), events

        step(5, "read the audit's last line")
        assert events[-1] == "finished: restored, 0 survivor(s)", events

    def MQC_CMN_UNI_112396_a_finished_audit_keeps_its_log_and_removes_every_older_one(
        self, tmp_path: Path
    ) -> None:
        """A finished audit's log is kept and every older one of its module deleted.

        A log that did not finish stays until a later audit finishes.

        Design: ``harness_test_taxonomy.md`` section 15.12.3.

        Args:
            tmp_path (Path): The repository root.

        Returns:
            None
        """
        step(1, "finish one audit, then leave a second refused and unfinished")
        good = ProgressLog.begin(tmp_path, MODULE, now=_START)
        good.finish("restored, 0 survivor(s)", now=_START)
        refused = ProgressLog.begin(tmp_path, MODULE, now=_START + timedelta(hours=1))
        refused.line("refused: QC_HARNESS_AUDIT_REFUSED: a control failed")
        other = ProgressLog.begin(tmp_path, "cmn/other.py", now=_START)
        assert good.path.is_file() and refused.path.is_file(), "an unfinished log removed one"

        step(2, "finish a third audit of the same module")
        latest = ProgressLog.begin(tmp_path, MODULE, now=_START + timedelta(hours=2))
        latest.finish("restored, 0 survivor(s)")
        kept = sorted(path.name for path in (tmp_path / PROGRESS_DIR).iterdir())
        assert kept == sorted([latest.path.name, other.path.name]), kept

    def MQC_CMN_UNI_112397_a_refusal_quotes_the_last_progress_line_and_its_age(
        self, tmp_path: Path
    ) -> None:
        """A refusal quotes where the audit is and how long ago it said so.

        Design: ``harness_test_taxonomy.md`` section 15.12.3.

        Args:
            tmp_path (Path): The harness root.

        Returns:
            None
        """
        module = harness_tree(tmp_path, module_digest(SOURCE))
        hold_module(module, os.getpid())
        log = ProgressLog.begin(tmp_path, MODULE, now=_START)
        log.line("point 12 of 51 started: line 456: 1 to 2", now=_START)
        later = _START + timedelta(minutes=40)

        step(1, "read the module's progress forty minutes after its last line")
        progress = latest_progress(tmp_path, MODULE, now=later)
        assert progress == (
            'last progress "point 12 of 51 started: line 456: 1 to 2", written 40 minutes ago'
        ), progress

        step(2, "check the held module and read the refusal")
        refusal = mutation_state(tmp_path, environ={}, now=later) or ""
        assert refusal is not None and progress in refusal, refusal
