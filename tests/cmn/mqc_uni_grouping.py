                "name: gate-on-change",
                "on:",
                "  push:",
                "jobs:",
                "  unit:",
                "    runs-on: ubuntu-26.04",
                "    steps:",
                "      - run: pytest -m unit",
                "  publish:",
                "    needs: unit",
                "    runs-on: ubuntu-26.04",
                "    permissions:",
                "      pages: write",
                "      id-token: write",
