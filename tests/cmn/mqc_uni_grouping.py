class TestMQCGroupingDeclaration:
    """A declaration that disagrees with the repository is reported."""

    def MQC_CMN_UNI_420000_a_collected_module_declaring_no_capability_is_reported(
        self, tmp_path: Path
    ) -> None:
        """This repository maps every module, and a planted one that does not is named.

        **Both directions.** A check that reported everything would pass a
        one-sided assertion and fail the unit layer on every push, and a check
        that reported nothing is what the rule had instead of enforcement for
        the project's whole life.

        Design: ``harness_test_taxonomy.md`` section 16.3.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        step(1, "read this repository's own declaration against its test tree")
        assert not grouping_problems(_ROOT), (
            "this repository's declaration disagrees with its test tree: "
            + "; ".join(grouping_problems(_ROOT))
        )

        step(2, "plant a repository holding one mapped module and one that is not")
        planted = plant_root(
            tmp_path,
            epic="AP-Harness-QC",
            features=_VOCABULARY,
            declared={_MAPPED: "The result record"},
            modules=[_MAPPED, _UNMAPPED],
        )
        reported = grouping_problems(planted)
        assert any(_UNMAPPED in problem for problem in reported), (
            f"a module holding cases and declaring no capability was not reported, "
            f"so its results would group under nothing: {reported}"
        )

        step(3, "and the mapped one is not reported")
        assert not any(_MAPPED in problem for problem in reported), (
            f"the mapped module was reported as well, so the check cannot tell a "
            f"declared capability from a missing one: {reported}"
        )

    def MQC_CMN_UNI_420001_a_capability_outside_the_vocabulary_is_reported(
        self, tmp_path: Path
    ) -> None:
        """A capability spelled outside the list, and an entry naming no module, are named.

        A free-text label grows the tree a branch at a time and nothing says
        so: the thirteen classes labelled by hand before this carried three
        different vocabularies between them, two of which the standard did not
        name.

        Design: ``harness_test_taxonomy.md`` section 16.3.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        planted = plant_root(
            tmp_path,
            epic="AP-Harness-QC",
            features=_VOCABULARY,
            declared={
                _MAPPED: "Invented capability",
                "tests/cmn/mqc_uni_absent.py": "The result record",
            },
            modules=[_MAPPED],
        )
        reported = grouping_problems(planted)

        step(1, "a capability the vocabulary does not hold is reported")
        assert any("Invented capability" in problem for problem in reported), (
            f"a capability outside the declared vocabulary was accepted, so the tree "
            f"can grow a branch by typo: {reported}"
        )

        step(2, "and an entry naming a module the repository does not hold")
        assert any("mqc_uni_absent.py" in problem for problem in reported), (
            f"an entry naming no module was accepted, so a deleted module keeps its "
            f"capability and nothing says the map is stale: {reported}"
        )

    def MQC_CMN_UNI_420002_the_declared_epic_is_the_distribution_name(
        self, tmp_path: Path
    ) -> None:
        """The epic is this distribution's own name, and a planted mismatch is reported.

        **The epic is what separates two result sets.** A collector reading
        both repositories tells them apart by it, so an epic somebody typed
        differently from the distribution is a result attributed to a
        repository that does not exist.

        Design: ``harness_test_taxonomy.md`` section 16.3.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        step(1, "read the epic this repository declares")
        assert load_grouping(_ROOT).epic == "AP-Harness-QC", (
            f"{DECLARATION} declares the epic "
            f"{load_grouping(_ROOT).epic!r}, which is not this repository"
        )

        step(2, "plant a repository whose epic is another name")
        mismatched = plant_root(
            tmp_path / "other",
            epic="AP-Model-QC",
            features=_VOCABULARY,
            declared={_MAPPED: "The result record"},
            modules=[_MAPPED],
        )
        assert any("AP-Model-QC" in problem for problem in grouping_problems(mismatched)), (
            "an epic that is not the distribution name was accepted, so two "
            "repositories could publish results under one epic"
        )

        step(3, "and one that declares no epic at all")
        silent = plant_root(
            tmp_path / "silent",
            epic="",
            features=_VOCABULARY,
            declared={_MAPPED: "The result record"},
            modules=[_MAPPED],
        )
        assert any("declares no epic" in problem for problem in grouping_problems(silent)), (
            "a declaration with no epic was accepted, so every result would carry "
            "none and a collector could not say which repository produced it"
        )


@pytest.mark.environment("reporter")
class TestMQCGroupingLabels:
    """What a real reporter writes for a collected case.

    **Scoped to an installed reporter**, because reading what one wrote needs
    one. Where the reporting extra is absent these two are **deselected**, so
    they leave the total rather than reporting a non-outcome in it
    (``harness_test_taxonomy.md`` sections 7.5.1 and 16.7).
    """

    def MQC_CMN_UNI_420003_a_real_reporter_writes_all_three_grouping_labels(
        self, tmp_path: Path
    ) -> None:
        """A run of one module publishes an epic, a capability and a scenario.

        **A real reporter rather than a double.** The labels are written by
        ``allure-pytest`` from markers the collection hook adds, so a double
        would assert that this suite's own idea of the format agrees with
        itself. Section 5.1 of ``cmn_verdict_and_cli.md`` was established by
        reading a raw result for exactly that reason.

        Design: ``harness_test_taxonomy.md`` section 16.2.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        step(1, "run one module under a real reporter")
        results = published_results(_ROOT, _PROBE, tmp_path / "allure")
        assert results, "the probe run published no result at all"

        step(2, "every result carries one epic, and it is this repository")
        epics = {sole_label(result, "epic") for result in results}
        assert epics == {"AP-Harness-QC"}, (
            f"the published epics were {epics}, so a result carries none, or two"
        )

        step(3, "one capability, and it is the one the declaration maps")
        declared = load_grouping(_ROOT).modules[_PROBE]
        features = {sole_label(result, "feature") for result in results}
        assert features == {declared}, (
            f"the published capabilities were {features} against {declared!r} in "
            f"{DECLARATION}, so the report groups by something else"
        )

        step(4, "and one scenario, taken from the test class")
        stories = {sole_label(result, "story") for result in results}
        assert stories == {story_for(_PROBE_CLASS)}, (
            f"the published scenarios were {stories} against "
            f"{story_for(_PROBE_CLASS)!r} for {_PROBE_CLASS}"
        )

    def MQC_CMN_UNI_420004_a_declared_story_is_kept_and_not_duplicated(
        self, tmp_path: Path
    ) -> None:
        """A case naming its own scenario keeps it, and gains no second one.

        Allure unions the label markers an item carries and treats a story as
        repeatable, so a derived label added beside a declared one publishes
        **both** and the report grows a branch for each. The hook therefore
        fills only what an item declares none of.

        Design: ``harness_test_taxonomy.md`` section 16.2.1.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        results = published_results(_ROOT, _DECLARING, tmp_path / "allure")

        step(1, "no result carries two scenarios")
        doubled = [
            result["name"] for result in results if len(label_values(result, "story")) != 1
        ]
        assert not doubled, (
            f"{len(doubled)} result(s) carry no scenario or two, so the derived label "
            f"competes with the declared one rather than standing aside: {doubled[:3]}"
        )

        step(2, "and the scenarios they carry are the ones their cases name")
        published = {sole_label(result, "story") for result in results}
        assert story_for("TestMQCBandSummary") not in published, (
            f"a derived scenario reached a case that names its own, so the override "
            f"in section 16.2.1 is not in force: {published}"
        )


class TestMQCGroupingPublication:
    """The report is rendered and published, not only uploaded raw."""

