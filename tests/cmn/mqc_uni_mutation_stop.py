"""Unit tests for deselecting mutation audits by default and for stopping one on request.

Created: 2026-10-20
Last updated: 2026-10-21

Its cases check ``deselect_unrequested_audits`` in ``cmn/selection.py`` and
``request_stop``, ``stop_requested`` and ``stop_audits`` in
``cmn/mutation_guard.py``, driven through ``tools/mutation_audit.py``. An audit is
deselected unless the run asks for it, a stop request ends an audit and restores
its module, a request naming another process is ignored, a stopped audit refuses
and logs the stop, and the stop command passes only once every module is restored.

``conftest.py`` deselects the audits at collection, and the audit tool's stop
command is how an operator ends one without leaving a module rewritten.

Specified by ``docs/design/cmn_verdict_and_cli.md`` section 10 and
``docs/design/harness_test_taxonomy.md`` section 15.13.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.
"""

