    def MQC_CMN_UNI_112415_a_stop_request_ends_an_audit_and_restores_its_module(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A request made while point 1 runs stops the audit before point 2, module restored.

        Design: ``harness_test_taxonomy.md`` section 15.13.2.

        Args:
            tmp_path (Path): The harness root.
            monkeypatch (pytest.MonkeyPatch): Replaces the process launcher.

        Returns:
            None
        """
        module = pointed_tree(tmp_path)
        points = mutation_audit.mutation_points(POINTED)
        step(1, "count the points the module offers")
        assert len(points) >= 3, f"the module offers {len(points)} points, too few to stop between"

        calls: list[list[str]] = []
        requested: list[Any] = []

        def on_point(number: int) -> None:
            if number == 1:
                requested.extend(request_stop(tmp_path))

        monkeypatch.setattr(mutation_audit.subprocess, "run", launcher(calls, on_point))
        step(2, "audit the module, requesting a stop while point 1 runs")
        with pytest.raises(mutation_audit.MutationRefusal) as raised:
            mutation_audit.survivors(tmp_path, module, ["tests/x.py"])
        assert requested == [(MODULE, os.getpid())], f"the request named {requested}"
        assert f"stopped on request at point 2 of {len(points)}" in str(raised.value), (
            str(raised.value)
        )

        step(5, "count the runs: the control and point 1, and nothing after the request")
        assert len(calls) == 2, f"{len(calls)} runs were launched"

        step(6, "read the module, its backup and its lock")
        assert restored_baseline(module), (
            "the stopped audit left the module mutated, backed up or held"
        )

    def MQC_CMN_UNI_112416_a_stop_request_for_another_process_does_not_stop_an_audit(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A request naming another live process is kept and ignored; a dead one's is removed.

        Design: ``harness_test_taxonomy.md`` section 15.13.2.

        Args:
            tmp_path (Path): The harness root.
            monkeypatch (pytest.MonkeyPatch): Replaces the process launcher.

        Returns:
            None
        """
        module = pointed_tree(tmp_path)

        step(1, "ask about this process under a request naming only an exited one")
        request = write_stop_request(tmp_path, [exited_pid()])
        assert not stop_requested(tmp_path, os.getpid()), "a dead process's request stopped us"
        assert not request.exists(), "a request whose processes have all exited was kept"

        step(3, "ask about this process under a request naming another live one")
        request = write_stop_request(tmp_path, [os.getppid()])
        assert not stop_requested(tmp_path, os.getpid()), "another process's request stopped us"
        assert request.exists(), "a live process's request was removed"

        step(5, "audit the module under that request")
        calls: list[list[str]] = []
        monkeypatch.setattr(mutation_audit.subprocess, "run", launcher(calls, lambda _: None))
        found = mutation_audit.survivors(tmp_path, module, ["tests/x.py"])
        assert not found and len(calls) == 1 + len(mutation_audit.mutation_points(POINTED)), (
            f"the audit ran {len(calls)} times and found {found}"
        )
        assert restored_baseline(module)

    def MQC_CMN_UNI_112417_an_audit_stopped_on_request_refuses_and_logs_the_stop(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A later audit in a stopped process refuses before its control and logs why.

        Design: ``harness_test_taxonomy.md`` section 15.13.2.

        Args:
            tmp_path (Path): The harness root.
            monkeypatch (pytest.MonkeyPatch): Replaces the process launcher.

        Returns:
            None
        """
        module = pointed_tree(tmp_path)
        write_stop_request(tmp_path, [os.getpid()])
        calls: list[list[str]] = []
        monkeypatch.setattr(mutation_audit.subprocess, "run", launcher(calls, lambda _: None))

        step(1, "audit the module in a process a request names")
        with pytest.raises(mutation_audit.MutationRefusal) as raised:
            mutation_audit.survivors(tmp_path, module, ["tests/x.py"])
        refusal = str(raised.value)
        assert refusal.startswith("QC_HARNESS_AUDIT_REFUSED") and (
            "stopped on request before its control" in refusal
        ), refusal

        step(3, "count the runs and read the module")
        assert not calls and restored_baseline(module), (
            "the stopped audit ran or touched the module"
        )

        step(4, "read the audit's progress log")
        logs = sorted((tmp_path / PROGRESS_DIR).glob("*mutation-progress-*"))
        last = logs[-1].read_text(encoding="utf-8").splitlines()[-1] if logs else ""
        assert "stopped on request" in last, f"the progress log ends on {last!r}"

    def MQC_CMN_UNI_112418_the_stop_command_passes_only_once_every_module_is_restored(
        self, tmp_path: Path
    ) -> None:
        """The command waits for each named lock, then proves each module is its baseline.

        Design: ``harness_test_taxonomy.md`` section 15.13.2.

        Args:
            tmp_path (Path): The harness root.

        Returns:
            None
        """
        step(1, "stop with no audit running")
        code, lines = stop_audits(tmp_path, wait=0)
        assert code == 0 and "no mutation audit is running" in " ".join(lines), lines
        assert not (tmp_path / STOP_REQUEST).exists(), "a request was written for nothing"

        module = pointed_tree(tmp_path)
        lock = module.with_name(module.name + LOCK_SUFFIX)
        backup = module.with_name(module.name + BACKUP_SUFFIX)

        def held() -> None:
            lock.write_text(json.dumps({"pid": os.getpid(), "started": "2026-10-20T21:00:00Z"}),
                            encoding="utf-8", newline="\n")

        step(3, "stop an audit that releases its lock, its module restored")
        held()
        code, lines = stop_audits(tmp_path, wait=5, sleep=lambda _: lock.unlink())
        assert code == 0 and MODULE in " ".join(lines), lines
        assert json.loads((tmp_path / STOP_REQUEST).read_text(encoding="utf-8"))["pids"] == [
            os.getpid()
        ]

        step(5, "stop an audit that releases its lock and leaves a backup")
        held()
        backup.write_text(POINTED, encoding="utf-8", newline="\n")
        code, lines = stop_audits(tmp_path, wait=5, sleep=lambda _: lock.unlink())
        assert code == 1 and any(BACKUP_SUFFIX in line for line in lines), lines
        backup.unlink()

        step(6, "stop an audit that releases its lock with the module not its baseline")
        held()
        module.write_text(POINTED.replace("2", "3"), encoding="utf-8", newline="\n")
        code, lines = stop_audits(tmp_path, wait=5, sleep=lambda _: lock.unlink())
        assert code == 1 and any("digest" in line for line in lines), lines
        module.write_text(POINTED, encoding="utf-8", newline="\n")

        step(7, "stop an audit that never releases its lock, waiting no time")
        held()
        code, lines = stop_audits(tmp_path, wait=0)
        assert code == 1 and any("still held" in line for line in lines), lines
