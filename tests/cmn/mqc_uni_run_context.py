class TestMQCSessionRunContext:
    """The session builds one run context and every case carries it."""

    def MQC_CMN_UNI_112176_the_session_hands_every_case_the_run_context_it_built(
        self,
    ) -> None:
        """A full CI session running its preconditions is gated in every case.

        Returns:
            None
        """
        config = StubConfig()
        items = stub_items(PRECONDITION_NODE, GRADED_NODE)
        environ = workflow_environment("gate-gemini.yml")
        try:
            step(1, "adopt the session's run context")
            run = adopt_run_context(config, items, environ)
            assert run == session_run_context(config, items, environ) and run.gated, (
                f"the session built {run}"
            )

            step(2, "start the next case")
            emission.begin_case()
            assert emission.current_run_context() == run, (
                f"the case carried {emission.current_run_context()}"
            )
        finally:
            emission.reset_run_context()


class TestMQCPreconditionsRecord:
    """A preconditions job vouches for the graded jobs after it."""

    def MQC_CMN_UNI_112181_passing_preconditions_write_their_record(
        self, tmp_path: Path
    ) -> None:
        """A session whose preconditions passed writes a record a later band admits.

        Args:
            tmp_path (Path): Holds the record.

        Returns:
            None
        """
        record = tmp_path / "preconditions.json"
        write_preconditions_record(record, provenance_for("a1b2c3"), passed=True)
        assert read_preconditions_record(record, provenance_for("a1b2c3")) is True

    def MQC_CMN_UNI_112182_a_failed_precondition_removes_the_record(
        self, tmp_path: Path
    ) -> None:
        """A failure leaves no record behind, including one an earlier pass wrote.

        Args:
            tmp_path (Path): Holds the record.

        Returns:
            None
        """
        record = tmp_path / "preconditions.json"
        write_preconditions_record(record, provenance_for("a1b2c3"), passed=True)
        write_preconditions_record(record, provenance_for("a1b2c3"), passed=False)
        assert not record.exists(), "a stale pass outlived the failure"

    def MQC_CMN_UNI_112183_a_matching_record_counts_as_preconditions_executed(
        self, tmp_path: Path
    ) -> None:
        """A band job holding a matching record is gated, its engine and mode differing.

        Args:
            tmp_path (Path): Holds the record.

        Returns:
            None
        """
        record = tmp_path / "preconditions.json"
        write_preconditions_record(record, provenance_for("a1b2c3"), passed=True)
        config = StubConfig(
            options={"--preconditions-record": str(record), "--engine": "claude",
                     "--mode": "replay", "--priority": "0"},
            supplied={"priority": "0"},
        )
        environ = {**workflow_environment("gate-claude.yml"), "MQC_CODE_REF": "a1b2c3",
                   "MQC_CASE_REF": "c0ffee"}
        run = session_run_context(config, stub_items(GRADED_NODE), environ, system="Linux")
        assert run.preconditions_executed and run.gated, f"the band job built {run}"

    def MQC_CMN_UNI_112184_a_record_from_another_commit_is_refused_naming_the_field(
        self, tmp_path: Path
    ) -> None:
        """A record written at another harness commit refuses, naming ``code_ref``.

        Args:
            tmp_path (Path): Holds the record.

        Returns:
            None
        """
        record = tmp_path / "preconditions.json"
        write_preconditions_record(record, provenance_for("a1b2c3"), passed=True)
        with pytest.raises(ValueError, match="QC_HARNESS_PREREQUISITE_MISMATCH.*code_ref"):
            read_preconditions_record(record, provenance_for("d4e5f6"))

    def MQC_CMN_UNI_112185_an_absent_record_counts_as_not_executed_and_is_not_refused(
        self, tmp_path: Path
    ) -> None:
        """The boundary: a band run alone names a record nobody wrote, and is ungated.

        Args:
            tmp_path (Path): Where no record was written.

        Returns:
            None
        """
        record = tmp_path / "preconditions.json"
        assert read_preconditions_record(record, provenance_for("a1b2c3")) is False
