"""Unit tests for how a run learns its context and whether its preconditions held.

Created: 2026-10-21
Last updated: 2026-10-21

Its cases check ``detected_run_context`` in ``cmn/observations.py``, which reads
the run context from the environment; ``session_run_context`` and
``adopt_run_context`` in ``cmn/run_context.py``, which build the session's
run context and hand it to every case; and ``write_preconditions_record`` and
``read_preconditions_record`` in ``cmn/prerequisites.py``, through which a
preconditions job tells the graded jobs after it that the preconditions held.

The run context decides whether a row is gated, so whether the verdict tool
will judge a run and whether a collector keeps its rows. A failure here is
**not a model finding**, so the module carries no priority marker, per
``framework-rules.md`` section 3.3.

Specified by ``docs/design/cmn_verdict_and_cli.md`` section 7.1.4.
"""

