import ast
from pathlib import Path

import pytest

from cmn.selection import refuse_repeated_cases, select_named_tests
from tests.cmn.selection_support import SimulatedConfig, SimulatedItem

pytestmark = pytest.mark.unit

_ROOT = Path(__file__).resolve().parents[2]


class TestMQCExecutionIdentity:
    """One identifier, one test case, one execution."""

    def MQC_CMN_UNI_112153_an_identifier_collected_twice_refuses_the_run(self) -> None:
        """Each identifier once runs; one identifier collected twice refuses.

        The refusal names every repeated identifier with its count, and the
        repository's collection hook calls the guard.

        Design: ``cmn_verdict_and_cli.md`` section 7.8.5.

        Returns:
            None
        """
        distinct = [
            SimulatedItem("MQC_CMN_UNI_112056_a_rate"), SimulatedItem("MQC_CMN_UNI_112057_b")
        ]
        refuse_repeated_cases(distinct)

        repeated = [
            SimulatedItem("MQC_CMN_UNI_112056_a_rate[-0.5]"),
            SimulatedItem("MQC_CMN_UNI_112056_a_rate[1.5]"),
            SimulatedItem("MQC_CMN_UNI_112056_a_rate[2.0]"),
            SimulatedItem("MQC_CMN_UNI_112057_b"),
        ]
        with pytest.raises(ValueError, match="QC_HARNESS_CASE_REPEATED") as raised:
            refuse_repeated_cases(repeated)
        assert "112056" in str(raised.value) and "3" in str(raised.value), str(raised.value)
        assert "112057" not in str(raised.value), "a case collected once was named"

        hook = next(
            node for node in ast.walk(ast.parse((_ROOT / "conftest.py").read_text(
                encoding="utf-8")))
            if isinstance(node, ast.FunctionDef)
            and node.name == "pytest_collection_modifyitems"
        )
        called = {
            node.func.id for node in ast.walk(hook)
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
        }
        assert "refuse_repeated_cases" in called, (
            "the collection hook never calls the guard, so a repeated case runs"
        )

    def MQC_CMN_UNI_112154_a_named_list_selects_one_execution_per_identifier(
        self,
    ) -> None:
        """A list naming N identifiers keeps N items, and a repeated one refuses.

        Design: ``cmn_verdict_and_cli.md`` section 7.8.5.

        Returns:
            None
        """
        items = [SimulatedItem(f"MQC_CMN_UNI_11205{digit}_case") for digit in range(6)]
        select_named_tests(SimulatedConfig({"--tests": "112050,112052,112054"}), items)
        refuse_repeated_cases(items)
        assert len(items) == 3, [item.name for item in items]

        doubled = [SimulatedItem("MQC_CMN_UNI_112050_case[one]"),
                   SimulatedItem("MQC_CMN_UNI_112050_case[two]")]
        select_named_tests(SimulatedConfig({"--tests": "112050"}), doubled)
        with pytest.raises(ValueError, match="QC_HARNESS_CASE_REPEATED"):
            refuse_repeated_cases(doubled)
