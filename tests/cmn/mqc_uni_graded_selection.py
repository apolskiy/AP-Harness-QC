pytestmark = pytest.mark.unit


class TestMQCGradedSelectionCoverage:
    """A selection yielding a verdict covers every graded layer."""

    def MQC_CMN_UNI_112188_a_graded_invocation_leaving_out_a_layer_is_reported(
        self,
    ) -> None:
        """A graded step selecting part of the layers would still yield a verdict.

        **``-m`` is the layer dimension and is not read as a subset at
        runtime**, because every job selects its layer that way and the bands
        partition by priority inside it (``cmn_verdict_and_cli.md`` section
        7.1.4). Whether the expression is complete is therefore checked here,
        where it is a literal rather than a string that may have arrived
        through a workflow input.

        **This repository held the instance.** ``evaluate-live-weekly.yml`` ran
        gates 4, 5 and 6 as three steps selecting ``evaluator``, ``tool`` and
        ``sec`` separately, each recording ``selection_mode: full`` in a ``ci``
        context. They are one step now. A debug workflow is exempt by its
        cadence suffix, since its rows yield no verdict whatever they selected.

        **This repository's own definitions only.** The scanner is shared and
        ``MQC_CAS_UNI_115776`` calls it with the other root.

        Design: ``consumer_ci.md`` section 4.21.

        Returns:
            None
        """
        gaps = partial_graded_selection_gaps(Path(__file__).resolve().parents[2])

        assert not gaps, (
            "graded invocation(s) select part of the graded layers while the "
            "harness records a full selection, so their rows would carry a "
            "verdict over part of a run: " + "; ".join(gaps)
        )
