class TestMQCStrategyConformance:
    """Every registered strategy is implemented and carries the battery."""

    def MQC_EVL_UNI_114032_every_strategy_has_its_battery_cases(self) -> None:
        """Every registered strategy has a case of its own for each battery check.

        Design: ``harness_test_taxonomy.md`` section 1.1.

        Returns:
            None
        """
        module = Path(__file__)
        for helper in ("_emits_scale_id", "_is_deterministic",
                       "_handles_single_criterion", "_handles_empty"):
            missing = uncovered_members(module, helper, registered_strategies())
            assert not missing, f"{helper}: strategies with no case of their own: {missing}"

    def MQC_EVL_UNI_114006_every_declared_strategy_has_an_implementation(self) -> None:
        """The two halves of a registry entry must both exist.

        A strategy named in the scale table with no implementation, or the
        reverse, is a registration error rather than a runtime surprise, and a
        rubric naming it would fail deep inside a run.

        Returns:
            None
        """
        assert registered_strategies() == registered_aggregation_strategies()
        for strategy in _STRATEGIES:
            assert strategy_scale(strategy)

    def MQC_EVL_UNI_114007_an_unregistered_strategy_is_rejected_by_name(self) -> None:
        """A rubric naming a strategy nobody wrote fails with both lists.

        Returns:
            None
        """
        with pytest.raises(ValueError, match="QC_HARNESS_PARSER_ERROR") as caught:
            aggregate("geometric_mean", _scores(3.0))
        assert "geometric_mean" in str(caught.value)


class TestMQCPassMark:
    """A score at the mark, which is where a comparison drifts unnoticed."""

    def MQC_EVL_UNI_114010_a_score_at_the_pass_mark_exactly_passes(self) -> None:
        """The mark is inclusive, so a 3.0 against a 3.0 threshold passes.

        **This harness was designed to pass a 3.0 judgement grade**, and
        `tier3_evaluation.md` section 9 records that as a decision rather than
        a default: 36 of 479 recorded judgements passed on a minimum of exactly
        3.0 and would fail at any higher mark.

        **Nothing held it until this case.** Flipping `>=` to `>` in
        `aggregation.py` was caught by none of 772 cases, because the nearest
        case used 3.1 and called it marginal. That is near the boundary rather
        than at it, which `framework-rules.md` section 3.2 prohibits for
        exactly this reason.

        Returns:
            None
        """
        at_the_mark = aggregate("unweighted_mean", _scores(3.0, 3.0), threshold=3.0)

        assert at_the_mark.passed is True, (
            "a score equal to the pass mark failed, so the comparison excludes "
            "its own boundary and the mark is not the mark the design states"
        )
        assert at_the_mark.value == 3.0

        # AND JUST BELOW IT DOES NOT, so this states an inclusive boundary
        # rather than asserting that everything passes.
        below = aggregate("unweighted_mean", _scores(2.9, 2.9), threshold=3.0)
        assert below.passed is False

        # THE MARK IS A PARAMETER, NOT A CONSTANT. The harness supplies the
        # comparison and the corpus supplies the number, so a mark set above
        # 3.0 makes the same score fail. The switch is available by design.
        raised = aggregate("unweighted_mean", _scores(3.0, 3.0), threshold=4.0)
        assert raised.passed is False, (
            "the pass mark was ignored, so a corpus could not tighten its own "
            "standard even deliberately"
        )


    def MQC_EVL_UNI_114011_at_pass_mark_fail_rejects_a_score_on_the_mark(
        self,
    ) -> None:
        """The boundary moves without the mark moving, under `--at-pass-mark`.

        **`pass` is the default and the behaviour that shipped**, so a run
        that names nothing is judged exactly as every recorded result was.
        `fail` makes the mark exclusive, which is the stricter reading a
        consumer's product requirements may call for.

        **It can only tighten.** A score above the mark passes under either
        setting, so no value admits a result the default would reject. That is
        what separates it from the configurable threshold
        `harness_extensibility_standard.md` section 14 warns about.

        Design: section 9.

        Returns:
            None
        """
        on_the_mark = _scores(3.0, 3.0)

        assert aggregate(
            "unweighted_mean", on_the_mark, threshold=3.0
        ).passed is True, "the default stopped being inclusive"

        assert aggregate(
            "unweighted_mean", on_the_mark, threshold=3.0, at_pass_mark="pass"
        ).passed is True

        assert aggregate(
            "unweighted_mean", on_the_mark, threshold=3.0, at_pass_mark="fail"
        ).passed is False, (
            "at_pass_mark=fail accepted a score on the mark, so the switch "
            "the design offers does nothing"
        )

        # ABOVE THE MARK PASSES UNDER EITHER, which is what makes this a
        # tightening switch rather than a second threshold.
        for setting in ("pass", "fail"):
            clear = aggregate(
                "unweighted_mean", _scores(3.5, 3.5), threshold=3.0,
                at_pass_mark=setting,
            )
            assert clear.passed is True, f"{setting} rejected a clear pass"

        # AND A TYPO REFUSES, so a misspelling cannot silently leave the
        # boundary where it was while a reader believes it moved.
        with pytest.raises(ValueError, match="QC_HARNESS_PARSER_ERROR"):
            aggregate(
                "unweighted_mean", on_the_mark, threshold=3.0,
                at_pass_mark="strict",
            )


class TestMQCScaleComparability:
    """What may be compared, and what only looks as though it may."""

    def MQC_EVL_UNI_114001_scores_of_differing_scale_id_are_not_combined(self) -> None:
        """Two strategies on different scales produce numbers that look alike.

        A verdict of 1.0 and a mean of 1.0 are not the same claim, and nothing
        about the numbers says so. The scale travelling with the score is what
        makes the difference machine-checkable.

        Returns:
            None
        """
        continuous = aggregate("weighted_mean", _scores(4.0, 2.0))
        verdict = aggregate("all_must_pass", _scores(4.0, 2.0))
        tally = aggregate("threshold_count", _scores(4.0, 2.0))

        assert combinable(continuous, verdict) is False
        assert combinable(verdict, tally) is False
        assert combinable(continuous, aggregate("min", _scores(4.0))) is True
        assert len({continuous.scale_id, verdict.scale_id, tally.scale_id}) == 3

    def MQC_EVL_UNI_114002_score_recorded_on_pass_as_well_as_failure(self) -> None:
        """A pass at 3.1 and a pass at 4.8 are materially different signals.

        That distinction disappears entirely if only failures carry scores, and
        it is the distinction a trend over history is built from.

        Returns:
            None
        """
        marginal = aggregate("unweighted_mean", _scores(3.1, 3.1), threshold=3.0)
        strong = aggregate("unweighted_mean", _scores(4.8, 4.8), threshold=3.0)

        assert marginal.passed is True
        assert strong.passed is True
        assert marginal.value != strong.value
        assert marginal.evaluated and strong.evaluated

    def MQC_EVL_UNI_114008_weighting_changes_the_result_it_claims_to_weight(self) -> None:
        """The counterweight the weighted strategy needs.

        A weighted mean that ignored its weights would satisfy every case above,
        because equal weights make it identical to the unweighted one.

        Returns:
            None
        """
        weighted = [
            CriterionScore("MQC_CRT_major", 1.0, weight=4.0),
            CriterionScore("MQC_CRT_minor", 5.0, weight=1.0),
        ]
        assert aggregate("weighted_mean", weighted).value == pytest.approx(1.8)
        assert aggregate("unweighted_mean", weighted).value == pytest.approx(3.0)

    def MQC_EVL_UNI_114009_all_weights_zero_falls_back_rather_than_dividing(self) -> None:
        """A rubric declaring no criterion matters still has to produce a number.

        Dividing by a zero total would raise, and a silent zero would read as a
        quality finding. The unweighted mean is the only answer that is neither.

        Returns:
            None
        """
        unweighted_all = [
            CriterionScore("MQC_CRT_one", 2.0, weight=0.0),
            CriterionScore("MQC_CRT_two", 4.0, weight=0.0),
        ]
        assert aggregate("weighted_mean", unweighted_all).value == pytest.approx(3.0)
