        judge = RecordingJudge(score=5)
        step(1, "evaluate the clarification on a case declaring a payload")
        result = evaluate_observation(
            observation_context(figure_rule, _CLARIFICATION, declared_adversarial=True),
            judge.binding(),
        )
        assert result.judge_skipped_reason == DECLARED_ADVERSARIAL, (
            f"the skip reason is not the declared payload: {result.judge_skipped_reason}"
        )

        step(2, "count the judge requests")
        assert not judge.requests, (
            f"a declared payload's case reached the judge {len(judge.requests)} time(s)"
        )
