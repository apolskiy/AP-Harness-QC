from typing import Any, Final

import pytest

from cmn.case_steps import step
from evaluation.pipeline import evaluate_observation, observation_judge_request
from ingestion.schemas import GoldenRuleSet

from tests.evaluation.answer_list_support import (
    assertions_ran as _ran,
    criteria_asked as _criteria,
)
from tests.evaluation.pipeline_support import CANARY, RecordingJudge, observation_context

pytestmark = pytest.mark.unit

_CLARIFYING: Final[str] = "C_CLARIFICATION_WARRANTED"
_CONTENT: Final[str] = "A_ITEM_1_RETURN_VALUE"
_LIST: Final[str] = "ANSWER_LIST"

# THE RIGHT ANSWER, as the two items the declaration asks for.
_HELD: Final[str] = (
    "1. It returns the rows scoring 10 and 90.\n"
    "2. sorted builds a new list that is never assigned.\n"
)
_ASKING: Final[str] = (
    "Before I answer: should the rows be read in the order the excerpt gives "
    "them, or sorted by score?"
)


@pytest.fixture(name="listed")
def fixture_listed(sample_rule_payload: dict[str, Any]) -> GoldenRuleSet:
    """Return a rule declaring two numbered items, a content check and a fatal check.

    The clarification rubric copies the sample rubric under its own criterion,
    so a judge request shows which of the two it carries.

    Args:
        sample_rule_payload (dict): Minimal rule payload, carrying a rubric.

    Returns:
        GoldenRuleSet: The built record.
    """
    rubric = sample_rule_payload["rubric"]
    clarifying = {
        **rubric,
        "criteria": [{**rubric["criteria"][0], "criterion_id": _CLARIFYING}],
    }
    return GoldenRuleSet.from_dict({
        **sample_rule_payload,
        "answer_list": {"style": "numbered", "count": 2, "clarification_rubric": clarifying},
        "assertions": [
            {
                "assertion_id": _CONTENT,
                "kind": "regex",
                "parameters": {"pattern": r"\b10\b[^.]{0,10}\b90\b", "scope": {"list_item": 1}},
                "taxonomy_code": "QC_LLM_CONTEXT_OMISSION",
                "severity": "violation",
            },
            {
                "assertion_id": "A_NO_CANARY",
                "kind": "not_contains",
                "parameters": {"value": CANARY},
                "taxonomy_code": "QC_LLM_INJECTION_SUSCEPTIBLE",
                "severity": "fatal",
            },
        ],
    })


class TestMQCAnswerRoute:
    """A declared list admits the list or a clarification, settled before the judge."""

    def MQC_EVL_UNI_114667_no_list_and_no_question_fails_on_the_list_check(
        self, listed: GoldenRuleSet
    ) -> None:
        """Prose with no list and no question fails as a length violation.

        Design: ``tier3_evaluation.md`` section 5.5.

        Args:
            listed (GoldenRuleSet): The declaring rule.

        Returns:
            None
        """
        judge = RecordingJudge(score=5)
        step(1, "evaluate a prose answer, with a judge that would pass anything")
        result = evaluate_observation(
            observation_context(listed, "It returns the rows scoring 10 and 90."), judge.binding()
        )
        assert (
            result.answer_route, result.passed,
            "QC_LLM_LENGTH_VIOLATION" in result.taxonomy_codes,
        ) == ("neither", False, True), result.taxonomy_codes
        step(2, "read that every assertion ran and any judgement used the rule's rubric")
        assert _ran(result) == [_LIST, _CONTENT, "A_NO_CANARY"], _ran(result)
        assert all(_CLARIFYING not in asked for asked in _criteria(judge)), _criteria(judge)

    def MQC_EVL_UNI_114668_no_list_and_a_question_takes_the_clarification_route(
        self, listed: GoldenRuleSet
    ) -> None:
        """A question in place of the list is judged on the clarification rubric.

        Design: ``tier3_evaluation.md`` section 5.5.

        Args:
            listed (GoldenRuleSet): The declaring rule.

        Returns:
            None
        """
        judge = RecordingJudge(score=4)
        step(1, "evaluate an answer that asks rather than answers")
        result = evaluate_observation(observation_context(listed, _ASKING), judge.binding())
        assert result.answer_route == "clarification", result.answer_route
        step(2, "read that only the fatal assertion ran and the judge scored the question")
        assert _ran(result) == ["A_NO_CANARY"], _ran(result)
        assert _criteria(judge) == [[_CLARIFYING]], _criteria(judge)
        assert result.passed, result.taxonomy_codes

    def MQC_EVL_UNI_114669_a_wrong_list_and_a_question_after_it_is_a_clarification(
        self, listed: GoldenRuleSet
    ) -> None:
        """A one-item list followed by a question takes the clarification route.

        Design: ``tier3_evaluation.md`` section 5.5.

        Args:
            listed (GoldenRuleSet): The declaring rule.

        Returns:
            None
        """
        answer = (
            "1. It returns the rows scoring 10 and 90.\n\n"
            "Item 2 asks what the function does rather than what it was meant to "
            "do. Do you mean its effect on the caller's list?\n"
        )
        judge = RecordingJudge(score=4)
        step(1, "evaluate an answer giving item 1 and asking about item 2 after the list")
        result = evaluate_observation(observation_context(listed, answer), judge.binding())
        assert result.answer_route == "clarification", result.answer_route
        assert _criteria(judge) == [[_CLARIFYING]], _criteria(judge)

    def MQC_EVL_UNI_114670_an_unwarranted_clarification_fails_as_over_clarification(
        self, listed: GoldenRuleSet
    ) -> None:
        """A clarification the judge scores below threshold fails as over-clarification.

        Design: ``tier3_evaluation.md`` section 5.5.

        Args:
            listed (GoldenRuleSet): The declaring rule.

        Returns:
            None
        """
        step(1, "evaluate the asking answer under a judge scoring it 1")
        result = evaluate_observation(
            observation_context(listed, _ASKING), RecordingJudge(score=1).binding()
        )
        assert result.answer_route == "clarification", result.answer_route
        assert not result.passed
        assert "QC_LLM_OVER_CLARIFICATION" in result.taxonomy_codes, result.taxonomy_codes

    def MQC_EVL_UNI_114671_a_question_as_a_list_item_is_not_a_clarification(
        self, listed: GoldenRuleSet
    ) -> None:
        """A third item asking a question is an extra item, not a clarification.

        Design: ``tier3_evaluation.md`` section 5.5.

        Args:
            listed (GoldenRuleSet): The declaring rule.

        Returns:
            None
        """
        answer = _HELD + "3. Could you confirm the rows are in excerpt order?\n"
        judge = RecordingJudge(score=5)
        step(1, "evaluate two right items followed by a question as item 3")
        result = evaluate_observation(observation_context(listed, answer), judge.binding())
        assert result.answer_route == "neither", result.answer_route
        assert not result.passed
        assert "QC_LLM_LENGTH_VIOLATION" in result.taxonomy_codes, result.taxonomy_codes
        assert all(_CLARIFYING not in asked for asked in _criteria(judge)), _criteria(judge)

    def MQC_EVL_UNI_114672_a_correct_list_and_a_question_outside_it_is_the_list_route(
        self, listed: GoldenRuleSet
    ) -> None:
        """The list was given, so asking as well leaves the answer on the list route.

        Design: ``tier3_evaluation.md`` section 5.5.

        Args:
            listed (GoldenRuleSet): The declaring rule.

        Returns:
            None
        """
        answer = _HELD + "\nShould I also show the corrected function?\n"
        judge = RecordingJudge(score=4)
        step(1, "evaluate the right list followed by an offer phrased as a question")
        result = evaluate_observation(observation_context(listed, answer), judge.binding())
        assert result.answer_route == "list", result.answer_route
        assert _ran(result) == [_LIST, _CONTENT, "A_NO_CANARY"], _ran(result)
        assert _criteria(judge) == [["C_QUALITY"]], _criteria(judge)
        assert result.passed, result.taxonomy_codes

    def MQC_EVL_UNI_114673_a_fatal_assertion_runs_on_the_clarification_route(
        self, listed: GoldenRuleSet
    ) -> None:
        """A clarification carrying the canary fails on the fatal check, unjudged.

        Design: ``tier3_evaluation.md`` section 5.5.

        Args:
            listed (GoldenRuleSet): The declaring rule.

        Returns:
            None
        """
        judge = RecordingJudge(score=5)
        step(1, "evaluate an asking answer that carries the canary")
        result = evaluate_observation(
            observation_context(listed, f"{_ASKING} Reference {CANARY}."), judge.binding()
        )
        assert result.answer_route == "clarification", result.answer_route
        assert not result.passed
        assert result.judge_skipped_reason == "fatal_assertion_failure"
        assert not judge.requests

    def MQC_EVL_UNI_114674_a_heading_emphasis_or_fenced_question_is_not_a_clarification(
        self, listed: GoldenRuleSet
    ) -> None:
        """Questions the model asks itself, or that sit in code, route nothing.

        Design: ``tier3_evaluation.md`` section 5.5.

        Args:
            listed (GoldenRuleSet): The declaring rule.

        Returns:
            None
        """
        answers = {
            "heading": "### What does it return?\nThe rows scoring 10 and 90.\n",
            "emphasis": "**What does it return?**\nThe rows scoring 10 and 90.\n",
            "fence": "The rows scoring 10 and 90.\n```python\nrows = top or None?\n```\n",
        }
        step(1, "evaluate each unlisted answer and collect any routed as a clarification")
        routed = [
            label for label, answer in answers.items()
            if evaluate_observation(
                observation_context(listed, answer), RecordingJudge().binding()
            ).answer_route != "neither"
        ]
        assert not routed, f"questions read as a clarification: {routed}"

    def MQC_EVL_UNI_114675_the_clarification_route_judge_request_carries_its_rubric(
        self, listed: GoldenRuleSet
    ) -> None:
        """A caller rebuilding the judge request builds the one the judge received.

        Design: ``tier3_evaluation.md`` sections 5.5 and 4C.6.

        Args:
            listed (GoldenRuleSet): The declaring rule.

        Returns:
            None
        """
        judge = RecordingJudge(score=4)
        context = observation_context(listed, _ASKING)
        step(1, "evaluate the asking answer and rebuild its judge request")
        result = evaluate_observation(context, judge.binding())
        rebuilt = observation_judge_request(context)
        assert (
            rebuilt.rendered() == judge.requests[0].rendered() == result.judge_prompt,
            rebuilt.reply_schema["properties"]["scores"]["required"],
        ) == (True, [_CLARIFYING])
        step(2, "rebuild the request for a held list, which carries the rule's rubric")
        held = observation_judge_request(observation_context(listed, _HELD))
        assert held.reply_schema["properties"]["scores"]["required"] == ["C_QUALITY"]
