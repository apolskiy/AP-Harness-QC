"""Unit cases for the route an answer takes when its rule declares a list.

Created: 2026-11-04
Last updated: 2026-11-04

Its cases check :func:`evaluation.pipeline.evaluate_observation` and
:func:`evaluation.pipeline.observation_judge_request` on a rule declaring a
two-item numbered list. An answer holding the list takes the list route; one
that does not, and asks a question outside the list, takes the clarification
route, runs only its fatal assertions and is judged on the clarification
rubric, failing below it as over-clarification; one that does neither fails on
the list check. A question opening an item, a heading, an emphasis line or a
fenced line is not a clarification, and a correct list with a question outside
it takes the list route.

Specified by ``docs/design/tier3_evaluation.md`` section 5.5.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.
"""

