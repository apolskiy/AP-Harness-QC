class TestMQCCalibrationTolerance:
    """How far the judge may drift before the rubric is no longer usable."""

    def MQC_EVL_UNI_114200_calibration_exact_match_passes(self) -> None:
        """The judge landed on the level the exemplar was written for.

        Returns:
            None
        """
        result = compare_to_anchor(_CRITERION, 3, 3.0)
        assert result.passed is True
        assert result.exact is True
        assert result.deviation == 0
        assert result.drifted_within_tolerance is False

    def MQC_EVL_UNI_114208_a_score_one_level_below_passes_and_records(self) -> None:
        """A judged score one level below the exemplar's passes, and the deviation is recorded.

        Returns:
            None
        """
        self._one_level_deviation(2.0)

    def MQC_EVL_UNI_114209_a_score_one_level_above_passes_and_records(self) -> None:
        """A judged score one level above the exemplar's passes, and the deviation is recorded.

        Returns:
            None
        """
        self._one_level_deviation(4.0)

    def _one_level_deviation(
        self, observed: float
    ) -> None:
        """The boundary, stated at one level exactly and in both directions.

        A single level of disagreement between an anchor and a judge is within
        what a five-point scale can be expected to resolve. Two is not.

        Args:
            observed (float): What the judge awarded a level 3 exemplar.

        Returns:
            None
        """
        result = compare_to_anchor(_CRITERION, 3, observed)
        assert result.passed is True
        assert result.exact is False
        assert result.deviation == 1.0
        assert result.drifted_within_tolerance is True

    def MQC_EVL_UNI_114210_a_score_two_levels_below_fails_calibration(self) -> None:
        """A judged score two levels below the exemplar's fails calibration.

        Returns:
            None
        """
        self._two_level_deviation(1.0)

    def MQC_EVL_UNI_114211_a_score_two_levels_above_fails_calibration(self) -> None:
        """A judged score two levels above the exemplar's fails calibration.

        Returns:
            None
        """
        self._two_level_deviation(5.0)

    def _two_level_deviation(self, observed: float) -> None:
        """Two levels apart means the rubric or the judge has drifted.

        Scores from a rubric in that state cannot be compared with earlier
        ones, which is the whole purpose of running calibration at all.

        Args:
            observed (float): What the judge awarded a level 3 exemplar.

        Returns:
            None
        """
        result = compare_to_anchor(_CRITERION, 3, observed)
        assert result.passed is False
        assert result.deviation == 2.0
        assert tolerance() == 1

    def MQC_EVL_UNI_114203_deviation_within_tolerance_is_recorded_for_trend(self) -> None:
        """Recording a tolerated deviation is what makes trend visible.

        A rubric drifting steadily by one level passes every run and is obvious
        only across many. Discarding the deviation because it passed would
        discard the only signal that distinguishes drift from stability.

        Returns:
            None
        """
        drifting = [compare_to_anchor(_CRITERION, 3, 4.0) for _ in range(5)]
        stable = [compare_to_anchor(_CRITERION, 3, 3.0) for _ in range(5)]

        assert all(result.passed for result in drifting + stable)
        assert sum(result.deviation for result in drifting) == 5.0
        assert sum(result.deviation for result in stable) == 0.0
        assert all(result.drifted_within_tolerance for result in drifting)


class TestMQCCalibrationOverARubric:
    """Applying calibration to every anchor that carries an exemplar."""

    def MQC_EVL_UNI_114204_an_anchor_without_an_exemplar_yields_no_result(
        self, sample_rubric_record: Rubric
    ) -> None:
        """Nothing was measured, so nothing passes.

        A manufactured pass would make an uncalibrated rubric look verified,
        which is worse than reporting that it was never checked.

        Args:
            sample_rubric_record (Rubric): The rubric to calibrate.

        Returns:
            None
        """
        criterion = sample_rubric_record.criteria[0]
        observed = {criterion.criterion_id: {level: 3.0 for level in criterion.anchors}}
        results = calibrate_rubric(sample_rubric_record, observed)

        exemplars = [
            level for level in criterion.anchors
            if criterion.anchors[level].exemplar is not None
        ]
        assert len(results) == len(exemplars)

    def MQC_EVL_UNI_114205_an_unjudged_exemplar_yields_no_result(
        self, sample_rubric_record: Rubric
    ) -> None:
        """A calibration run that reached no judge measured nothing.

        Args:
            sample_rubric_record (Rubric): The rubric to calibrate.

        Returns:
            None
        """
        assert not calibrate_rubric(sample_rubric_record, {})


class TestMQCCalibrationThroughTheJudge:
    """Sending each exemplar to a judge, and comparing what comes back."""

    def MQC_EVL_UNI_114212_an_exemplar_reaches_the_judge_on_its_own_criterion(self) -> None:
        """One request per exemplar, carrying the rule's material and one criterion.

        Design: ``tier3_evaluation.md`` section 9.1.

        Returns:
            None
        """
        material = rule_material()
        requests = calibration_requests(_CASE_ID, calibration_rubric(), material)

        sent = {(item.criterion_id, item.intended_level) for item in requests}
        expected = {
            (criterion_id, level)
            for criterion_id, exemplars in EXEMPLARS.items() for level in exemplars
        }
        assert sent == expected
        for item in requests:
            judged = item.judge_request
            other = next(name for name in EXEMPLARS if name != item.criterion_id)
            assert judged.data["candidate_output"] == (
                EXEMPLARS[item.criterion_id][item.intended_level]
            )
            assert judged.data["task_instruction"] == material.task_instruction
            assert judged.data["system_instruction"] == material.system_instruction
            assert judged.data["context_document.report"] == (
                material.context_documents["report"]
            )
            assert judged.instruction_contains(f"- {item.criterion_id}:")
            assert not judged.instruction_contains(other)
            assert judged.reply_schema["properties"]["scores"]["required"] == [
                item.criterion_id
            ]
            assert judged.observation_index == item.intended_level

    def MQC_EVL_UNI_114213_a_calibration_judgement_never_addresses_a_graded_one(
        self, tmp_path: Path
    ) -> None:
        """A recording judge stores a calibration score where no graded one lives.

        Design: ``tier3_evaluation.md`` section 9.1.1.

        Args:
            tmp_path (Path): A fixture root.

        Returns:
            None
        """
        requests = calibration_requests(_CASE_ID, calibration_rubric(), rule_material())

        def stored_at(case_id: str, observation: int) -> Path:
            """Return where a recording judge would store this judgement.

            Args:
                case_id (str): The request's case identifier.
                observation (int): Its observation index.

            Returns:
                Path: The judgement file.
            """
            return JudgementKey(case_id, "grok", "gemini", observation).path(tmp_path)

        graded = {stored_at(_CASE_ID, observation) for observation in range(6)}
        graded_directory = stored_at(_CASE_ID, 0).parent.parent
        calibration = [
            stored_at(item.judge_request.case_id, item.judge_request.observation_index)
            for item in requests
        ]
        assert len(set(calibration)) == len(requests)
        assert not graded & set(calibration)
        assert all(graded_directory not in path.parents for path in calibration)

    def MQC_EVL_UNI_114214_calibrate_compares_what_the_judge_awarded_each_exemplar(
        self,
    ) -> None:
        """A judge scoring each exemplar at its level calibrates exactly.

        Design: ``tier3_evaluation.md`` section 9.1.

        Returns:
            None
        """
        judge = StandInJudge(lambda level: level)
        results = calibrate(
            _CASE_ID, calibration_rubric(), rule_material(), judge, judge_engine="gemini"
        )

        assert len(judge.calls) == 5
        assert len(results) == 5
        assert all(result.passed and result.exact for result in results)

    def MQC_EVL_UNI_114215_an_exemplar_the_judge_scores_two_levels_away_fails(self) -> None:
        """A judge awarding 5 to everything fails the exemplars at 1 and 3.

        Design: ``tier3_evaluation.md`` section 9.1.

        Returns:
            None
        """
        results = calibrate(
            _CASE_ID, calibration_rubric(), rule_material(),
            StandInJudge(lambda level: 5), judge_engine="gemini",
        )

        failed = {(result.criterion_id, result.intended_level)
                  for result in results if not result.passed}
        assert failed == {("C_SOURCE", 1), ("C_SOURCE", 3), ("C_ARITHMETIC", 1)}

    def MQC_EVL_UNI_114216_an_uncalibrated_judge_is_reported_by_its_code(self) -> None:
        """The message leads with the registered code and names every misplaced exemplar.

        Design: ``tier3_evaluation.md`` section 9.3.

        Returns:
            None
        """
        results = calibrate(
            _CASE_ID, calibration_rubric(), rule_material(),
            StandInJudge(lambda level: 5), judge_engine="gemini",
        )
        message = uncalibrated_message("source_fidelity", [
            f"{_CASE_ID} {result.criterion_id} level {result.intended_level} "
            f"scored {result.observed_score:g}"
            for result in results if not result.passed
        ])

        assert message.startswith("QC_HARNESS_JUDGE_UNCALIBRATED: ")
        assert "placed 3 source_fidelity exemplar(s)" in message
        assert f"{_CASE_ID} C_ARITHMETIC level 1 scored 5" in message
        assert f"{_CASE_ID} C_SOURCE level 3 scored 5" in message


class TestMQCObservationVariance:
    """The second drift signal, which needs no new machinery."""

    def MQC_EVL_UNI_114206_variance_across_observations_is_reported(self) -> None:
        """High variance on identical input means the anchors do not discriminate.

        A4 already produces three observations, so this signal costs nothing
        beyond reading what is there.

        Returns:
            None
        """
        assert observation_variance([3.0, 3.0, 3.0]) == 0.0
        assert observation_variance([1.0, 3.0, 5.0]) == 4.0

    def MQC_EVL_UNI_114207_variance_is_undefined_below_two_observations(self) -> None:
        """Reporting zero would make one observation look maximally consistent.

        Returns:
            None
        """
        assert observation_variance([]) is None
        assert observation_variance([4.0]) is None
