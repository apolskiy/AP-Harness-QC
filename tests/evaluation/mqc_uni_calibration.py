    def MQC_EVL_UNI_114222_one_criterion_below_threshold_counts_though_the_mean_clears(
        self, checked: GoldenRuleSet
    ) -> None:
        """Scores of 5 and 2 average 3.5, which clears 3, and the judge still caught it.

        Design: ``tier3_evaluation.md`` section 9.1.

        Args:
            checked (GoldenRuleSet): The checked rule set.

        Returns:
            None
        """
        judge = RecordingJudge(score=5, by_criterion={DEPTH: 2})
        outcome = calibrate_sample(
            calibration_case(checked),
            sample(HEDGED, violates=[NO_HEDGE], mistake="hedges the figure with about"),
            judge.binding(),
        )
        step(1, "read the rubric verdict the graded path computed")
        assert outcome.result.score.passed, (
            f"the mean of 5 and 2 did not clear 3, so this case does not test the "
            f"boundary: {outcome.result.score}"
        )
        step(2, "read the calibration outcome")
        assert outcome.agreed, (
            f"a criterion scored 2 under a mean that cleared did not count as caught: "
            f"{outcome.disagreement}"
        )

