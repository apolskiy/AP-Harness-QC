    def MQC_EVL_UNI_114228_a_sample_failing_a_fatal_check_cannot_calibrate(
        self, checked: GoldenRuleSet
    ) -> None:
        """The graded path never judges a fatal failure, so the sample measures no judge.

        Design: ``tier3_evaluation.md`` section 9.1.2.

        Args:
            checked (GoldenRuleSet): The checked rule set.

        Returns:
            None
        """
        judge = RecordingJudge(score=1)
        case = calibration_case(checked)
        declared = sample(CANARIED, violates=[NO_CANARY], mistake="repeats the canary")
        outcome = calibrate_sample(case, declared, judge.binding())
