# THE CODE THE JUDGE'S ADAPTER MAPS A TIMEOUT TO, and the one it is recorded
# under. Section 6.5.2.
_CANDIDATE_TIMEOUT = "QC_HARNESS_CANDIDATE_TIMEOUT"
_JUDGE_TIMEOUT = "QC_HARNESS_JUDGE_TIMEOUT"


class TestMQCJudgementAvailability:
    """A gap in the judgement store, and what it is allowed to report."""

    def MQC_EVL_UNI_114115_an_unavailable_judgement_skips_and_keeps_its_assertions(
        self,
        rules: GoldenRuleSet,
    ) -> None:
        """A recording gap measures nothing, and says so without failing.

        **A `QC_HARNESS_*` event is a skip, never a failure**
        (`framework-rules.md` section 4). The candidate path learned this when
        both store exceptions escaped dispatch as errors, because each
        inherits from ``Exception`` alone and the handler was written for
        ``ValueError``. This is the judge side of the same gap.

        **It surfaced when an assertion was repaired.** Assertions gate
        judging, so a case whose assertion failed never reached the judge and
        no judgement was ever recorded for it. Fix the assertion and the
        observation arrives at a store that has nothing for it.

        **The assertion results travel with the skip**, which is the point: an
        observation that failed an assertion still reports that failure under
        its own model code, and only the judged half is missing.

        Design: ``tier3_evaluation.md`` section 6.5.

        Args:
            rules (GoldenRuleSet): The rule set.

        Returns:
            None
        """
        for error, expected in (
            (FixtureMissing(MissingArtifact(kind="judgement", path="j/0.json", detail="is absent")),
             ARTIFACT_MISSING),
            (FixtureStale("QC_HARNESS_FIXTURE_STALE: recorded elsewhere"),
             "QC_HARNESS_FIXTURE_STALE"),
        ):
            result = evaluate_observation(
                observation_context(
                    rules,
                    "It requires five years of Python.",
                    produced_output=True,
                ),
                refusing_judge(error),
            )
            assert result.judged is False, (
                f"a judgement that could not be replayed was counted as made, "
                f"so a gap in the recordings scores as a result: {expected}"
            )
            assert result.judge_skipped_reason == "judgement_unavailable", (
                f"the skip does not name itself, so a reader cannot tell a "
                f"recording gap from a judge that replied unusably: "
                f"{result.judge_skipped_reason!r}"
            )
            assert expected in result.taxonomy_codes, (
                f"the store's own code is absent, so the two gaps are "
                f"indistinguishable: {result.taxonomy_codes}"
            )

            # AND THE ASSERTIONS SURVIVED. Discarding them would throw away the
            # measurement that did happen along with the one that did not.
            assert result.assertion_results, (
                "the assertion results were dropped with the judgement, so an "
                "observation that failed an assertion now reports nothing"
            )

    def MQC_EVL_UNI_114117_a_judge_the_provider_could_not_answer_is_unavailable(
        self,
        rules: GoldenRuleSet,
    ) -> None:
        """No reply is unavailable with the provider's code; a bad reply is unusable.

        Design: ``tier3_evaluation.md`` section 6.5.1.

        Args:
            rules (GoldenRuleSet): The rule set.

        Returns:
            None
        """
        outage = evaluate_observation(
            observation_context(rules, "It requires five years of Python.", produced_output=True),
            refusing_judge(ValueError(
                "QC_HARNESS_PROVIDER_UNAVAILABLE: the judge could not be reached for x"
            )),
        )
        assert outage.judge_skipped_reason == "judgement_unavailable", (
            f"a judge the provider never answered was recorded as "
            f"{outage.judge_skipped_reason!r}, so the observation counts against the model"
        )
        assert "QC_HARNESS_PROVIDER_UNAVAILABLE" in outage.taxonomy_codes, outage.taxonomy_codes
        assert "QC_HARNESS_PARSER_ERROR" not in outage.taxonomy_codes, outage.taxonomy_codes

        garbled = evaluate_observation(
            observation_context(rules, "It requires five years of Python.", produced_output=True),
            refusing_judge(ValueError("QC_HARNESS_PARSER_ERROR: the reply was not JSON")),
        )
        assert garbled.judge_skipped_reason == "judge_reply_unusable", garbled.judge_skipped_reason

    def MQC_EVL_UNI_114146_an_unreplayable_judgement_carries_the_missing_artifact(
        self,
        rules: GoldenRuleSet,
        tmp_path: Path,
    ) -> None:
        """An absent or malformed stored judgement is unavailable, with the code and the record.

        Design: ``tier3_evaluation.md`` section 6.5, ``tier2_execution.md``
        section 7.6.2.

        Args:
            rules (GoldenRuleSet): The rule set.
            tmp_path (Path): The fixture root.

        Returns:
            None
        """
        step(1, "evaluate an observation whose judgement the store does not hold")
        key = JudgementKey(
            case_id="MQC_TASK_alpha::MQC_RULE_grounding", candidate_engine="claude",
            judge_engine="gemini", observation_index=0,
        )
        absent = evaluate_observation(
            observation_context(rules, "It requires five years of Python.", produced_output=True),
            stored_judge(tmp_path, key),
        )
        assert (
            absent.judge_skipped_reason == "judgement_unavailable"
            and ARTIFACT_MISSING in absent.taxonomy_codes
            and absent.missing_artifact is not None
            and absent.missing_artifact.kind == "judgement"
            and absent.missing_artifact.path == str(key.path(tmp_path))
            and absent.assertion_results
        ), (absent.judge_skipped_reason, absent.taxonomy_codes, absent.missing_artifact)

        step(2, "evaluate one whose stored judgement will not parse")
        key.path(tmp_path).parent.mkdir(parents=True, exist_ok=True)
        key.path(tmp_path).write_text("{ truncated", encoding="utf-8")
        garbled = evaluate_observation(
            observation_context(rules, "It requires five years of Python.", produced_output=True),
            stored_judge(tmp_path, key),
        )
        assert (
            garbled.judge_skipped_reason == "judgement_unavailable"
            and ARTIFACT_MISSING in garbled.taxonomy_codes
            and "QC_HARNESS_PARSER_ERROR" not in garbled.taxonomy_codes
        ), (garbled.judge_skipped_reason, garbled.taxonomy_codes)

    def MQC_EVL_UNI_114423_a_timed_out_judge_is_recorded_under_the_judge_code(
        self,
        rules: GoldenRuleSet,
    ) -> None:
        """A judge timing out after passing assertions is unavailable under the judge's code.

        Design: ``tier3_evaluation.md`` section 6.5.2.

        Args:
            rules (GoldenRuleSet): The rule set.

        Returns:
            None
        """
        result = evaluate_observation(
            observation_context(rules, "It requires five years of Python.", produced_output=True),
            refusing_judge(ValueError(f"{_CANDIDATE_TIMEOUT}: the judge could not be reached")),
        )

        step(1, "find the observation unavailable under the judge's timeout code alone")
        assert (
            result.judge_skipped_reason == "judgement_unavailable"
            and _JUDGE_TIMEOUT in result.taxonomy_codes
            and _CANDIDATE_TIMEOUT not in result.taxonomy_codes
        ), (result.judge_skipped_reason, result.taxonomy_codes)

    def MQC_EVL_UNI_114424_a_judge_timeout_keeps_a_failed_assertion_and_skips(
        self,
        rules: GoldenRuleSet,
    ) -> None:
        """A judge timing out after a failed assertion skips, the failure and its code kept.

        Design: ``tier3_evaluation.md`` section 6.5.2.

        Args:
            rules (GoldenRuleSet): The rule set.

        Returns:
            None
        """
        result = evaluate_observation(
            observation_context(rules, "It requires some experience.", produced_output=True),
            refusing_judge(ValueError(f"{_CANDIDATE_TIMEOUT}: the judge could not be reached")),
        )
        failed = [entry for entry in result.assertion_results if not entry.passed]

        step(1, "find the observation unavailable under the judge's timeout code")
        assert (
            result.judge_skipped_reason == "judgement_unavailable"
            and _JUDGE_TIMEOUT in result.taxonomy_codes
            and _CANDIDATE_TIMEOUT not in result.taxonomy_codes
        ), (result.judge_skipped_reason, result.taxonomy_codes)

        step(2, "find the failed assertion and its model code kept for review")
        assert failed and any(
            str(code).startswith("QC_LLM_") for code in result.taxonomy_codes
        ), (result.assertion_results, result.taxonomy_codes)
