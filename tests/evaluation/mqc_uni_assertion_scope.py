"""Unit cases for an assertion that reads one numbered item of the answer.

Created: 2026-11-04
Last updated: 2026-11-05

Its cases check ``scope: {list_item: N}`` through
:func:`evaluation.assertions.run_assertion`. A scoped assertion reads only the
item it names, so a sentence in another item cannot fail it; an answer with no
such item fails it whatever ``present`` says; an indented number is a sub-list
and neither ends an item nor opens one; and an item opens at the margin inside
markdown emphasis or after heading marks as well as bare.

Specified by ``docs/design/tier3_evaluation.md`` section 5.4.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.
"""

