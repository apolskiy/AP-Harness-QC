from typing import Any, Final

import pytest

from cmn.case_steps import step
from evaluation.assertions import run_assertion

from tests.evaluation.assertion_support import (
    programmatic_assertion as _assertion,
)

pytestmark = pytest.mark.unit


# THE SHAPE THAT PRODUCED THE PARAMETER: the right return value in item 1 and a
# true sentence about a repaired function in item 2, which a whole-answer claim
# read as the wrong answer (design section 5.4).
_ANSWER: Final[str] = (
    "1. It returns the rows scoring 10 and 90, in that order.\n"
    "2. sorted builds a new list that is never assigned, so it is discarded.\n"
    "### Fix (for reference)\n"
    "With the result assigned, this returns the rows scoring 90 and 50.\n"
)
# THE CLAIM FORBIDDING THE INTENDED-BUT-WRONG ANSWER, over the whole answer and
# over item 1, so the scoped pass is shown not to be vacuous.
_WRONG_ANSWER: Final[dict[str, Any]] = {
    "pattern": r"(?i)\breturns?\b[^.]{0,40}\b90\b[^.]{0,25}\b50\b",
    "present": False,
    "unless": ["appears"],
}
_FORBIDS_ANYWHERE: Final[Any] = _assertion("claim", _WRONG_ANSWER)
_FORBIDS_IN_ITEM_1: Final[Any] = _assertion(
    "claim", {**_WRONG_ANSWER, "scope": {"list_item": 1}}
)


class TestMQCAssertionScope:
    """A scoped assertion reads the numbered item it names, and nothing else."""

    def MQC_EVL_UNI_114656_a_scoped_assertion_reads_only_its_numbered_item(
        self,
    ) -> None:
        """A sentence outside the named item neither fails nor satisfies it.

        Design: ``tier3_evaluation.md`` section 5.4.

        Returns:
            None
        """
        step(1, "show the whole-answer claim fails, so the scoped pass is not vacuous")
        assert not run_assertion(_FORBIDS_ANYWHERE, _ANSWER).passed
        step(2, "scope the same claim to item 1 and confirm it passes")
        scoped = run_assertion(_FORBIDS_IN_ITEM_1, _ANSWER)
        assert scoped.passed, scoped.detail
        step(3, "require the right answer in item 1, then in item 2 where it is absent")
        required = {"pattern": r"\b10\b[^.]{0,10}\b90\b", "present": True}
        assert run_assertion(
            _assertion("regex", {**required, "scope": {"list_item": 1}}), _ANSWER
        ).passed
        assert not run_assertion(
            _assertion("regex", {**required, "scope": {"list_item": 2}}), _ANSWER
        ).passed

    def MQC_EVL_UNI_114657_a_scoped_assertion_fails_an_answer_missing_its_item(
        self,
    ) -> None:
        """An answer without the named item fails, whatever present says.

        Design: ``tier3_evaluation.md`` section 5.4.

        Returns:
            None
        """
        prose = "It returns the rows scoring 90 and 50."
        step(1, "forbid the wrong answer in item 1 of an answer with no list")
        result = run_assertion(_FORBIDS_IN_ITEM_1, prose)
        assert not result.passed
        assert "item 1" in result.detail, result.detail
        step(3, "ask for item 3 of a two-item answer")
        missing = run_assertion(
            _assertion("not_contains", {"value": "50", "scope": {"list_item": 3}}), _ANSWER
        )
        assert not missing.passed
        assert "item 3" in missing.detail, missing.detail

    def MQC_EVL_UNI_114658_an_indented_number_neither_ends_an_item_nor_opens_one(
        self,
    ) -> None:
        """A sub-list inside an item stays in it, and an indented 1 is not item 1.

        Design: ``tier3_evaluation.md`` section 5.4.

        Returns:
            None
        """
        nested = (
            "  1. Read naively, it returns the rows scoring 90 and 50.\n"
            "1. It returns the rows scoring 10 and 90.\n"
            "2. Why:\n"
            "   1. sorted returns a new list, which is discarded.\n"
            "   2. The slice reads the original order.\n"
            "3. Nothing else.\n"
        )
        step(1, "an indented 1 before the list does not open item 1")
        assert run_assertion(_FORBIDS_IN_ITEM_1, nested).passed
        step(2, "an indented 2 inside item 2 does not end it")
        held = run_assertion(
            _assertion("contains", {"value": "original order", "scope": {"list_item": 2}}),
            nested,
        )
        assert held.passed, held.detail
        step(3, "item 2 still ends at the margin 3")
        assert not run_assertion(
            _assertion("contains", {"value": "Nothing else", "scope": {"list_item": 2}}),
            nested,
        ).passed

    def MQC_EVL_UNI_114659_an_item_opens_inside_emphasis_or_after_heading_marks(
        self,
    ) -> None:
        """Emphasis, heading marks and a closing parenthesis all open an item.

        Design: ``tier3_evaluation.md`` section 5.4.

        Returns:
            None
        """
        spellings = (
            "**1.** It returns the rows scoring 10 and 90.\n**2.** Because sorted is discarded.",
            "**1. Return value**\nIt returns the rows scoring 10 and 90.\n**2. Why**\nDiscarded.",
            "### 1. Return value\nIt returns the rows scoring 10 and 90.\n### 2. Why\nDiscarded.",
            "1) It returns the rows scoring 10 and 90.\n2) Because sorted is discarded.",
        )
        required = {"pattern": r"\b10\b[^.]{0,10}\b90\b", "present": True}
        step(1, "find the right answer in item 1 and not in item 2, for each spelling")
        misread = [
            answer.split("\n", 1)[0]
            for answer in spellings
            if not run_assertion(
                _assertion("regex", {**required, "scope": {"list_item": 1}}), answer
            ).passed
            or run_assertion(
                _assertion("regex", {**required, "scope": {"list_item": 2}}), answer
            ).passed
        ]
        assert not misread, f"items misread for spellings opening: {misread}"
