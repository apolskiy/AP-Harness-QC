class TestMQCJudgingAFailedCase:
    """What the default decides, what the flag asks for, and what neither reaches."""

    def MQC_EVL_UNI_114531_a_violation_failure_reaches_the_judge(
        self,
        rules: GoldenRuleSet,
    ) -> None:
        """A response that screens clean is assessed whatever the assertions found.

        **The rule, as the project owner set it on 2026-11-02**: where no
        injection is detected, the response is forwarded to the judge for
        assessment, and a partial or complete violation of the system
        instruction does not change that.

        **The assessment does not excuse the case.** Section 4.1 is untouched,
        so the case still fails on its assertion and the score beside it
        separates good content with a broken form from content that was poor
        as well.

        **It replaces `114501`**, which asserted the retired default. That
        identifier stays retired, and `114503` does not: the flag is not the
        default and asserting it is a separate claim (section 4.2.0).

        Design: section 4.2.

        Args:
            rules (GoldenRuleSet): The rule set.

        Returns:
            None
        """
        judge = RecordingJudge()
        result = evaluate_observation(
            observation_context(rules, _FAILING_ANSWER), judge.binding()
        )

        assert result.assertion_results[0].passed is False
        assert len(judge.requests) == 1, (
            "an answer the screen passed was not assessed, so a failed "
            "assertion suppressed the judgement as well as the pass"
        )
        assert result.judge_skipped_reason is None
        assert result.judged is True
        assert result.passed is False

    def MQC_EVL_UNI_114503_violation_failure_judged_under_flag(
        self, rules: GoldenRuleSet, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The flag asks for a diagnostic score on a case that already failed.

        **This is what the flag is for**: somebody authoring a case wants the
        rubric's reading of a response the assertions rejected, in order to
        tell a wrong case from a wrong model, and wants it on an invocation of
        their choosing (section 4.2.0).

        **The development default is pinned off here**, so what the judgement
        is attributed to is the flag. With the default on, the two paths reach
        the same judge and nothing could tell which one asked, which would
        leave the flag's own behaviour unasserted until the phase ends and the
        default tightens. `114531` covers the default.

        Design: section 4.2.0.

        Args:
            rules (GoldenRuleSet): The rule set.
            monkeypatch (pytest.MonkeyPatch): Pins the development default off.

        Returns:
            None
        """
        monkeypatch.setattr("evaluation.pipeline._JUDGE_A_FAILED_CASE", False)

        judge = RecordingJudge()
        result = evaluate_observation(
            observation_context(rules, _FAILING_ANSWER),
            judge.binding(),
            judge_on_failure=True,
        )

        assert result.assertion_results[0].passed is False
        assert len(judge.requests) == 1, (
            "the flag asked for a judgement on a failed case and none was made"
        )
        assert result.judge_on_failure is True
        assert result.judged is True
        assert result.passed is False

        # AND THE FLAG IS WHAT CARRIED IT, which is the half the default hides:
        # the same observation with neither reaches no judge and is reported as
        # the assertion failure.
        withheld = RecordingJudge()
        unasked = evaluate_observation(
            observation_context(rules, _FAILING_ANSWER), withheld.binding()
        )

        assert not withheld.requests
        assert unasked.judge_skipped_reason == "violation_assertion_failure"

    def MQC_EVL_UNI_114507_judge_on_failure_flag_recorded_in_metadata(
        self, rules: GoldenRuleSet
    ) -> None:
        """A run's record says whether its judgement was asked for or inherited.

        **Nothing read the flag into the pipeline until 2026-11-02.** It was
        declared, documented, traced and recorded, and the one production
        caller never passed it, so this case asserted a field that no
        invocation could move. It asserts the wiring now: the same observation
        evaluated with and without the flag carries the two values.

        **A reviewer comparing two runs needs the difference**, because the
        development default judges a failed case as well, and a judgement that
        was asked for and one that was inherited are different facts about the
        run that produced it.

        Design: section 4.2.0.

        Args:
            rules (GoldenRuleSet): The rule set.

        Returns:
            None
        """
        without = evaluate_observation(
            observation_context(rules, _FAILING_ANSWER), RecordingJudge().binding()
        )
        with_flag = evaluate_observation(
            observation_context(rules, _FAILING_ANSWER), RecordingJudge().binding(),
            judge_on_failure=True,
        )

        assert without.judge_on_failure is False
        assert with_flag.judge_on_failure is True, (
            "the flag reached the pipeline and the result does not record it"
        )
        assert without.judged is True
        assert with_flag.judged is True

    def MQC_EVL_UNI_114504_fatal_failure_never_judged_even_under_flag(
        self,
        fatal_rules: GoldenRuleSet,
    ) -> None:
        """There is nothing coherent to score, so a fatal failure reaches no judge.

        **The flag does not reach it and neither does the default.** A `fatal`
        failure is the one assertion outcome that withholds the judge whatever
        the invocation asked for, because the request would spend quota to
        produce noise rather than a diagnosis, and a screen abort withholds it
        for a reason that is not about cost at all.

        Design: section 4.2 and section 4.2.0.

        Args:
            fatal_rules (GoldenRuleSet): A rule set with a fatal assertion.

        Returns:
            None
        """
        judge = RecordingJudge()
        result = evaluate_observation(
            observation_context(fatal_rules, "not json at all"), judge.binding(),
            judge_on_failure=True,
        )

        assert not judge.requests
        assert result.judge_skipped_reason == "fatal_assertion_failure"
