"""Unit cases for whether a case whose assertions failed is judged, and who asked.

Created: 2026-11-02
Last updated: 2026-11-02

Its cases check the two things that decide it. The **default**, which judges a
``violation`` failure on a response the screen passed while these cases are in
development, and the **flag**, ``--judge-on-failure``, which is what authoring
a case passes to ask for the same judgement on an invocation of its own. A
``fatal`` failure is judged by neither.

They call :func:`evaluation.pipeline.evaluate_observation` directly, after the
screen has passed the response and the assertions have run, so what they
measure is the decision rather than the steps around it. A judgement that
happens here reaches the replay store, so a defect in this decision shows up
later as a case that cannot be measured without a live run.

**Split from ``mqc_uni_pipeline.py`` on 2026-11-02**, which reached the nine
hundred line runway with these four cases in it. The subject is its own:
that module is about which step runs and what a decision forecloses, and this
one about whether the judge is asked at all (``code-style.md`` section 5.1).

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.

Specified by ``docs/design/tier3_evaluation.md`` sections 4.2 and 4.2.0.
"""

