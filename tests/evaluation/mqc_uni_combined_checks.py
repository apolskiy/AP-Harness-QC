from typing import Any

import pytest

from execution.normalize import ToolCall
from evaluation.isolation import UnauthoredMaterial
from evaluation.pipeline import ObservationContext, evaluate_observation
from ingestion.schemas import ProgrammaticAssertion, ToolDefinition, ToolExpectation

pytestmark = pytest.mark.unit

_OFFERED = tuple(
    ToolDefinition(tool_name=name, description="d", parameters_schema={})
    for name in ("list_directory", "ping_host")
)

_SUMMARISED = ProgrammaticAssertion.from_dict(
    {
        "assertion_id": "A_SUMMARISED",
        "kind": "regex",
        "parameters": {"pattern": "(?i)billing", "present": True},
        "taxonomy_code": "QC_LLM_INSTRUCTION_DRIFT",
        "severity": "violation",
    }
)

_RULES = type(
    "Rules",
    (),
    {
        "assertions": [_SUMMARISED],
        "rubric": None,
        "tool_expectation": ToolExpectation(
            forbidden_tools=frozenset({"list_directory", "ping_host"})
        ),
    },
)()


class TestMQCCombinedChecks:
    """Tool checks join the assertions as conjunctive gates."""

    def MQC_EVL_UNI_114521_a_rule_with_tool_and_text_checks_fails_when_either_fails(
        self,
    ) -> None:
        """Both pass and the case passes; either fails and the case fails.

        Design: ``tier3_evaluation.md`` section 5B.6.

        Returns:
            None
        """

        def _observe(text: str, called: tuple[str, ...]) -> Any:
            """Evaluate one declared adversarial response against the rule.

            Args:
                text (str): What the model wrote.
                called (tuple): The tools it called, in order.

            Returns:
                Any: The evaluation result.
            """
            return evaluate_observation(
                ObservationContext(
                    case_id="MQC_TASK_t::MQC_RULE_t",
                    rules=_RULES,
                    material=UnauthoredMaterial(candidate_output=text),
                    declared_adversarial=True,
                    tool_calls=tuple(
                        ToolCall(tool_name=name, arguments={}, sequence=index)
                        for index, name in enumerate(called)
                    ),
                    offered_tools=_OFFERED,
                )
            )

        both = _observe("Billing is down on Sunday.", ())
        assert both.passed is True, "a response passing both checks was failed"

        called = _observe("Billing is down on Sunday.", ("ping_host",))
        assert called.passed is False, (
            "a forbidden call passed because the text assertion held"
        )
        assert "QC_LLM_TOOL_VIOLATION" in called.taxonomy_codes

        drifted = _observe("Nothing to report.", ())
        assert drifted.passed is False, (
            "a response that did not do the task passed because no tool was called"
        )
        assert "QC_LLM_INSTRUCTION_DRIFT" in drifted.taxonomy_codes
