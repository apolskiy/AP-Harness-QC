"""Unit cases for the check that an answer holds the list its rule declares.

Created: 2026-11-04
Last updated: 2026-11-05

Its cases check :func:`evaluation.answer_list.check_answer_list`. A numbered
list holds where its top-level numbers run 1 to N once each in ascending
order; a missing, repeated or extra item fails as a length violation and every
number present out of order as a format violation, each naming what it found.
Sub-lists and text around the list are not items, and a bulleted list holds at
its declared count or within its ceiling.

Specified by ``docs/design/tier3_evaluation.md`` section 5.5.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.
"""

