from typing import Any, Final, Optional

import pytest

from cmn.case_steps import step
from evaluation.answer_list import check_answer_list

from tests.evaluation.answer_list_support import (
    list_declaration as _declared,
    numbered_answer as _numbered,
)

pytestmark = pytest.mark.unit

_LENGTH: Final[str] = "QC_LLM_LENGTH_VIOLATION"
_FORMAT: Final[str] = "QC_LLM_FORMAT_VIOLATION"

# THE gemini ANSWER TO `134203` RECORDED IN THE SWEEP OF 2026-11-04, four items
# in order with a bulleted sub-list inside item 1.
_FOUR_ITEMS: Final[str] = (
    "1. Revenue by region:\n"
    "   - North America: 41.2 million\n"
    "   - EMEA: 28.7 million\n"
    "   - Japan: 11.4 million\n"
    "   - Australia: 6.1 million\n"
    "2. North America\n"
    "3. 47.14% (or approximately 47.1%)\n"
    "4. Divide North America's revenue by the total revenue and multiply by 100.\n"
)


class TestMQCAnswerListShape:
    """Whether the answer holds the list the prompt asked for, and what it lacks."""

    def MQC_EVL_UNI_114660_a_numbered_list_of_its_size_in_order_takes_the_list_route(
        self,
    ) -> None:
        """Items 1 to 4, once each and in order, hold a four-item declaration.

        Design: ``tier3_evaluation.md`` section 5.5.

        Returns:
            None
        """
        step(1, "check the recorded four-item answer against a four-item declaration")
        result = check_answer_list(_FOUR_ITEMS, _declared("numbered", count=4))
        assert result.passed, result.detail
        assert result.assertion_id == "ANSWER_LIST" and result.kind == "answer_list"
        assert result.taxonomy_code is None

    def MQC_EVL_UNI_114661_a_numbered_list_missing_an_item_fails_naming_it(
        self,
    ) -> None:
        """Items 1, 2 and 4 of four fail as a length violation naming item 3.

        Design: ``tier3_evaluation.md`` section 5.5.

        Returns:
            None
        """
        step(1, "check an answer that drops item 3")
        result = check_answer_list(_numbered(1, 2, 4), _declared("numbered", count=4))
        assert (result.passed, result.taxonomy_code, "missing [3]" in result.detail) == (
            False, _LENGTH, True
        ), result.detail

        step(2, "check an answer with no numbered list at all")
        prose = check_answer_list("North America, at 47.1 percent.", _declared("numbered", count=4))
        assert not prose.passed and prose.taxonomy_code == _LENGTH, prose.detail

    def MQC_EVL_UNI_114662_a_numbered_list_with_an_extra_item_fails_naming_it(
        self,
    ) -> None:
        """A fifth item on a four-item declaration fails, naming item 5.

        Design: ``tier3_evaluation.md`` section 5.5.

        Returns:
            None
        """
        step(1, "check an answer adding a fifth item")
        result = check_answer_list(
            _FOUR_ITEMS + "5. Note: figures are as reported.\n", _declared("numbered", count=4)
        )
        assert not result.passed
        assert result.taxonomy_code == _LENGTH, result.taxonomy_code
        assert "extra [5]" in result.detail, result.detail

    def MQC_EVL_UNI_114663_a_numbered_list_out_of_order_fails_as_a_format_violation(
        self,
    ) -> None:
        """Every number once, in the order 2, 1, 3, is the wrong form, not the wrong size.

        Design: ``tier3_evaluation.md`` section 5.5.

        Returns:
            None
        """
        step(1, "check an answer writing items 2, 1, 3")
        result = check_answer_list(_numbered(2, 1, 3), _declared("numbered", count=3))
        assert not result.passed
        assert result.taxonomy_code == _FORMAT, result.taxonomy_code
        assert "[2, 1, 3]" in result.detail, result.detail

    def MQC_EVL_UNI_114664_a_numbered_list_repeating_an_item_fails_naming_it(
        self,
    ) -> None:
        """A list restarting at 1 repeats items, which is a length violation.

        Design: ``tier3_evaluation.md`` section 5.5.

        Returns:
            None
        """
        step(1, "check an answer whose two items are followed by a second list from 1")
        result = check_answer_list(_numbered(1, 2, 1, 2), _declared("numbered", count=2))
        assert not result.passed
        assert result.taxonomy_code == _LENGTH, result.taxonomy_code
        assert "repeated [1, 2]" in result.detail, result.detail

    def MQC_EVL_UNI_114665_sub_lists_and_text_around_the_list_are_not_items(
        self,
    ) -> None:
        """An introduction, a closing note and indented sub-lists leave the list held.

        Design: ``tier3_evaluation.md`` section 5.5.

        Returns:
            None
        """
        answer = (
            "Here is the answer, from the report above.\n\n"
            "1. It returns the rows scoring 10 and 90.\n"
            "2. Why:\n"
            "   1. sorted builds a new list, which is discarded.\n"
            "   2. The slice reads the original order.\n"
            "   3. So the scores are never compared.\n\n"
            "All figures are as the excerpt gives them.\n"
        )
        step(1, "check a two-item answer whose item 2 holds a numbered sub-list")
        result = check_answer_list(answer, _declared("numbered", count=2))
        assert result.passed, result.detail

    def MQC_EVL_UNI_114666_a_bulleted_list_is_held_at_its_count_and_within_its_ceiling(
        self,
    ) -> None:
        """Three bullets hold at most three and exactly three; four and none do not.

        Design: ``tier3_evaluation.md`` section 5.5.

        Returns:
            None
        """
        def bullets(total: int) -> str:
            return "Summary:\n" + "".join(
                f"- Point {index} of the release.\n  - a detail\n" for index in range(total)
            )

        ceiling = _declared("bulleted", max_count=3)
        exact = _declared("bulleted", count=3)
        def outcome(answer: str, declaration: Any) -> tuple[bool, Optional[str]]:
            result = check_answer_list(answer, declaration)
            return result.passed, result.taxonomy_code

        step(1, "three bullets, each with an indented sub-bullet, against both bounds")
        assert [outcome(bullets(3), ceiling), outcome(bullets(3), exact)] == [
            (True, None), (True, None)
        ]
        step(2, "two bullets hold the ceiling and fail the count")
        assert [outcome(bullets(2), ceiling), outcome(bullets(2), exact)] == [
            (True, None), (False, _LENGTH)
        ]
        step(3, "four bullets fail both, and an answer with none fails the ceiling")
        assert [
            outcome(bullets(4), ceiling), outcome(bullets(4), exact),
            outcome("A paragraph and no list.", ceiling),
        ] == [(False, _LENGTH)] * 3
        step(4, "an asterisk and a bullet character open bullets, bold text does not")
        mixed = "* First.\n• Second.\n**Third** is bold prose.\n"
        assert outcome(mixed, _declared("bulleted", count=2)) == (True, None)
