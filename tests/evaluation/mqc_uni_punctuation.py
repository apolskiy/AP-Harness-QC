from typing import Final

import pytest

from cmn.case_steps import step
from cmn.markup import blank_punctuation
from evaluation.assertions import run_assertion

from tests.evaluation.assertion_support import (
    programmatic_assertion as _assertion,
)

pytestmark = pytest.mark.unit


# THE PAIRS THE RULING IS ABOUT: one answer written with punctuation between two
# words of a phrase and one without, which must decide the same way.
_PAIRS: Final[tuple[tuple[str, str], ...]] = (
    ("It is a full match.", 'It is a "full match".'),
    ("The candidate meets two of five.", "The candidate meets two, of five."),
    ("I report a full match.", "I report a full-match."),
    ("the second returns 0 here", "the second returns `0` here"),
)


class TestMQCPunctuationBlanking:
    """Two answers differing only in punctuation reach the same outcome."""

    def MQC_EVL_UNI_114649_punctuation_between_words_does_not_decide_a_pattern(
        self,
    ) -> None:
        """A pattern and a substring decide a punctuated answer as they decide a plain one.

        Design: ``tier3_evaluation.md`` section 5.1.1.

        Returns:
            None
        """
        checks = (
            _assertion("regex", {"pattern": r"full\s+match"}),
            _assertion("contains", {"value": "full match"}),
            _assertion("not_contains", {"value": "full match"}),
        )
        step(1, "read a quoted phrase and a bare one through a pattern and a substring")
        disagreed = [
            (check.kind, plain, punctuated)
            for check in checks
            for plain, punctuated in _PAIRS[:1]
            if run_assertion(check, plain).passed
            is not run_assertion(check, punctuated).passed
        ]
        assert not disagreed, f"punctuation decided a check: {disagreed}"

        step(2, "read every recorded pairing through a word-sequence pattern")
        pattern = _assertion("regex", {"pattern": r"(full\s+match|two\s+of\s+five|returns\s+0)"})
        disagreed = [
            (plain, punctuated) for plain, punctuated in _PAIRS
            if run_assertion(pattern, plain).passed
            is not run_assertion(pattern, punctuated).passed
        ]
        assert not disagreed, f"punctuation decided a pattern: {disagreed}"

        step(3, "read a substring declared with punctuation against text without it")
        held = run_assertion(_assertion("contains", {"value": '"full match"'}), "a full match")
        assert held.passed, (
            f"a needle written with quotation marks failed on text without them, so "
            f"blanking one side only inverted the check: {held.detail}"
        )

    def MQC_EVL_UNI_114650_a_mark_on_a_digit_or_inside_a_word_survives_blanking(
        self,
    ) -> None:
        """A figure, a code identifier and a contraction each keep the mark they need.

        Design: ``tier3_evaluation.md`` section 5.1.1.

        Returns:
            None
        """
        step(1, "blank a figure, a ratio, a currency amount and a spaced ratio")
        for figure in ("40%", "33.3", "$1,000", "2/5", "2 / 10", "100 × 90%"):
            assert blank_punctuation(f"it is {figure} here") == f"it is {figure} here", (
                f"a mark in {figure!r} was blanked, which would make every figure "
                f"gate unmatchable: {blank_punctuation(f'it is {figure} here')!r}"
            )

        step(7, "read the ninety-to-one-hundred percent gate through a blanked reading")
        gate = _assertion(
            "regex",
            {"pattern": r"(?i)(?<![×x*]\s)(?<![×x*])\b(9\d|100)(\.\d+)?\s*(%|per\s?cent)"},
        )
        assert run_assertion(gate, 'It is a "full match", at 95% of the posting.').passed, (
            "the figure gate stopped matching once punctuation was blanked"
        )

        step(8, "verify a scale is still not read as the figure it is out of")
        assert not run_assertion(gate, "Score it 2 / 10 on depth.").passed, (
            "a ratio's scale was read as a mark, so the separator was blanked"
        )

        step(9, "blank an identifier a code pattern would match")
        assert blank_punctuation("amount_owed is wrong") == "amount_owed is wrong", (
            "an underscore was blanked, which splits every identifier a code "
            "excerpt names"
        )

        step(10, "blank a contraction the rejection vocabulary reads")
        assert blank_punctuation("I didn't follow it.") == "I didn't follow it.", (
            "an apostrophe inside a contraction was blanked, which leaves no word "
            "for the rejection vocabulary to read"
        )

        step(11, "blank a terminator that ends a sentence")
        assert blank_punctuation("Done. Next") == "Done. Next", (
            "a sentence terminator was blanked, so a pattern anchored at a "
            "sentence end no longer matches and the reading loses its boundaries"
        )

        step(12, "blank a terminator inside a quotation, where no sentence ends")
        assert blank_punctuation('reads "go." Next') == "reads  go   Next", (
            "a terminator inside a quotation was kept, although no sentence ends "
            "there and the raw text does not break there either"
        )

    def MQC_EVL_UNI_114676_a_mark_beside_a_bracketed_figure_survives_blanking(
        self,
    ) -> None:
        """A multiplier beside a bracketed fraction is kept, and a bracketed word keeps nothing.

        Design: ``tier3_evaluation.md`` section 5.1.1.

        Returns:
            None
        """
        bracketed = ("(2/5) * 100%", "100 * (2/5)", "(1 / 2) * (100)")
        for number, figure in enumerate(bracketed, start=1):
            step(number, f"blank the multiplier in {figure!r}")
            assert blank_punctuation(f"so {figure} here") == f"so {figure} here", (
                f"the mark beside a bracketed figure in {figure!r} was blanked: "
                f"{blank_punctuation(f'so {figure} here')!r}"
            )

        step(len(bracketed) + 1, "read openai's working through the ninety percent gate")
        gate = _assertion(
            "regex",
            {"pattern": r"(?i)(?<![×x*]\s)(?<![×x*])\b(9\d|100)(\.\d+)?\s*(%|per\s?cent)"},
        )
        assert not run_assertion(gate, "(2/5) * 100% = **40%**").passed, (
            "a 100 percent multiplier after a bracketed fraction was read as a figure"
        )

        step(len(bracketed) + 2, "blank a mark beside a bracket holding a word")
        assert (
            blank_punctuation("(see note) * 40"), blank_punctuation("40 * (note 2)")
        ) == (" see note    40", "40    note 2)"), (
            "a mark between a figure and a bracketed word was kept, which no "
            "figure needs"
        )

    def MQC_EVL_UNI_114651_a_claim_splits_raw_sentences_before_blanking_each(
        self,
    ) -> None:
        """A hedge in one sentence does not suppress a claim in another.

        Design: ``tier3_evaluation.md`` section 5.1.1.

        Returns:
            None
        """
        claim = _assertion("claim", {
            "pattern": r"full\s+match", "present": False, "unless": ["not a"],
        })
        step(1, "read a hedged claim and an unhedged one in separate sentences")
        result = run_assertion(
            claim, "This is not a full match. The resume reads \"full match\" plainly."
        )
        assert not result.passed, (
            "a hedge in the first sentence suppressed the claim in the second, so "
            "the sentences were not split from the raw text"
        )

        step(2, "verify the detail quotes the raw sentence rather than a blanked one")
        assert '"full match"' in result.detail, (
            f"the failure detail quotes a blanked sentence, which misquotes the "
            f"model on a ticket page: {result.detail}"
        )

        step(3, "read a hedge whose own punctuation differs from the declared one")
        held = run_assertion(claim, 'This is "not a" full match.')
        assert held.passed, (
            f"a hedge written with quotation marks stopped matching the declared "
            f"one, so the markers were not blanked with the text: {held.detail}"
        )

    def MQC_EVL_UNI_114652_length_json_schema_and_source_phrase_absent_read_raw_text(
        self,
    ) -> None:
        """The three kinds whose subject is the text as written still read it.

        Design: ``tier3_evaluation.md`` section 5.1.1.

        Returns:
            None
        """
        punctuated = 'It is a "full match", truly.'
        step(1, "count a bound against the text as written")
        assert run_assertion(
            _assertion("length", {"unit": "characters", "maximum": len(punctuated)}),
            punctuated,
        ).passed, "a bound was measured against something other than the text"

        step(2, "count a bound one character under the text")
        assert not run_assertion(
            _assertion("length", {"unit": "characters", "maximum": len(punctuated) - 1}),
            punctuated,
        ).passed, (
            "a bound one character under the text held, so the count was taken "
            "from a reading rather than from the response"
        )

        step(3, "parse a body whose punctuation is its syntax")
        assert run_assertion(
            _assertion("json_schema", {"schema": {"type": "object"}}), '{"verdict": 2}'
        ).passed, "a JSON body stopped parsing, so the text was altered before the parse"

        step(4, "compare words against a declared source, which needs no blanking")
        reuse = _assertion(
            "source_phrase_absent",
            {"source": 'Return "full match" now.', "min_words": 2},
        )
        assert not run_assertion(reuse, "It is a full match.").passed, (
            "a two-word run of the declared source passed"
        )

        step(5, "read a paraphrase of the same declared source")
        assert run_assertion(reuse, "It matches fully.").passed, (
            "a paraphrase of the declared source failed"
        )

        step(6, "verify an assertion declaring literal punctuation reads the raw text")
        bullet = _assertion(
            "regex",
            {
                "pattern": r"^[ \t]*[-*][ \t]+.*[^.!?\s][ \t]*$",
                "present": False,
                "literal_punctuation": True,
            },
            assertion_id="A_PUNCTUATION_LITERAL",
            taxonomy_code="QC_LLM_INSTRUCTION_DRIFT",
        )
        assert not run_assertion(bullet, "- a bullet with no terminator").passed, (
            "a bullet check reading literal punctuation passed vacuously, so the "
            "opt-out did not reach it"
        )
