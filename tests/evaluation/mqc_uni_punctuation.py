"""Unit cases for punctuation never deciding a deterministic check.

Created: 2026-10-30
Last updated: 2026-11-05

Its cases check :func:`cmn.markup.blank_punctuation` through
:func:`evaluation.assertions.run_assertion`. Two answers differing only in
punctuation reach the same outcome; the marks that are part of a word or of a
figure survive, so a figure gate, a code pattern and a rejection still match; a
``claim`` splits the raw text into sentences before blanking each, so a hedge in
one sentence does not suppress a claim in another; and the three kinds that read
the text as written are checked to still do so.

Specified by ``docs/design/tier3_evaluation.md`` section 5.1.1.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.
"""

