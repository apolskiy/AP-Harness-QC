"""Unit case for evaluating a response with the judge withheld, ``--judge-mode off``.

Created: 2026-10-21
Last updated: 2026-10-21

Its case checks :func:`evaluation.pipeline.evaluate_observation` with a
:class:`evaluation.judge.JudgeBinding` marked ``withheld``: a rubric-bearing
observation whose screen and assertions hold is skipped ``unjudged`` and never
passes, a failing assertion and a screen abort fail as always, a rule with no
rubric passes on its assertions, and the judge is never called.

A debug run uses this to check the deterministic checks alone before the judge
is involved, so a failure here would let an unjudged case read as a pass or
spend a judge request the requester declined.

Specified by ``docs/design/tier3_evaluation.md`` section 5A.5.3.
"""

