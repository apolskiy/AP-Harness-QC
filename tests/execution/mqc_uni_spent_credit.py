"""Unit cases for how an adapter codes a 429 that says the account's money is spent.

Created: 2026-11-26
Last updated: 2026-11-26

This file contains ``TestMQCSpentCredit``, cases on each adapter's
``map_error``. They check that gemini's spending-cap 429 and openai's
``insufficient_quota`` 429 are coded ``QC_HARNESS_CREDIT_EXHAUSTED``, and that a
429 naming no spent credit stays ``QC_HARNESS_RATE_LIMIT``. The candidate ending
its job on spent credit is ``113228`` in ``mqc_uni_circuit_breaker.py``.

**The status decides the kind of failure, and the provider's words only narrow
a rate limit to spent credit**, so a reworded message falls back to the rate
limit and never to a wrong code.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.

Specified by ``docs/design/tier2_execution.md`` section 8.6.5.
"""

