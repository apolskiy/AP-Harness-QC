import pytest

from execution.adapters.gemini import GeminiAdapter
from execution.adapters.openai import OpenAIAdapter
from tests.execution.provider_doubles import (
    SPENDING_CAP_MESSAGE,
    gemini_exhausted,
    openai_quota_error,
)

pytestmark = pytest.mark.unit


class TestMQCSpentCredit:
    """A 429 is spent credit only where the provider says so."""

    def MQC_EXE_UNI_113038_gemini_codes_a_spending_cap_as_spent_credit(self) -> None:
        """Gemini's spending-cap 429 is coded ``QC_HARNESS_CREDIT_EXHAUSTED``.

        Returns:
            None
        """
        code = GeminiAdapter().map_error(gemini_exhausted(SPENDING_CAP_MESSAGE))
        assert code == "QC_HARNESS_CREDIT_EXHAUSTED", code

    def MQC_EXE_UNI_113039_a_429_naming_no_spent_credit_stays_a_rate_limit(self) -> None:
        """A 429 whose words name no spent credit is a rate limit on both protocols.

        Returns:
            None
        """
        reworded = SPENDING_CAP_MESSAGE.replace("spending cap", "budget").replace(
            "spend cap", "budget"
        )
        for error in (
            gemini_exhausted("Resource has been exhausted (e.g. check quota)."),
            gemini_exhausted(reworded),
        ):
            code = GeminiAdapter().map_error(error)
            assert code == "QC_HARNESS_RATE_LIMIT", (code, str(error))
        code = OpenAIAdapter().map_error(openai_quota_error("rate_limit_exceeded"))
        assert code == "QC_HARNESS_RATE_LIMIT", code

    def MQC_EXE_UNI_113040_openai_codes_insufficient_quota_as_spent_credit(self) -> None:
        """Openai's ``insufficient_quota`` 429 is coded ``QC_HARNESS_CREDIT_EXHAUSTED``.

        Returns:
            None
        """
        code = OpenAIAdapter().map_error(openai_quota_error("insufficient_quota"))
        assert code == "QC_HARNESS_CREDIT_EXHAUSTED", code
