"""The adapter registry, and the conformance cases every engine must carry.

Inventoried in ``docs/design/tier2_execution.md`` sections 10.1 and 9.1.

**One case per engine and check**, since 2026-10-16: the battery was
parametrised over the registry, which ran one identifier once per engine
(``harness_test_taxonomy.md`` section 1.1). The checks live in
``conformance_checks.py`` and each engine's cases in
``mqc_uni_conformance_<engine>.py``. **`113114` keeps the registry honest**:
registering an adapter without its cases fails it, so there is still nothing
to remember.

A failure here is **not a model finding**, so the module carries no priority marker, per
``framework-rules.md`` section 3.3.
"""

