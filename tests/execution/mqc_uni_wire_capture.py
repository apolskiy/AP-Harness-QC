@pytest.fixture(name="offline", autouse=True)
def fixture_offline(monkeypatch: pytest.MonkeyPatch) -> None:
    """Refuse every real HTTP send, so a case whose wiring is broken fails offline.

    **Found by the first run of these cases**, before the transport was wired:
    the SDKs fell back to their own transports and sent the planted credential
    to two providers, which rejected it. A unit case reaching the network is a
    defect whatever it sends.

    Args:
        monkeypatch (pytest.MonkeyPatch): pytest's patcher.

    Returns:
        None
    """

    def refuse(_transport: Any, request: httpx.Request) -> httpx.Response:
        """Fail the send instead of making it.

        Args:
            _transport (Any): The transport asked to send.
            request (httpx.Request): What it was asked to send.

        Returns:
            httpx.Response: Never.

        Raises:
            AssertionError: Always.
        """
        raise AssertionError(f"a unit case reached the network: {request.url.host}")

    monkeypatch.setattr(httpx.HTTPTransport, "handle_request", refuse)


@pytest.fixture(name="planted")
def fixture_planted(monkeypatch: pytest.MonkeyPatch) -> str:
    """Plant the credential under every engine's variable, and clear what would override it.

    Args:
        monkeypatch (pytest.MonkeyPatch): pytest's patcher.

    Returns:
        str: The planted credential.
    """
    for name in ("GOOGLE_API_KEY", "OPENAI_BASE_URL", "ANTHROPIC_BASE_URL", "OPENAI_LOG"):
        monkeypatch.delenv(name, raising=False)
    for engine in WIRE_ENGINES.values():
        monkeypatch.setenv(engine.key_variable, PLANTED_KEY)
    return PLANTED_KEY


class TestMQCWireCapture:
    """Every HTTP attempt is recorded, and travels with the observation that made it."""

    def MQC_EXE_UNI_460000_every_attempt_records_its_headers_status_and_body_hash(
        self, planted: str, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """One dispatch, one attempt, carrying what went out and what came back.

        Args:
            planted (str): The planted credential.
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.

        Returns:
            None
        """
        assert planted
        sent: list[httpx.Request] = []
        serve_mock(monkeypatch, reply_handler(
            WIRE_ENGINES["grok"].reply, headers=(("x-request-id", "req-1"),), sent=sent,
        ))
        attempts = dispatch_minimal("grok").take_wire_attempts()

        step(2, "read the one attempt the dispatch made")
        assert len(attempts) == 1 and len(sent) == 1, attempts
        record = attempts[0].as_mapping()
        assert record["attempt_index"] == 0 and record["method"] == "POST", record
        assert record["url"] == str(sent[0].url), record
        assert record["url"].endswith("/chat/completions"), record
        assert "x-stainless-os" in record["request_headers"], record["request_headers"]
        assert record["status"] == 200 and record["error"] == "", record
        assert record["response_headers"]["x-request-id"] == "req-1", record
        assert record["body_sha256"] == hashlib.sha256(sent[0].content).hexdigest(), record
        assert record["elapsed_ms"] >= 0, record

    def MQC_EXE_UNI_460001_a_url_query_string_never_reaches_the_record(self) -> None:
        """A credential carried in a query string is not recorded with the URL.

        Returns:
            None
        """
        recorder = mock_recorder(reply_handler({}))
        send_through(recorder, method="GET", url=f"{ECHO_URL}?key={PLANTED_KEY}&alt=json")
        record = recorder.take()[0].as_mapping()
        assert record["url"] == ECHO_URL, record
        assert PLANTED_KEY not in json.dumps(record), record

    def MQC_EXE_UNI_460002_an_sdk_retry_is_a_second_attempt_of_one_dispatch(
        self, planted: str, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A retry inside the SDK is visible, which no record showed before.

        Args:
            planted (str): The planted credential.
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.

        Returns:
            None
        """
        assert planted
        serve_mock(monkeypatch, reply_handler(WIRE_ENGINES["grok"].reply, failures=(500,)))
        attempts = [item.as_mapping() for item in dispatch_minimal("grok").take_wire_attempts()]
        assert [item["attempt_index"] for item in attempts] == [0, 1], attempts
        assert [item["status"] for item in attempts] == [500, 200], attempts

    def MQC_EXE_UNI_460003_an_attempt_raising_before_a_response_records_its_error_class(
        self,
    ) -> None:
        """The attempt an event hook could not see is recorded, with no status.

        Returns:
            None
        """
        recorder = mock_recorder(reply_handler({}, failures=(httpx.ConnectError("refused"),)))
        with pytest.raises(httpx.ConnectError):
            send_through(recorder)
        record = recorder.take()[0].as_mapping()
        assert record["error"] == "ConnectError", record
        assert record["status"] is None and record["response_headers"] == {}, record

    def MQC_EXE_UNI_460009_the_body_is_stored_in_a_debug_run_and_only_hashed_otherwise(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The hash on every attempt, the body only where the run is a debug run.

        Args:
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.

        Returns:
            None
        """
        body = b'{"probe": 1}'
        step(1, "a recorder keeping bodies stores the bytes sent")
        kept = mock_recorder(reply_handler({}), keep_body=True)
        send_through(kept, content=body)
        stored = kept.take()[0].as_mapping()
        assert stored["body"] == body.decode("utf-8"), stored
        assert stored["body_sha256"] == hashlib.sha256(body).hexdigest(), stored

        step(3, "a recorder not keeping them stores the hash alone")
        hashed = mock_recorder(reply_handler({}))
        send_through(hashed, content=body)
        bare = hashed.take()[0].as_mapping()
        assert bare["body"] is None and bare["body_sha256"] == stored["body_sha256"], bare

        step(4, "an adapter keeps bodies in a debug run and in no other")
        monkeypatch.setenv("GITHUB_ACTIONS", "true")
        for workflow, keeps in (("debug-cases-on-demand.yml", True),
                                ("evaluate-engine.yml", False)):
            monkeypatch.setenv("GITHUB_WORKFLOW_REF", f"o/r/.github/workflows/{workflow}@x")
            assert adapter_for("grok")().wire.keep_body is keeps, workflow

    def MQC_EXE_UNI_460010_each_adapter_hands_its_sdk_the_recording_transport(
        self, planted: str, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """All four engines send through the recording transport, credential redacted.

        Args:
            planted (str): The planted credential.
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.

        Returns:
            None
        """
        for engine in _ENGINES:
            serve_mock(monkeypatch, reply_handler(WIRE_ENGINES[engine].reply))
            attempts = dispatch_minimal(engine).take_wire_attempts()
            assert len(attempts) == 1, (engine, attempts)
            headers = attempts[0].as_mapping()["request_headers"]
            assert headers.get(WIRE_ENGINES[engine].credential_header) is not None, (
                engine, sorted(headers),
            )
            assert planted not in json.dumps(attempts[0].as_mapping()), engine

    def MQC_EXE_UNI_460011_the_outcome_carries_the_attempts_and_clears_the_recorder(
        self, planted: str, monkeypatch: pytest.MonkeyPatch, minimal_case: EvaluationCase,
        tmp_path: Path,
    ) -> None:
        """A live dispatch outcome holds its attempts, and the next one starts empty.

        Args:
            planted (str): The planted credential.
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.
            minimal_case (EvaluationCase): The case to dispatch.
            tmp_path (Path): The fixture root.

        Returns:
            None
        """
        assert planted
        serve_mock(monkeypatch, reply_handler(WIRE_ENGINES["claude"].reply))
        clock = FakeClock()
        session = DispatchSession(monotonic=clock.monotonic, delay=clock.sleep)
        plan = DispatchPlan(mode="live", fixture_root=tmp_path)
        first = dispatch_case(minimal_case, "claude", plan, session, 0)
        second = dispatch_case(minimal_case, "claude", plan, session, 1)
        assert first.measured and len(first.wire_attempts) == 1, first
        assert len(second.wire_attempts) == 1, (
            "the second outcome carried the first one's attempts as well"
        )
        assert first.attempts == 1, "the harness attempt count changed meaning"

    def MQC_EXE_UNI_460012_a_judgement_carries_the_attempts_its_judge_made(
        self, planted: str, monkeypatch: pytest.MonkeyPatch,
        sample_rule_payload: dict[str, Any],
    ) -> None:
        """The judge's attempts reach the channel's caller and the evaluation result.

        Args:
            planted (str): The planted credential.
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.
            sample_rule_payload (dict): Minimal rule payload.

        Returns:
            None
        """
        assert planted
        reply = json.loads(json.dumps(WIRE_ENGINES["grok"].reply))
        reply["choices"][0]["message"]["content"] = json.dumps(AWARDED)
        serve_mock(monkeypatch, reply_handler(reply))

        step(2, "a live judgement leaves its attempts on the channel, taken once")
        channel = JudgeChannel("grok", model="grok-wire", plan=JudgementPlan())
        assert channel.invoke(JudgeRequestDouble()) == AWARDED
        taken = channel.take_wire_attempts()
        assert len(taken) == 1 and taken[0].as_mapping()["status"] == 200, taken
        assert channel.take_wire_attempts() == (), "the channel kept attempts it handed over"

        step(5, "the pipeline stores what the binding's callable returns")
        binding = dataclasses.replace(RecordingJudge().binding(), wire_attempts=lambda: taken)
        result = evaluate_observation(
            observation_context(violation_rule_set(sample_rule_payload),
                                "It requires five years of Python."),
            binding,
        )
        assert result.judged and result.judge_wire_attempts == taken, result

    def MQC_EXE_UNI_460013_a_replayed_exchange_carries_no_attempts(
        self, planted: str, monkeypatch: pytest.MonkeyPatch, minimal_case: EvaluationCase,
        tmp_path: Path,
    ) -> None:
        """A replay sends nothing, and the recorded request hash ignores the capture.

        Args:
            planted (str): The planted credential.
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.
            minimal_case (EvaluationCase): The case to dispatch.
            tmp_path (Path): The fixture root.

        Returns:
            None
        """
        assert planted
        serve_mock(monkeypatch, reply_handler(WIRE_ENGINES["claude"].reply))
        clock = FakeClock()
        session = DispatchSession(monotonic=clock.monotonic, delay=clock.sleep)
        live = dispatch_case(minimal_case, "claude",
                             DispatchPlan(mode="live", fixture_root=tmp_path, record=True),
                             session, 0)
        replayed = dispatch_case(minimal_case, "claude",
                                 DispatchPlan(mode="replay", fixture_root=tmp_path), session, 0)
        assert live.wire_attempts and replayed.measured, (live, replayed)
        assert not replayed.wire_attempts, replayed.wire_attempts
        stored = load_fixture(tmp_path, FixtureKey(minimal_case.case_id, "claude", 0),
                              hash_request(live.request))
        assert stored.request == live.request, "the recording carries something the capture added"


class TestMQCWireRedaction:
    """No credential reaches a recorded header, by name or by value."""

    @staticmethod
    def _recorded(
        header: str, value: str, environ: Optional[dict[str, str]] = None
    ) -> dict[str, Any]:
        """Send one request carrying a header, and return the attempt recorded.

        Args:
            header (str): The header name.
            value (str): Its value.
            environ (dict): The environment the by-value mechanism reads.

        Returns:
            dict: The attempt as a mapping.
        """
        recorder = mock_recorder(reply_handler({}), environ=environ)
        send_through(recorder, headers={header: value})
        return recorder.take()[0].as_mapping()

    def MQC_EXE_UNI_460004_the_authorization_header_value_never_reaches_the_record(
        self,
    ) -> None:
        """grok's and openai's header, caught by its name with no credential in the environment.

        Returns:
            None
        """
        record = self._recorded("Authorization", f"Bearer {PLANTED_KEY}")
        assert record["request_headers"]["authorization"] == wire.REDACTED, record
        assert PLANTED_KEY not in json.dumps(record), record

    def MQC_EXE_UNI_460005_the_x_api_key_header_value_never_reaches_the_record(
        self,
    ) -> None:
        """claude's header, caught by its name with no credential in the environment.

        Returns:
            None
        """
        record = self._recorded("x-api-key", PLANTED_KEY)
        assert record["request_headers"]["x-api-key"] == wire.REDACTED, record
        assert PLANTED_KEY not in json.dumps(record), record

    def MQC_EXE_UNI_460006_the_x_goog_api_key_header_value_never_reaches_the_record(
        self,
    ) -> None:
        """gemini's header, caught by its name with no credential in the environment.

        Returns:
            None
        """
        record = self._recorded("x-goog-api-key", PLANTED_KEY)
        assert record["request_headers"]["x-goog-api-key"] == wire.REDACTED, record
        assert PLANTED_KEY not in json.dumps(record), record

    def MQC_EXE_UNI_460007_a_cookie_and_set_cookie_value_never_reach_the_record(
        self,
    ) -> None:
        """A cookie sent and a cookie set, both caught by name.

        Returns:
            None
        """
        recorder = mock_recorder(reply_handler(
            {}, headers=(("set-cookie", f"session={PLANTED_KEY}"),)
        ))
        send_through(recorder, headers={"cookie": f"session={PLANTED_KEY}"})
        record = recorder.take()[0].as_mapping()
        assert record["request_headers"]["cookie"] == wire.REDACTED, record
        assert record["response_headers"]["set-cookie"] == wire.REDACTED, record
        assert PLANTED_KEY not in json.dumps(record), record

    def MQC_EXE_UNI_460008_a_credential_value_under_an_unlisted_header_name_is_replaced(
        self,
    ) -> None:
        """A header the list does not name, caught by its value alone.

        Returns:
            None
        """
        record = self._recorded("x-vendor-session", f"v1.{PLANTED_KEY}",
                                environ={"VENDOR_SESSION_TOKEN": PLANTED_KEY})
        assert record["request_headers"]["x-vendor-session"] == wire.REDACTED, record
        assert PLANTED_KEY not in json.dumps(record), record


class TestMQCLogScrubbing:
    """No credential and no query string reaches the log."""

    def MQC_EXE_UNI_460014_no_credential_reaches_the_log_with_sdks_at_debug(
        self, planted: str, monkeypatch: pytest.MonkeyPatch,
        caplog: pytest.LogCaptureFixture,
    ) -> None:
        """Every engine dispatched with httpx, httpcore and the SDKs logging at DEBUG.

        Args:
            planted (str): The planted credential.
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.
            caplog (pytest.LogCaptureFixture): pytest's log capture.

        Returns:
            None
        """
        assert log_scrubbing.log_scrubbing_installed(), "the harness did not install it"
        caplog.set_level(logging.DEBUG)
        for engine in _ENGINES:
            serve_mock(monkeypatch, reply_handler(WIRE_ENGINES[engine].reply))
            dispatch_minimal(engine)
        assert caplog.records, "nothing logged, so the case asserted nothing"
        assert planted not in caplog.text, "a credential reached the log"

    def MQC_EXE_UNI_460015_a_log_record_with_a_credential_or_query_is_scrubbed(
        self, monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture,
    ) -> None:
        """A record carrying a credential value and a query string is scrubbed when created.

        Args:
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.
            caplog (pytest.LogCaptureFixture): pytest's log capture.

        Returns:
            None
        """
        assert log_scrubbing.log_scrubbing_installed(), "the harness did not install it"
        monkeypatch.setenv("MQC_PROBE_TOKEN", PLANTED_KEY)
        caplog.set_level(logging.INFO)
        logging.getLogger("httpx").info(
            "HTTP Request: GET %s?key=%s token=%s", ECHO_URL, PLANTED_KEY, PLANTED_KEY
        )
        message = caplog.records[-1].getMessage()
        assert PLANTED_KEY not in message and "?key=" not in message, message
        assert ECHO_URL in message, "the scrubbing removed the URL rather than its query"
