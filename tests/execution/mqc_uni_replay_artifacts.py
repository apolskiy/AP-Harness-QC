"""Unit preconditions for a recording or judgement the replay store cannot find or read.

Created: 2026-11-17
Last updated: 2026-11-17

The cases here check ``execution.replay`` and ``execution.dispatch``. A
recording or judgement that is absent, or present and unreadable, raises
``FixtureMissing`` carrying a missing artifact of kind ``recording`` or
``judgement``, its path and what was wrong, its message leading with
``QC_HARNESS_ARTIFACT_MISSING``; a malformed judgement never escapes as a
decoding or key error; and a replay dispatch whose recording is missing
returns the code with the record.

Specified by ``docs/design/tier2_execution.md`` section 7.6.2. A failure here is
**not a model finding**, so the module carries no priority marker, per
``framework-rules.md`` section 3.3."""

