from pathlib import Path
from typing import Any

import pytest

from cmn.case_steps import step
from cmn.missing_artifact import ARTIFACT_MISSING
from execution.dispatch import DispatchPlan, DispatchSession, dispatch_case
from execution.replay import (
    FixtureKey,
    FixtureMissing,
    JudgementKey,
    hash_request,
    load_fixture,
    load_judgement,
)
from tests.execution.replay_artifact_support import (
    CASE_ID,
    JUDGE_MODEL,
    MALFORMED_JUDGEMENTS,
    UNREADABLE_RECORDINGS,
    raised_missing as _raised,
    write_body,
)

pytestmark = pytest.mark.unit

_RECORDING = FixtureKey(CASE_ID, "gemini", 0)
_JUDGEMENT = JudgementKey(
    case_id=CASE_ID, candidate_engine="gemini", judge_engine="gemini", observation_index=0,
)


class TestMQCReplayArtifacts:
    """A recording or judgement replay cannot use names the file it could not use."""

    def MQC_EXE_UNI_113621_an_absent_recording_is_a_missing_artifact_naming_its_path(
        self, tmp_path: Path
    ) -> None:
        """An absent recording raises carrying kind recording, its path and that it is absent.

        Design: ``tier2_execution.md`` section 7.6.2.

        Args:
            tmp_path (Path): An empty fixture root.

        Returns:
            None
        """
        step(1, "load a recording from an empty store")
        raised = _raised(lambda: load_fixture(tmp_path, _RECORDING, hash_request({})))

        step(2, "read the missing artifact it carries")
        path = str(_RECORDING.as_path(tmp_path))
        assert (
            raised.missing.kind == "recording"
            and raised.missing.path == path
            and "is absent" in raised.missing.detail
            and str(raised).startswith(f"{ARTIFACT_MISSING}: recording {path}")
        ), (raised.missing, str(raised))

    def MQC_EXE_UNI_113622_an_unreadable_recording_is_a_missing_artifact_naming_it(
        self, tmp_path: Path
    ) -> None:
        """Each unreadable recording raises carrying its path and that it cannot be read.

        Design: ``tier2_execution.md`` section 7.6.2.

        Args:
            tmp_path (Path): The fixture root.

        Returns:
            None
        """
        step(1, "load each unreadable recording, and collect the wrong outcomes")
        path = _RECORDING.as_path(tmp_path)
        wrong: dict[str, str] = {}
        for name, body in UNREADABLE_RECORDINGS.items():
            write_body(path, body)
            try:
                load_fixture(tmp_path, _RECORDING, hash_request({}))
            except FixtureMissing as raised:
                if not (raised.missing.kind == "recording"
                        and raised.missing.path == str(path)
                        and "cannot be read" in raised.missing.detail
                        and str(raised).startswith(ARTIFACT_MISSING)):
                    wrong[name] = str(raised)
                continue
            except (KeyError, TypeError, ValueError) as other:
                wrong[name] = f"raised {type(other).__name__}: {other}"
                continue
            wrong[name] = "was read as a recording"
        assert not wrong, wrong

