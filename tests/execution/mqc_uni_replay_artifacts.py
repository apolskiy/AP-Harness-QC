    def MQC_EXE_UNI_113625_a_replay_dispatch_carries_the_missing_recording(
        self, tmp_path: Path, minimal_case: Any
    ) -> None:
        """A replay dispatch over an empty store returns the code and the missing recording.

        Design: ``tier2_execution.md`` section 7.6.2.

        Args:
            tmp_path (Path): An empty fixture root.
            minimal_case (Any): A case carrying no optional furniture.

        Returns:
            None
        """
        step(1, "dispatch the case in replay against an empty store, and read the outcome")
        outcome = dispatch_case(
            minimal_case, "gemini", DispatchPlan(mode="replay", fixture_root=tmp_path),
            DispatchSession(),
        )
        expected = FixtureKey(minimal_case.case_id, "gemini", 0).as_path(tmp_path)
        assert (
            outcome.taxonomy_code == ARTIFACT_MISSING
            and outcome.missing_artifact is not None
            and outcome.missing_artifact.kind == "recording"
            and outcome.missing_artifact.path == str(expected)
        ), (outcome.taxonomy_code, outcome.missing_artifact)
