class TestMQCRequestHash:
    """What the hash covers, and what it must not depend on."""

    def MQC_EXE_UNI_113617_a_prompt_hashes_alike_across_line_endings(self) -> None:
        """A top-level prompt hashes identically under LF and CRLF.

        Returns:
            None
        """
        self._hash_ignores_line_endings({"prompt": "line one\nline two"})

    def MQC_EXE_UNI_113618_a_nested_prompt_hashes_alike_across_line_endings(self) -> None:
        """A prompt nested in a message hashes identically under LF and CRLF.

        Returns:
            None
        """
        self._hash_ignores_line_endings({"message": {"prompt": "line one\nline two"}})

    def MQC_EXE_UNI_113619_documents_hash_alike_across_line_endings(self) -> None:
        """A list of documents hashes identically under LF and CRLF.

        Returns:
            None
        """
        self._hash_ignores_line_endings({"documents": ["line one\nline two", "plain"]})

    def _hash_ignores_line_endings(
        self, structure: dict
    ) -> None:
        """The same commit must hash identically on both supported platforms.

        Normalization happens **before** serialization. A carriage return is
        escaped into a two-character sequence by the serializer, so a
        replacement applied afterwards finds no control character and silently
        does nothing, which is the defect this case exists to prevent.

        The parameters cover the top level, a nested mapping and a list,
        because a prompt is as likely to sit in a nested field as at the top.

        Args:
            structure (dict): A request carrying a multi-line value.

        Returns:
            None
        """
        as_text = json.dumps(structure)
        windows_form = json.loads(as_text.replace("\\n", "\\r\\n"))
        assert hash_request(structure) == hash_request(windows_form)

    def MQC_EXE_UNI_113608_different_requests_hash_differently(self) -> None:
        """The counterweight: normalization must not collapse real differences.

        A hash that ignored line endings by ignoring content would satisfy the
        case above and be useless.

        Returns:
            None
        """
        assert hash_request(_REQUEST) != hash_request({**_REQUEST, "prompt": "Summarise it."})
        assert hash_request({"a": 1, "b": 2}) == hash_request({"b": 2, "a": 1})

    def MQC_EXE_UNI_113609_an_unserializable_request_names_the_boundary_it_crossed(self) -> None:
        """A provider object reaching the hash should have stopped at the adapter.

        Returns:
            None
        """
        with pytest.raises(ValueError, match="QC_HARNESS_PARSER_ERROR"):
            hash_request({"client": {1, 2, 3}})


class TestMQCFixtureStore:
    """Locating, verifying and recording observations."""

    def MQC_EXE_UNI_113607_a_fixture_path_never_contains_the_case_id_separator(
        self,
        tmp_path: Path,
    ) -> None:
        """A case identifier carries a colon, which Windows refuses in a path.

        The key stays the tuple and the path splits it, per design section
        7.2.1. This asserts the split rather than the platform, so the case
        fails on Linux too if the split is ever removed.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        path = FixtureKey(_CASE_ID, "gemini", 0).as_path(tmp_path)
        assert "::" not in path.as_posix()
        assert path.parent.name == "MQC_RULE_grounding"
        assert path.parent.parent.name == "MQC_TASK_alpha"

    def MQC_EXE_UNI_113600_replay_reproduces_all_three_recorded_observations(
        self, recorded_run: tuple
    ) -> None:
        """Three recordings replay as three different responses.

        Replaying one response three times would show zero variance and falsely
        imply the model is deterministic, destroying the same-commit
        reliability signal repeat observation exists to produce.

        Args:
            recorded_run (tuple): Root, hash and the recorded responses.

        Returns:
            None
        """
        root, digest, responses = recorded_run
        replayed = [
            load_fixture(root, FixtureKey(_CASE_ID, "gemini", index), digest).response
            for index in range(3)
        ]
        assert replayed == responses
        assert len({json.dumps(entry, sort_keys=True) for entry in replayed}) == 3

    def MQC_EXE_UNI_113601_replay_of_single_response_thrice_is_rejected(
        self,
        tmp_path: Path,
    ) -> None:
        """A run storing one observation cannot reproduce a three-observation run.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        digest = hash_request(_REQUEST)
        record_fixture(tmp_path, FixtureKey(_CASE_ID, "gemini", 0), digest, {"text": "x"}, "m")
        assert stored_observation_count(tmp_path, _CASE_ID, "gemini") == 1
        with pytest.raises(FixtureMissing):
            load_fixture(tmp_path, FixtureKey(_CASE_ID, "gemini", 1), digest)

    def MQC_EXE_UNI_113602_changed_request_hash_reports_fixture_stale(
        self,
        recorded_run: tuple,
    ) -> None:
        """A moved prompt must not replay an answer to the old question.

        Args:
            recorded_run (tuple): Root, hash and the recorded responses.

        Returns:
            None
        """
        root, _, _ = recorded_run
        moved = hash_request({**_REQUEST, "prompt": "A different question entirely."})
        with pytest.raises(FixtureStale, match="QC_HARNESS_FIXTURE_STALE") as caught:
            load_fixture(root, FixtureKey(_CASE_ID, "gemini", 0), moved)
        assert _CASE_ID in str(caught.value)

    def MQC_EXE_UNI_113603_absent_fixture_reports_fixture_missing(self, tmp_path: Path) -> None:
        """A missing fixture skips and names the case rather than failing.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        with pytest.raises(FixtureMissing, match="QC_HARNESS_FIXTURE_MISSING") as caught:
            load_fixture(tmp_path, FixtureKey(_CASE_ID, "gemini", 0), hash_request(_REQUEST))
        assert _CASE_ID in str(caught.value)

    def MQC_EXE_UNI_113604_recorded_fixture_carries_resolved_model_version(
        self, recorded_run: tuple
    ) -> None:
        """A recording knows which model it came from.

        Replaying it against a later model version is then visible in the
        record rather than assumed away.

        Args:
            recorded_run (tuple): Root, hash and the recorded responses.

        Returns:
            None
        """
        root, digest, _ = recorded_run
        assert load_fixture(
            root, FixtureKey(_CASE_ID, "gemini", 0), digest
        ).resolved_model == "gemini-flash-002"

    def MQC_EXE_UNI_113605_divergent_refs_report_staleness_as_a_finding(
        self, recorded_run: tuple
    ) -> None:
        """Under divergent refs the staleness report is the answer, not an error.

        A changed hash says the request composition moved between the two
        checkouts, which is exactly what the diagnostic in `harness_ci_pipeline.md`
        section 6.4 is asking. The store reports and continues rather than
        deciding what the divergence means.

        Args:
            recorded_run (tuple): Root, hash and the recorded responses.

        Returns:
            None
        """
        root, _, _ = recorded_run
        other_checkout = hash_request({**_REQUEST, "prompt": "Composed differently."})
        stale_count = 0
        for index in range(3):
            try:
                load_fixture(root, FixtureKey(_CASE_ID, "gemini", index), other_checkout)
            except FixtureStale:
                stale_count += 1
        assert stale_count == 3

    def MQC_EXE_UNI_113610_an_unreadable_fixture_reports_missing_not_stale(
        self,
        tmp_path: Path,
    ) -> None:
        """A fixture that cannot be parsed carries no hash to compare.

        Reporting it stale would claim more than is known: staleness is a
        statement about a hash, and there is none.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        key = FixtureKey(_CASE_ID, "gemini", 0)
        path = key.as_path(tmp_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("{ truncated", encoding="utf-8")
        with pytest.raises(FixtureMissing):
            load_fixture(tmp_path, key, hash_request(_REQUEST))


class TestMQCDispatchConvertsFixtureFailures:
    """The store raises; dispatch must turn that into a skip."""

    def MQC_EXE_UNI_113611_a_missing_fixture_becomes_a_skip_rather_than_an_error(
        self, tmp_path: Path, minimal_case: Any
    ) -> None:
        """The documented skip never happened, for two years of exceptions.

        `_replay_case` promised "a skip when the fixture is missing or stale,
        both reported, never silently replayed", and caught `FileNotFoundError`
        and `ValueError`. **The store raises neither**: `FixtureMissing` and
        `FixtureStale` inherit from `Exception` alone, so the handler never
        fired and the exception escaped dispatch.

        **A harness event surfacing as an error is what this forbids.**
        `framework-rules.md` section 4 makes a `QC_HARNESS_*` code a skip or
        broken and never a failure, because a red suite reads as a finding
        about the model.

        **The existing cases assert that the store raises, which it does.**
        Nothing asserted that dispatch converts what it raises, and those are
        different claims about different modules.

        Args:
            tmp_path (Path): An empty fixture root.
            minimal_case (Any): A case carrying no optional furniture.

        Returns:
            None
        """
        plan = DispatchPlan(mode="replay", fixture_root=tmp_path)

        outcome = dispatch_case(minimal_case, "gemini", plan, DispatchSession())

        assert outcome.taxonomy_code == "QC_HARNESS_FIXTURE_MISSING", (
            "a missing fixture did not become a skip, so a harness event "
            "reaches the suite as a failure about the model"
        )
        assert outcome.response is None
        assert outcome.mode == "replay"

        # AND THE EXCEPTION DOES NOT ESCAPE, which is the whole defect: the
        # handler named two builtins the store never raises, so the call above
        # used to propagate instead of returning at all.
        assert outcome.attempts == 0
        assert outcome.rate_limit_encounters == 0


class TestMQCStoredRequest:
    """The fixture carries the call that produced it, and checks itself.

    Design: ``tier2_execution.md`` section 7.13.
    """

    def MQC_EXE_UNI_113612_a_recorded_fixture_stores_the_request_it_sent(
        self, tmp_path: Path
    ) -> None:
        """The composed request is written into the fixture, not only hashed.

        **The hash was standing in for the record rather than checking it.**
        Section 7.12 retained the request on the outcome and specified attaching
        it for a failing case, and nothing attached it, so a ticket could cite a
        digest and nothing a provider could read.

        Returns:
            None
        """
        key = FixtureKey(case_id=_CASE_ID, engine="gemini", observation_index=0)
        record_fixture(
            tmp_path, key, hash_request(_REQUEST), {"text": "ok"}, "gemini-flash",
            _REQUEST,
        )

        stored = load_fixture(tmp_path, key, hash_request(_REQUEST))
        assert stored.request == _REQUEST, (
            f"the fixture stored {stored.request!r} rather than the request that "
            f"produced it, so a finding cannot be filed from the fixture alone"
        )

        # AND IT IS ON DISK, not merely reconstructed by the reader.
        written = json.loads(
            key.as_path(tmp_path).read_text(encoding="utf-8")
        )
        assert written["request"] == _REQUEST, written

        # A CALLER HOLDING NO REQUEST RECORDS NO NULL, so a reader can tell a
        # recording made before the field from a call that was empty.
        bare = FixtureKey(case_id=_CASE_ID, engine="gemini", observation_index=1)
        record_fixture(tmp_path, bare, hash_request(_REQUEST), {"text": "ok"}, "gemini-flash")
        assert "request" not in json.loads(
            bare.as_path(tmp_path).read_text(encoding="utf-8")
        ), "an absent request was written as a null a reader cannot interpret"
        assert load_fixture(tmp_path, bare, hash_request(_REQUEST)).request is None

    def MQC_EXE_UNI_113613_a_stored_request_disagreeing_with_its_hash_is_stale(
        self, tmp_path: Path
    ) -> None:
        """A fixture whose two halves disagree is refused, never replayed.

        Design: ``tier2_execution.md`` section 7.13.1.

        Returns:
            None
        """
        key = FixtureKey(case_id=_CASE_ID, engine="gemini", observation_index=0)
        path = record_fixture(
            tmp_path, key, hash_request(_REQUEST), {"text": "ok"}, "gemini-flash",
            _REQUEST,
        )

        # EDITED IN PLACE, leaving the hash naming the request it no longer holds.
        payload = json.loads(path.read_text(encoding="utf-8"))
        payload["request"] = {"prompt": "A different question entirely."}
        path.write_text(
            json.dumps(payload, indent=2, sort_keys=True) + "\n",
            encoding="utf-8", newline="\n",
        )

        with pytest.raises(FixtureStale) as raised:
            load_fixture(tmp_path, key, hash_request(_REQUEST))
        assert "does not hash to the hash recorded beside it" in str(raised.value), (
            f"a fixture disagreeing with its own hash replayed: {raised.value}"
        )

    def MQC_EXE_UNI_113614_a_fixture_carrying_a_credential_shaped_value_is_reported(
        self, tmp_path: Path
    ) -> None:
        """The screen reports a credential by field name and by value shape.

        **This is what makes storing the request safe.** A credential enters at
        client construction and never the payload, and a boundary nothing checks
        lapses the first time an adapter composes a field differently
        (section 7.13.3).

        Returns:
            None
        """
        key = FixtureKey(case_id=_CASE_ID, engine="gemini", observation_index=0)
        record_fixture(
            tmp_path, key, hash_request(_REQUEST), {"text": "ok"}, "gemini-flash",
            _REQUEST,
        )
        assert not fixture_credential_problems(tmp_path), (
            "an ordinary recording was reported, so the screen cannot be trusted "
            "when it reports nothing"
        )

        # BY FIELD NAME.
        named = FixtureKey(case_id=_CASE_ID, engine="gemini", observation_index=1)
        record_fixture(
            tmp_path, named, "hash", {"text": "ok"}, "gemini-flash",
            {"prompt": "hello", "api_key": "redacted-in-this-double"},
        )
        problems = fixture_credential_problems(tmp_path)
        assert any("named like a credential" in entry for entry in problems), problems

        # AND BY VALUE SHAPE, in a field called anything at all.
        valued = FixtureKey(case_id=_CASE_ID, engine="gemini", observation_index=2)
        record_fixture(
            tmp_path, valued, "hash", {"text": "ok"}, "gemini-flash",
            {"prompt": "hello", "note": "sk-ant-not-a-real-key"},
        )
        problems = fixture_credential_problems(tmp_path)
        assert any("shaped like a credential" in entry for entry in problems), problems

        # AND NO REPORT CARRIES THE VALUE, which would disclose it in the
        # report that found it.
        assert not any("sk-ant-not-a-real-key" in entry for entry in problems), (
            "the report quoted the credential it found"
        )

    def MQC_EXE_UNI_113615_a_recording_without_a_request_is_a_gap_not_a_stale_fixture(
        self, tmp_path: Path
    ) -> None:
        """A request-less recording replays, and a gap-filling run still asks.

        **Two questions, not one.** Whether the stored response answers the
        question being asked is settled by the hash and the answer is yes, so
        replay is correct. Whether anything is left to learn is a different
        question, and the request itself is the answer.

        Marking it stale was the first draft of section 7.13.2 and would have
        made every existing recording unreplayable until a paid run finished,
        taking CI red for a schema addition.

        Returns:
            None
        """
        key = FixtureKey(case_id=_CASE_ID, engine="gemini", observation_index=0)
        record_fixture(
            tmp_path, key, hash_request(_REQUEST), {"text": "ok"}, "gemini-flash"
        )

        # IT REPLAYS, because the hash agrees and the response is the answer to
        # the question being asked.
        stored = load_fixture(tmp_path, key, hash_request(_REQUEST))
        assert stored.request is None, stored.request
        assert stored.response == {"text": "ok"}, (
            "a recording made before the field stopped replaying, so a schema "
            "addition made every existing fixture unreplayable"
        )

        # AND IT IS STILL A GAP, so a gap-filling run records the request.
        plan = DispatchPlan(
            mode="live", fixture_root=tmp_path, record=True, fill_gaps=True,
        )
        assert plan.fill_gaps and stored.request is None, (
            "the gap condition cannot be expressed, so the re-record has no "
            "mechanism to select what it must refresh"
        )

    def MQC_EXE_UNI_113616_recording_retires_a_pair_answering_another_request(
        self, tmp_path: Path
    ) -> None:
        """A pair answers one request, so the write retires the rest.

        **Pruned by hand three times in one day.** The previous run escalated
        to five observations, the re-record agreed at three, and observations 3
        and 4 survived answering a question the corpus no longer asks. Nothing
        read them until an escalation did, and then it read two runs as one
        population: one such pair held two observations showing a
        miscomputation the engine no longer makes, under a case that passed.

        Design: ``tier2_execution.md`` section 7.14.

        Returns:
            None
        """
        pair = FixtureKey(case_id=_CASE_ID, engine="gemini", observation_index=0)
        old_request = {"prompt": "The question as it was.", "model": "gemini-flash"}
        old_hash = hash_request(old_request)

        # FIVE OBSERVATIONS OF THE OLD QUESTION, as an escalation leaves.
        for index in range(5):
            record_fixture(
                tmp_path,
                FixtureKey(case_id=_CASE_ID, engine="gemini", observation_index=index),
                old_hash, {"text": f"old {index}"}, "gemini-flash", old_request,
            )
        assert len(list(pair.as_path(tmp_path).parent.glob("*.json"))) == 5

        # THE QUESTION MOVES AND THE RE-RECORD AGREES AT THREE.
        new_request = {"prompt": "The question as it is now.", "model": "gemini-flash"}
        new_hash = hash_request(new_request)
        for index in range(3):
            record_fixture(
                tmp_path,
                FixtureKey(case_id=_CASE_ID, engine="gemini", observation_index=index),
                new_hash, {"text": f"new {index}"}, "gemini-flash", new_request,
            )

        remaining = sorted(
            path.stem for path in pair.as_path(tmp_path).parent.glob("*.json")
        )
        assert remaining == ["0", "1", "2"], (
            f"the pair kept {remaining}, so observations answering the old "
            f"question survive and an escalation would read two runs as one "
            f"population"
        )

        # AND EVERY SURVIVOR ANSWERS THE CURRENT QUESTION.
        for index in range(3):
            stored = load_fixture(
                tmp_path,
                FixtureKey(case_id=_CASE_ID, engine="gemini", observation_index=index),
                new_hash,
            )
            assert stored.request == new_request, stored.request

        # RECORDING THE SAME QUESTION AGAIN RETIRES NOTHING, which is the
        # ordinary case: a pair already answering this request is not stale.
        assert retire_stale_siblings(pair.as_path(tmp_path).parent, new_hash) == 0

        # AN UNREADABLE SIBLING IS LEFT ALONE. `load_fixture` reports it, and
        # removing a file we cannot read would destroy evidence.
        broken = pair.as_path(tmp_path).parent / "7.json"
        broken.write_text("{ not json", encoding="utf-8")
        assert retire_stale_siblings(pair.as_path(tmp_path).parent, new_hash) == 0
        assert broken.is_file()
