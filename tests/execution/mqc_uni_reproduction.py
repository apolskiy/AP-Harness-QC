    def MQC_EXE_UNI_113124_declares_a_reproduction_that_reconstructs_nothing(
        self,
        adapter: ProviderAdapter,
        minimal_case: EvaluationCase,
    ) -> None:
        """Every registered adapter can re-issue a recorded call, verbatim.

        **A ticket must not ask a vendor to trust our composer.** The recorded
        request is this SDK's keyword arguments rather than an HTTP body, so the
        reproduction passes them through and a hand-built ``curl`` is refused:
        for one provider a stored field has no wire form, and the rebuilt call
        would behave differently from the one it claims to reproduce
        (``consumer_ci.md`` section 9.5.3.1).

        **A declaration becomes an obligation here**, the arrangement design
        section 7.8.3 already uses: three adapters once declared
        ``structured_output`` and none implemented it.

        Args:
            adapter (ProviderAdapter): The adapter under check.
            minimal_case (EvaluationCase): A case with no documents and no tools.

        Returns:
            None
        """
        request = adapter.compose_request(minimal_case)
        snippet = reproduction_snippet(adapter.engine_name, request)

        assert snippet, (
            f"{adapter.engine_name} declares no reproduction, so a finding "
            f"filed against it cannot carry a runnable call"
        )

        # THE RECORDED ARGUMENTS REACH IT, which is the whole claim: nothing is
        # reconstructed, so every composed key appears.
        for name in request:
            assert f"{name}=" in snippet, (
                f"{adapter.engine_name} drops {name!r} from its reproduction, "
                f"so the snippet is not the call that was made"
            )

        # AND THE PROMPT ITSELF, so a reader sees what was asked.
        assert minimal_case.task.user_prompt in snippet, (
            f"{adapter.engine_name} omits the prompt from its reproduction"
        )

        # IT NAMES THE VARIABLE TO SET AND CARRIES NO CREDENTIAL. A ticket is
        # published, so a key reaching one is disclosed.
        assert adapter.API_KEY_ENV in snippet, (
            f"{adapter.engine_name} does not say which variable to set, so the "
            f"snippet cannot be run by whoever receives it"
        )
        for line in snippet.splitlines():
            assert not credential_shaped_value(line.strip()), (
                f"{adapter.engine_name} put a credential-shaped value in its "
                f"reproduction, which a ticket would publish"
            )

        # AN UNREGISTERED ENGINE GETS NOTHING RATHER THAN SOMETHING WRONG.
        assert reproduction_snippet("no-such-engine", request) == "", (
            "an unregistered engine produced a reproduction, so a ticket could "
            "carry a call against an adapter that does not exist"
        )

    def MQC_EXE_UNI_113126_a_reproduction_parses_back_to_the_recorded_arguments(
        self,
        adapter: ProviderAdapter,
        minimal_case: EvaluationCase,
    ) -> None:
        """The snippet is Python whose arguments evaluate to the recorded ones.

        A recorded boolean and a recorded null are added to the composed
        request, because gemini records ``"disable": true`` and a JSON rendering
        of it is not Python. Each keyword argument of the call is evaluated as
        a literal and compared with the recording.

        Design: ``consumer_ci.md`` section 9.5.3.1.

        Args:
            adapter (ProviderAdapter): The adapter under check.
            minimal_case (EvaluationCase): A case with no documents and no tools.

        Returns:
            None
        """
        request = {
            **adapter.compose_request(minimal_case),
            "probe_literals": {"on": True, "off": False, "unset": None},
        }
        snippet = reproduction_snippet(adapter.engine_name, request)

        try:
            tree = ast.parse(snippet)
        except SyntaxError as error:
            pytest.fail(f"{adapter.engine_name}'s reproduction is not Python: {error}")
        # THE CALL ASSIGNED TO `response`, not the client's construction,
        # which takes keyword arguments of its own on an engine with a base URL.
        calls = [
            node.value for node in ast.walk(tree)
            if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call)
            and any(isinstance(target, ast.Name) and target.id == "response"
                    for target in node.targets)
        ]
        assert len(calls) == 1, (
            f"{adapter.engine_name}'s reproduction assigns {len(calls)} call(s) "
            f"to response, so which one re-issues the recording is ambiguous"
        )
        recovered: dict[str, Any] = {}
        for keyword in calls[0].keywords:
            try:
                recovered[str(keyword.arg)] = ast.literal_eval(keyword.value)
            except ValueError:
                pytest.fail(
                    f"{adapter.engine_name}'s argument {keyword.arg!r} is not a "
                    f"Python literal: {ast.unparse(keyword.value)[:120]}"
                )

        assert recovered == request, (
            f"{adapter.engine_name}'s reproduction does not evaluate to the "
            f"recorded arguments, so it re-issues a different call"
        )

    def MQC_EXE_UNI_113127_a_wire_protocol_engine_also_reproduces_as_curl(
        self,
        adapter: ProviderAdapter,
        minimal_case: EvaluationCase,
    ) -> None:
        """An OpenAI-protocol engine offers a ``curl``; the others offer none.

        The ``curl`` posts the recorded request, unchanged, to the engine's own
        endpoint, naming its credential variable. The body is a quoted heredoc,
        and the prompt here carries an apostrophe to show it survives. An
        engine whose recording is not the wire body returns an empty string.

        Design: ``consumer_ci.md`` section 9.5.3.1.

        Args:
            adapter (ProviderAdapter): The adapter under check.
            minimal_case (EvaluationCase): A case with no documents and no tools.

        Returns:
            None
        """
        request = {
            **adapter.compose_request(minimal_case),
            "probe_text": "the source doesn't support it",
        }
        command = reproduction_curl(adapter.engine_name, request)

        if not isinstance(adapter, OpenAICompatibleAdapter):
            assert command == "", (
                f"{adapter.engine_name} offers a curl although its recording is "
                f"not the wire body, so the call it makes is not the one recorded"
            )
            return

        endpoint = (adapter.BASE_URL or "https://api.openai.com/v1") + "/chat/completions"
        assert command.startswith(f"curl {endpoint} "), (
            f"{adapter.engine_name}'s curl does not post to {endpoint}"
        )
        assert f'"Authorization: Bearer ${adapter.API_KEY_ENV}"' in command, (
            f"{adapter.engine_name}'s curl does not name {adapter.API_KEY_ENV}"
        )
        assert "<<'JSON'\n" in command, (
            f"{adapter.engine_name}'s curl body is not in a quoted heredoc, so "
            f"the shell expands or ends it inside a prompt"
        )
        opening, _, rest = command.partition("<<'JSON'\n")
        body, _, closing = rest.partition("\nJSON")
        assert opening and closing.strip() == "", (
            f"{adapter.engine_name}'s curl does not carry its body in a quoted "
            f"heredoc, so an apostrophe in a prompt ends the shell's quoting"
        )
        assert json.loads(body) == request, (
            f"{adapter.engine_name}'s curl body is not the recorded request"
        )
        for line in command.splitlines():
            assert not credential_shaped_value(line.strip()), (
                f"{adapter.engine_name} put a credential-shaped value in its curl"
            )

    def MQC_EXE_UNI_113129_a_client_on_another_base_url_is_given_its_own_key(
        self,
        adapter: ProviderAdapter,
        monkeypatch: pytest.MonkeyPatch,
        tmp_path: Path,
    ) -> None:
        """An OpenAI-protocol snippet builds a client holding its engine's key.

        The setup lines run with only the engine's own variable set, and the
        client they build carries that value and the engine's endpoint. The
        OpenAI client reads ``OPENAI_API_KEY`` alone, so an engine on another
        base URL must pass its variable by name.

        Design: ``consumer_ci.md`` section 9.5.3.1.

        Args:
            adapter (ProviderAdapter): The adapter under check.
            monkeypatch (pytest.MonkeyPatch): Sets and clears the variables.
            tmp_path (Path): Where the setup lines are written to be run.

        Returns:
            None
        """
        if not isinstance(adapter, OpenAICompatibleAdapter):
            assert adapter.engine_name, "an adapter with no engine name was registered"
            return
        monkeypatch.delenv("OPENAI_API_KEY", raising=False)
        monkeypatch.setenv(adapter.API_KEY_ENV, "probe-not-a-credential")

        setup = tmp_path / "setup.py"
        setup.write_text("\n".join(adapter.reproduction_setup()) + "\n", encoding="utf-8")
        client = runpy.run_path(str(setup))["client"]

        assert client.api_key == "probe-not-a-credential", (
            f"{adapter.engine_name}'s snippet builds a client that does not read "
            f"{adapter.API_KEY_ENV}, so running it is refused for the wrong key"
        )
        assert str(client.base_url).rstrip("/") == (
            adapter.BASE_URL or "https://api.openai.com/v1"
        ).rstrip("/"), f"{adapter.engine_name}'s snippet calls another endpoint"
