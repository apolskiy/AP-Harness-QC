    def _reproduction_parses_back_to_recorded_arguments(
        self,
        engine: str,
        minimal_case: EvaluationCase,
    ) -> None:
        """The snippet is Python whose arguments evaluate to the recorded ones.

        A recorded boolean and a recorded null are added to the composed
        request, because gemini records ``"disable": true`` and a JSON rendering
        of it is not Python. Each keyword argument of the call is evaluated as
        a literal and compared with the recording.

        Design: ``consumer_ci.md`` section 9.5.3.1.

        Args:
            engine (str): The registered engine whose adapter is checked.
            minimal_case (EvaluationCase): A case with no documents and no tools.

        Returns:
            None
        """
        adapter = adapter_named(engine)
        request = {
            **adapter.compose_request(minimal_case),
            "probe_literals": {"on": True, "off": False, "unset": None},
        }
        snippet = reproduction_snippet(adapter.engine_name, request)

        try:
            tree = ast.parse(snippet)
        except SyntaxError as error:
            pytest.fail(f"{adapter.engine_name}'s reproduction is not Python: {error}")
        # THE CALL ASSIGNED TO `response`, not the client's construction,
        # which takes keyword arguments of its own on an engine with a base URL.
        calls = [
            node.value for node in ast.walk(tree)
            if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call)
            and any(isinstance(target, ast.Name) and target.id == "response"
                    for target in node.targets)
        ]
        assert len(calls) == 1, (
            f"{adapter.engine_name}'s reproduction assigns {len(calls)} call(s) "
            f"to response, so which one re-issues the recording is ambiguous"
        )
        recovered: dict[str, Any] = {}
        for keyword in calls[0].keywords:
            try:
                recovered[str(keyword.arg)] = ast.literal_eval(keyword.value)
            except ValueError:
                pytest.fail(
                    f"{adapter.engine_name}'s argument {keyword.arg!r} is not a "
                    f"Python literal: {ast.unparse(keyword.value)[:120]}"
                )

        assert recovered == request, (
            f"{adapter.engine_name}'s reproduction does not evaluate to the "
            f"recorded arguments, so it re-issues a different call"
        )


