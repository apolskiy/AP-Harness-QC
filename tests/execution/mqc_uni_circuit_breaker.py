"""Unit cases for when the candidate's failures end the job.

Created: 2026-11-21
Last updated: 2026-11-21

This file contains ``TestMQCCircuitBreaker``, cases on
:func:`execution.dispatch.dispatch_case` and ``DispatchSession``. They check
that the circuit breaker counts consecutive failures rather than cumulative
ones, that one code on three cases running, five failures running of any code,
or an auth error ends the job, and that one non-retryable code skips only its
own case. They check that a budget stop and a missing fixture neither count nor
end it, and that once the job has ended no case is dispatched, each names the
failure that ended it, and the run exits 3.

**The breaker bounds what a failing provider costs.** A request of unknown
cost is not sent to confirm what three have already shown. Moved out of
``mqc_uni_dispatch.py`` on 2026-11-21, when the job end took that module past
its 900-line runway (``code-style.md`` section 5.1); the clock, the script and
the plan builder both use are in ``dispatch_support.py``.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.

Specified by ``docs/design/tier2_execution.md`` sections 8.3, 8.3.1, 8.3.2 and
8.3.4.
"""

