import pytest

from tests.execution.judge_breaker_doubles import (
    AWARDED,
    JudgeRequestDouble,
    ScriptedJudge,
    busy,
    rejected,
    scripted_channel,
)
from tests.execution.provider_doubles import gemini_judgement

pytestmark = pytest.mark.unit


class TestMQCJudgeBreaker:
    """A judge that will not answer stops being asked, for the rest of the run."""

    def MQC_EXE_UNI_113306_a_judge_rejecting_the_request_is_not_asked_again(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A rejected judge request stops the channel, which then sends nothing.

        Design: ``tier2_execution.md`` section 8.3.3.

        Args:
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.

        Returns:
            None
        """
        provider = ScriptedJudge([rejected(), gemini_judgement(AWARDED)])
        channel = scripted_channel(monkeypatch, provider)

        with pytest.raises(ValueError, match="QC_HARNESS_REQUEST_REJECTED"):
            channel.invoke(JudgeRequestDouble())
        assert channel.stopped == "QC_HARNESS_REQUEST_REJECTED", (
            "a judge that rejected the request is still reported as answering"
        )

        with pytest.raises(ValueError, match="QC_HARNESS_REQUEST_REJECTED"):
            channel.invoke(JudgeRequestDouble())
        assert provider.sent == 1, (
            f"the channel sent {provider.sent} requests to a judge that rejected "
            f"the first, so every judged observation repeats the rejection"
        )

    def MQC_EXE_UNI_113307_a_judge_failing_transiently_stops_at_the_breaker_threshold(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """Retryable judge failures stop the channel at the threshold, and a reply resets them.

        Design: ``tier2_execution.md`` sections 8.3 and 8.3.3.

        Args:
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.

        Returns:
            None
        """
        provider = ScriptedJudge(
            [busy()] * 4 + [gemini_judgement(AWARDED)] + [busy()] * 5
        )
        channel = scripted_channel(monkeypatch, provider)

        for _attempt in range(4):
            with pytest.raises(ValueError, match="QC_HARNESS_PROVIDER_UNAVAILABLE"):
                channel.invoke(JudgeRequestDouble())
        assert channel.stopped is None, "four transient failures stopped the judge"

        assert channel.invoke(JudgeRequestDouble()) == AWARDED, "a reply was not returned"

        for _attempt in range(4):
            with pytest.raises(ValueError, match="QC_HARNESS_PROVIDER_UNAVAILABLE"):
                channel.invoke(JudgeRequestDouble())
        assert channel.stopped is None, (
            "a reply did not reset the count, so failures either side of it summed"
        )

        with pytest.raises(ValueError, match="QC_HARNESS_PROVIDER_UNAVAILABLE"):
            channel.invoke(JudgeRequestDouble())
        assert channel.stopped == "QC_HARNESS_PROVIDER_UNAVAILABLE", (
            "five consecutive transient failures did not stop the judge"
        )
        sent = provider.sent
        with pytest.raises(ValueError, match="QC_HARNESS_PROVIDER_UNAVAILABLE"):
            channel.invoke(JudgeRequestDouble())
        assert provider.sent == sent, "a stopped judge was sent another request"
