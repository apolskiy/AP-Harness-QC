import logging

import pytest

from tests.execution.judge_breaker_doubles import (
    AWARDED,
    MODEL,
    JudgeRequestDouble,
    ScriptedJudge,
    busy,
    scripted_channel,
)
from tests.execution.provider_doubles import gemini_judgement

pytestmark = pytest.mark.unit

_PREFIX = "judge usage:"


class TestMQCJudgeUsage:
    """Each live judgement logs the tokens it billed."""

    def MQC_EXE_UNI_113308_each_live_judgement_logs_the_tokens_it_billed(
        self, monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture
    ) -> None:
        """A returned judgement logs one usage line; a call that raised logs none.

        Design: ``tier2_execution.md`` section 7.7.3.

        Args:
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.
            caplog (pytest.LogCaptureFixture): pytest's log capture.

        Returns:
            None
        """
        provider = ScriptedJudge(
            [gemini_judgement(AWARDED), gemini_judgement(AWARDED), busy()]
        )
        channel = scripted_channel(monkeypatch, provider)
        caplog.set_level(logging.INFO, logger="execution.judge_channel")
        per_call = channel.adapter.read_usage(gemini_judgement(AWARDED))
        assert per_call.input_tokens > 0 and per_call.output_tokens > 0, (
            f"the double reported no tokens, so the line could not be checked: {per_call}"
        )

        # TWO CALLS, so a line carrying the running total differs from one
        # carrying the call's own counts.
        channel.invoke(JudgeRequestDouble())
        channel.invoke(JudgeRequestDouble())
        logged = [
            record.getMessage() for record in caplog.records
            if record.getMessage().startswith(_PREFIX)
        ]
        expected = (
            f"{_PREFIX} engine=gemini model={MODEL} case={JudgeRequestDouble.case_id} "
            f"observation=0 input={per_call.input_tokens} output={per_call.output_tokens} "
            f"thinking={per_call.thinking_tokens} cached={per_call.cached_input_tokens}"
        )
        assert logged == [expected, expected], logged

        caplog.clear()
        with pytest.raises(ValueError, match="QC_HARNESS_PROVIDER_UNAVAILABLE"):
            channel.invoke(JudgeRequestDouble())
        raised = [
            record.getMessage() for record in caplog.records
            if record.getMessage().startswith(_PREFIX)
        ]
        assert not raised, f"a judgement that raised logged usage: {raised}"
