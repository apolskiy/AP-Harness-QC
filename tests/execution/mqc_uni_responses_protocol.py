"""Unit cases for the ``openai`` engine on OpenAI's Responses protocol.

Created: 2026-11-06
Last updated: 2026-11-06

Its cases check ``OpenAIAdapter`` in :mod:`execution.adapters.openai`, which
speaks the Responses protocol through
:class:`~execution.adapters.openai_responses.OpenAIResponsesAdapter`. They
cover how a request carries the system instruction, documents and tools, that
no request asks the provider to store it, how text, refusal parts and function
calls are read from the ``output`` items, how an incomplete reply maps to a
finish reason, the token counts, and how a judgement is constrained.

The conformance battery checks the same adapter against the shared contract;
these cases check what the protocol does that Chat Completions does not, each
against the Responses doubles in ``tests/execution/responses_doubles.py``.

Inventoried in ``docs/design/tier2_execution.md`` section 10.1.3 and specified
by section 3.5.4.

A failure here is **not a model finding**, so the module carries no priority marker.
"""

