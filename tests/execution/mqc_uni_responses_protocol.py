from typing import Any, Final

import pytest

from execution.adapters.openai import OpenAIAdapter
from ingestion.schemas import EvaluationCase
from tests.execution.responses_doubles import responses_response

pytestmark = pytest.mark.unit

_CASE_ID: Final[str] = "MQC_TASK_alpha::MQC_RULE_grounding"

_REPLY_SCHEMA: Final[dict[str, Any]] = {
    "type": "object",
    "properties": {"score": {"type": "integer"}},
    "required": ["score"],
    "additionalProperties": False,
}


class TestMQCResponsesProtocol:
    """What the Responses protocol does that Chat Completions does not."""

    def MQC_EXE_UNI_113029_openai_sends_the_system_instruction_as_an_input_role(
        self, furnished_case: EvaluationCase, minimal_case: EvaluationCase
    ) -> None:
        """The instruction leads the input, and the documents and prompt follow as user turns.

        Args:
            furnished_case (EvaluationCase): A case carrying a system
                instruction and a document.
            minimal_case (EvaluationCase): A case carrying neither.

        Returns:
            None
        """
        adapter = OpenAIAdapter()
        request = adapter.compose_request(furnished_case)
        assert "messages" not in request, "a Chat Completions field reached a Responses request"
        entries = request["input"]
        assert entries[0] == {
            "role": "system", "content": furnished_case.task.system_instruction
        }
        assert furnished_case.task.context_documents[0].content in entries[1]["content"]
        assert entries[1]["role"] == "user"
        assert entries[-1] == {"role": "user", "content": furnished_case.task.user_prompt}
        assert all(
            entry["role"] != "system"
            for entry in adapter.compose_request(minimal_case)["input"]
        )

    def MQC_EXE_UNI_113030_openai_offers_a_tool_flat_and_unstrict(
        self, furnished_case: EvaluationCase
    ) -> None:
        """A tool is one flat definition, offered exactly as the case declares it.

        Args:
            furnished_case (EvaluationCase): A case carrying a tool.

        Returns:
            None
        """
        tool = furnished_case.task.available_tools[0]
        offered = OpenAIAdapter().compose_request(furnished_case)["tools"]
        definition = offered[0]
        assert "function" not in definition, "the tool is nested as on Chat Completions"
        assert (definition["type"], definition["name"]) == ("function", tool.tool_name)
        assert definition["description"] == tool.description
        assert definition["parameters"] == tool.parameters_schema
        assert definition["strict"] is False
        assert len(definition) == 5, f"unexpected fields: {sorted(definition)}"

    def MQC_EXE_UNI_113031_openai_a_response_with_no_function_call_yields_an_empty_list(
        self,
    ) -> None:
        """A reply carrying a reasoning item and a message, and no call, captures nothing.

        Returns:
            None
        """
        response = responses_response()
        assert not [item for item in response.output if item.type == "function_call"]
        adapter = OpenAIAdapter()
        assert adapter.extract_tool_calls(response) == []
        assert adapter.normalize_response(response, _CASE_ID).finish_reason == "stop"

    def MQC_EXE_UNI_113032_openai_reads_text_and_refusal_parts_in_order(
        self,
    ) -> None:
        """Every text and refusal part is kept, in order, and the reasoning item adds nothing.

        Returns:
            None
        """
        response = responses_response(
            parts=[
                ("output_text", "The posting asks for Python. "),
                ("refusal", "I cannot share the salary band. "),
                ("output_text", "It asks for five years."),
            ]
        )
        normalized = OpenAIAdapter().normalize_response(response, _CASE_ID)
        assert normalized.text == (
            "The posting asks for Python. I cannot share the salary band. "
            "It asks for five years."
        )

    def MQC_EXE_UNI_113033_openai_maps_an_incomplete_response_to_its_finish_reason(
        self,
    ) -> None:
        """The status and its reason decide the finish reason, and a call decides a completed one.

        Returns:
            None
        """
        adapter = OpenAIAdapter()
        expected = {
            "max_output_tokens": "length",
            "content_filter": "content_filter",
            "a_reason_nobody_documented": "unknown",
        }
        for reason, canonical in expected.items():
            response = responses_response(incomplete_reason=reason)
            assert adapter.normalize_response(response, _CASE_ID).finish_reason == canonical, (
                f"an incomplete reply for {reason} did not map to {canonical}"
            )
        called = responses_response(tool_calls=[("search", {"query": "x"})])
        assert adapter.normalize_response(called, _CASE_ID).finish_reason == "tool_calls"

    def MQC_EXE_UNI_113034_openai_reads_token_counts_under_the_responses_names(
        self,
    ) -> None:
        """Input, output, reasoning and cached input are read from this protocol's fields.

        Returns:
            None
        """
        usage = responses_response().usage
        counted = OpenAIAdapter().read_usage(responses_response())
        assert counted.input_tokens == usage.input_tokens
        assert counted.output_tokens == usage.output_tokens
        assert counted.thinking_tokens == usage.output_tokens_details.reasoning_tokens
        assert counted.cached_input_tokens == usage.input_tokens_details.cached_tokens

    def MQC_EXE_UNI_113035_openai_constrains_a_judgement_through_the_text_format(
        self,
    ) -> None:
        """The reply schema travels in ``text.format``, strict, with no tool offered.

        Returns:
            None
        """
        request = OpenAIAdapter().compose_judgement("Score this.", _REPLY_SCHEMA)
        assert "response_format" not in request
        assert "tools" not in request
        assert request["input"] == [{"role": "user", "content": "Score this."}]
        assert request["text"] == {
            "format": {
                "type": "json_schema",
                "name": "mqc_judgement",
                "strict": True,
                "schema": _REPLY_SCHEMA,
            }
        }

    def MQC_EXE_UNI_113036_openai_asks_the_provider_not_to_store_the_request(
        self, minimal_case: EvaluationCase
    ) -> None:
        """A candidate request and a judgement each set ``store`` false.

        Args:
            minimal_case (EvaluationCase): A case carrying only a prompt.

        Returns:
            None
        """
        adapter = OpenAIAdapter()
        assert adapter.compose_request(minimal_case).get("store") is False, (
            "the provider keeps the model's answer by default unless told not to"
        )
        assert adapter.compose_judgement("Score this.", _REPLY_SCHEMA).get("store") is False
