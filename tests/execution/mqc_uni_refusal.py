"""Unit cases for a request the provider refused, as against a rejected credential.

Created: 2026-10-12
Last updated: 2026-10-21

Its cases check :mod:`execution.dispatch` and the status mapping in
:mod:`cmn.registries`. A 403 ends its own case and not the run, while a 401
still maps to the auth code. Refusals in a run that otherwise answered do not
trip the circuit breaker, and :func:`attributed_refusal` records a benign task's
refusal in such a run as the model's over-refusal.

Specified by ``docs/design/tier2_execution.md`` section 10.1.

**Split from `mqc_uni_conformance.py` on 2026-10-12**, which this subject took
to 936 lines against the nine-hundred-line runway ceiling. That module is about
what every adapter must implement; this one is about one status and who a
refusal belongs to.

**One refused case ended a recording run.** grok returned 403 to a
requirement-matching task about years of experience, both adapters mapped it
alongside 401, and the breaker aborts on the auth code without counting. The
message said the credential had been rejected while the balance was intact.

**And the refusal itself is a finding.** An entitlement the account lacks
refuses every request; this refused one case while 115 others were answered on
the same key and model, so the run is the control and the attribution is
evidence rather than inference.

Design: ``tier2_execution.md`` section 8.6.7.

A failure here is **not a model finding**, so the module carries no priority
marker, per ``framework-rules.md`` section 3.3.
"""

