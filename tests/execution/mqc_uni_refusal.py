from dataclasses import replace
from types import SimpleNamespace

import pytest

from cmn.registries import (
    code_criticality,
    is_registered_harness_code,
    taxonomy_for_status,
)
from execution.adapters.registry import registered_adapters
from execution.dispatch import (
    CircuitBreakerTripped,
    DispatchOutcome,
    DispatchSession,
    attributed_refusal,
)

pytestmark = pytest.mark.unit


class TestMQCRefusedRequest:
    """403 is about the request; 401 is about the caller.

    Design: ``tier2_execution.md`` section 8.6.7.
    """

    def MQC_EXE_UNI_113125_a_refused_request_ends_the_case_not_the_run(self) -> None:
        """A 403 takes its own code and does not abort the run.

        **One refused case ended a recording run.** grok returned 403 carrying
        "I'm sorry, I can't help with that request" to a requirement-matching
        task, both adapters mapped it alongside 401, and section 8.3 aborts on
        the auth code without counting. The message said the credential had
        been rejected while the balance was intact.

        **The remedy follows HTTP, not a string match.** 401 says the caller is
        not who it claims, so every case fails identically and aborting saves
        quota. 403 says this request is not permitted, and in that run 66 later
        requests succeeded.

        Returns:
            None
        """
        # THE TWO STATUSES ARE NO LONGER ONE CODE.
        assert taxonomy_for_status(401) == "QC_HARNESS_AUTH_ERROR", (
            taxonomy_for_status(401)
        )
        assert taxonomy_for_status(403) == "QC_HARNESS_REQUEST_REFUSED", (
            f"403 maps to {taxonomy_for_status(403)}, so a refused request "
            f"still reads as a rejected credential"
        )

        # AND THE NEW CODE IS REGISTERED, or an adapter returning it is refused.
        assert is_registered_harness_code("QC_HARNESS_REQUEST_REFUSED"), (
            "the code is unregistered, so an adapter returning it is refused "
            "and the mapping above cannot be used"
        )

        # EVERY ADAPTER TRANSLATES ITS OWN 403 TO IT, rather than to the auth
        # code. Parametrized over the registry so a new adapter is enrolled.
        for adapter_class in registered_adapters():
            mapped = {
                code for _, code in getattr(adapter_class, "ERROR_MAP", ())
            }
            if not mapped:
                continue
            assert "QC_HARNESS_AUTH_ERROR" not in mapped or (
                "QC_HARNESS_REQUEST_REFUSED" in mapped
            ), (
                f"{adapter_class.ENGINE_NAME} maps an auth code and no refusal "
                f"code, so its 403 still aborts the run"
            )

        # THE RUN SURVIVES ONE. An auth error aborts without counting; a
        # refusal counts as an ordinary failure toward the breaker.
        session = DispatchSession(breaker_threshold=3)
        refused = DispatchOutcome(
            case_id="MQC_TASK_a::MQC_RULE_a", engine="grok", mode="live",
            duration_ms=1, duration_kind="measured", attempts=1,
            rate_limit_encounters=0, response=None,
            taxonomy_code="QC_HARNESS_REQUEST_REFUSED",
        )
        session.note_outcome(refused)
        assert session.consecutive_failures == 1, session.consecutive_failures

        # AND AN AUTH ERROR STILL ABORTS, because that reading was correct.
        with pytest.raises(CircuitBreakerTripped):
            DispatchSession(breaker_threshold=99).note_outcome(
                replace(refused, taxonomy_code="QC_HARNESS_AUTH_ERROR")
            )

        # A REFUSED REASONABLE REQUEST IS A MODEL BUG, attributed on what the
        # run proved rather than on a sentence written for a human.
        benign = SimpleNamespace(
            case_id="MQC_TASK_b::MQC_RULE_b",
            task=SimpleNamespace(contains_adversarial_content=False),
        )
        adversarial = SimpleNamespace(
            case_id="MQC_TASK_c::MQC_RULE_c",
            task=SimpleNamespace(contains_adversarial_content=True),
        )
        answered = SimpleNamespace(measured_outcomes=66)
        silent = SimpleNamespace(measured_outcomes=0)
        refusal = "QC_HARNESS_REQUEST_REFUSED"

        assert attributed_refusal(benign, answered, refusal) == "QC_LLM_OVER_REFUSAL", (
            "a benign task refused in a run that answered 66 others stayed "
            "ours, so an over-refusal is discarded as our own infrastructure"
        )
        assert attributed_refusal(benign, silent, refusal) == refusal, (
            "a refusal in a run that measured nothing was blamed on the model, "
            "when an entitlement the account lacks refuses every request"
        )
        assert attributed_refusal(adversarial, answered, refusal) == refusal, (
            "declining an adversarial payload was recorded as a quality "
            "failure, which is the opposite of what it is"
        )

        # AND NOTHING ELSE IS RECLASSIFIED.
        for other in ("QC_HARNESS_AUTH_ERROR", "QC_HARNESS_RATE_LIMIT"):
            assert attributed_refusal(benign, answered, other) == other, other

        # THE RANK IS DECLARED, or it would sort below every ranked code and
        # classify a finding as the least serious thing that happened.
        assert code_criticality("QC_LLM_OVER_REFUSAL") < code_criticality(
            "QC_LLM_INCONSISTENT"
        ), "an over-refusal ranks no higher than disagreeing with itself"

    def MQC_EXE_UNI_113128_refusals_in_a_run_that_answered_do_not_trip_the_breaker(
        self,
    ) -> None:
        """Once the run has measured an outcome, a refusal resets the streak.

        Five observations of one refused case, in a run that had answered other
        requests, tripped the breaker and errored the case. A refusal in a run
        that has measured nothing still counts, which ``113125`` asserts.

        Design: ``tier2_execution.md`` section 8.6.7.

        Returns:
            None
        """
        refused = DispatchOutcome(
            case_id="MQC_TASK_a::MQC_RULE_a", engine="grok", mode="live",
            duration_ms=1, duration_kind="measured", attempts=1,
            rate_limit_encounters=0, response=None,
            taxonomy_code="QC_HARNESS_REQUEST_REFUSED",
        )
        session = DispatchSession(breaker_threshold=3)
        session.measured_outcomes = 122
        # BOTH ATTRIBUTIONS, because the breaker sees the code after
        # `attributed_refusal`: a benign task's refusal arrives as the model's.
        for code in ("QC_LLM_OVER_REFUSAL",) * 5 + ("QC_HARNESS_REQUEST_REFUSED",) * 5:
            session.note_outcome(replace(refused, taxonomy_code=code))
        assert session.consecutive_failures == 0, (
            f"{session.consecutive_failures} refusals counted toward the breaker in a "
            f"run that had answered, so one refused case ends the run"
        )

        # A TRANSPORT FAILURE STILL COUNTS, answered run or not.
        for _ in range(2):
            session.note_outcome(replace(refused, taxonomy_code="QC_HARNESS_PROVIDER_UNAVAILABLE"))
        with pytest.raises(CircuitBreakerTripped):
            session.note_outcome(replace(refused, taxonomy_code="QC_HARNESS_PROVIDER_UNAVAILABLE"))
